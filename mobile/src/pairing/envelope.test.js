// The delivery envelope, against the command that really sealed one (mobile
// plan, Task P6.8; the pairing plan's §7.2 and §8).
//
// **Why this test exists at all.** `crypto.test.js` proves the two primitives
// are AES-256-GCM and HKDF-SHA-256. It cannot prove that this app derives the
// *same key* the CLI does, builds the *same AAD*, splits the envelope at the
// same offsets, or checks the version byte in the same place -- and each of
// those is a way to be wrong that no standard vector would catch, because a
// wrong AAD still verifies a tag that was computed over the same wrong AAD.
// The only test that settles it is one that opens bytes `internal/budget/token`
// sealed, which is what `testdata/envelope.vector.json` is:
//
//   * `pairing_uid`, `phone_secret` and `phone_public` are the pairing's;
//   * `envelope` is `token.SealDelivery`'s output, verbatim;
//   * `payload` is what `token.Delivery.MarshalPayload` wrote inside it;
//   * `code` is `token.Fingerprint` of `phone_public`.
//
// The vector was generated by a throwaway Go program against the merged
// package, and the plaintext it holds is `internal/budget/token/testdata/
// delivery.golden.json`'s values, so the two repositories' fixtures agree on
// one document. It is a fixture and not a credential: every value is a
// repeated byte, and there is no secret-shaped literal in it.
//
// **`node:crypto` is the test's own implementation**, as in `crypto.test.js`:
// X25519 for the key agreement, and OpenSSL for sealing the cases the vector
// does not cover (another uid, another key, a tampered byte). The app's X25519
// is a dependency injected as a port and never `node:crypto`.

import assert from 'node:assert/strict';
import { createCipheriv, createPrivateKey, createPublicKey, diffieHellman, hkdfSync } from 'node:crypto';
import { readFileSync } from 'node:fs';
import test from 'node:test';

import { decodeBase64url, encodeBase64url } from './base64url.js';
import { readDelivery } from './delivery.js';
import {
  DELIVERY_INFO,
  DELIVERY_VERSION,
  ENVELOPE_CODES,
  decodeEnvelope,
  deliveryAAD,
  openDelivery,
  readDeliveryNode,
} from './envelope.js';
import { fingerprint } from './key.js';
import { readScannedPayload } from './payload.js';

const VECTOR = JSON.parse(
  readFileSync(new URL('./testdata/envelope.vector.json', import.meta.url), 'utf8'),
);

/** A raw 32-byte X25519 secret or public key as Node's own key object. The two
 * prefixes are DER's, and taking the last 32 bytes back out is what makes this
 * port a *raw* key agreement rather than a file format. */
const PKCS8 = '302e020100300506032b656e04220420';
const SPKI = '302a300506032b656e032100';

function privateKey(secret) {
  return createPrivateKey({ key: Buffer.from(PKCS8 + hex(secret), 'hex'), format: 'der', type: 'pkcs8' });
}

function publicKey(bytes) {
  return createPublicKey({ key: Buffer.from(SPKI + hex(bytes), 'hex'), format: 'der', type: 'spki' });
}

/** The port `openDelivery` takes, backed by OpenSSL: the same two calls the
 * app's dependency offers, with `node:crypto` behind them. */
const nodeX25519 = Object.freeze({
  getPublicKey(secret) {
    const der = createPublicKey(privateKey(secret)).export({ format: 'der', type: 'spki' });
    return new Uint8Array(der.subarray(der.length - 32));
  },
  getSharedSecret(secret, peer) {
    return new Uint8Array(diffieHellman({ privateKey: privateKey(secret), publicKey: publicKey(peer) }));
  },
});

/** The same port, except that the agreement is whatever `shared` says: the
 * shape a dependency that answered a low-order point's all-zero secret has. */
function portAnswering(shared) {
  return Object.freeze({
    getPublicKey: nodeX25519.getPublicKey,
    getSharedSecret: () => Uint8Array.from(shared),
  });
}

function hex(bytes) {
  return [...bytes].map((byte) => byte.toString(16).padStart(2, '0')).join('');
}

/** Bytes from the one spelling the CLI writes. */
function unbase64url(text, bytes = 32) {
  const decoded = decodeBase64url(text, bytes);
  assert.equal(decoded.ok, true, `the fixture's ${text.slice(0, 8)}… is not base64url`);
  return decoded.bytes;
}

function filler(seed, count) {
  const out = new Uint8Array(count);
  for (let i = 0; i < count; i += 1) out[i] = (seed * 31 + i * 17 + (i >> 3)) & 0xff;
  return out;
}

/**
 * Seal a delivery with OpenSSL, in §8's layout and this module's AAD: the
 * other direction of the vector, and the only way to build a *valid* envelope
 * for another uid or another key -- a tampered one is refused for the right
 * reason only if the untampered one would have opened.
 *
 * The AAD is `envelope.js`'s own `deliveryAAD` on purpose. That it is not a
 * second spelling is what the vector proves: the envelope above was sealed by
 * Go, and it opens here only if this layout is byte for byte the CLI's.
 */
function seal({ secret, publicKey: phonePublic, uid, plaintext, version = DELIVERY_VERSION, ephemeralSecret = filler(90, 32), nonce = filler(91, 12) }) {
  const shared = nodeX25519.getSharedSecret(ephemeralSecret, phonePublic);
  const key = new Uint8Array(hkdfSync('sha256', Buffer.from(shared), Buffer.alloc(0), Buffer.from(DELIVERY_INFO), 32));
  const cipher = createCipheriv('aes-256-gcm', Buffer.from(key), Buffer.from(nonce));
  cipher.setAAD(Buffer.from(deliveryAAD(uid, phonePublic, version)));
  const body = Buffer.concat([cipher.update(Buffer.from(plaintext)), cipher.final()]);
  const envelope = new Uint8Array(1 + 32 + 12 + body.length + 16);
  envelope[0] = version;
  envelope.set(nodeX25519.getPublicKey(ephemeralSecret), 1);
  envelope.set(nonce, 33);
  envelope.set(new Uint8Array(body), 45);
  envelope.set(new Uint8Array(cipher.getAuthTag()), 45 + body.length);
  // `secret` is unused here (the sealing end holds the ephemeral private key),
  // and it is a parameter so a caller reads the two ends' arguments as a pair.
  assert.equal(secret.length, 32);
  return envelope;
}

/** The vector's three values, decoded once. */
const UID = VECTOR.pairing_uid;
const PHONE_SECRET = unbase64url(VECTOR.phone_secret);
const PHONE_PUBLIC = unbase64url(VECTOR.phone_public);
// The wire's spelling, decoded by the app's own decoder: the fixture is the
// text the delivery node holds, not a byte array a test built.
const DECODED = decodeEnvelope(VECTOR.envelope);
assert.equal(DECODED.ok, true, 'the fixture’s envelope is not base64url');
const ENVELOPE = DECODED.bytes;

test('the envelope the CLI sealed opens, and the code is the key’s fingerprint', () => {
  // The fixture is a real pair: the secret's public half is the one the CLI
  // bound into the AAD. If this fails, nothing below means anything.
  assert.equal(encodeBase64url(nodeX25519.getPublicKey(PHONE_SECRET)), VECTOR.phone_public);

  const opened = openDelivery({
    envelope: ENVELOPE,
    secret: PHONE_SECRET,
    publicKey: PHONE_PUBLIC,
    uid: UID,
    x25519: nodeX25519,
  });
  assert.equal(opened.ok, true, JSON.stringify(opened));
  // The plaintext is one compact JSON document -- `json.Marshal`'s, with no
  // indentation -- and it parses to the document the vector names. A byte
  // comparison against a re-encoding here would test `JSON.stringify`'s key
  // order rather than Go's.
  const text = new TextDecoder('utf-8', { fatal: true }).decode(opened.plaintext);
  assert.equal(/[\s]/.test(text), false, 'the payload is compact JSON');
  assert.deepEqual(JSON.parse(text), VECTOR.payload);

  // **The code the operator compares is this key's fingerprint** (§7.2): the
  // CLI derived it from the public key the phone sent, and the phone derives
  // it from the public key it generated -- the same five bytes of SHA-256 of
  // the same 32 bytes, printed the same way.
  assert.equal(fingerprint(PHONE_PUBLIC), VECTOR.code);
});

test('the opened payload is the record the app stores', () => {
  // The two modules together, on the CLI's own bytes: this is the pairing's
  // whole read path minus the transport.
  const scan = readScannedPayload(
    JSON.stringify({
      v: 1,
      project: VECTOR.payload.config.project,
      gcp_project: VECTOR.payload.config.gcp_project,
      database_url: VECTOR.payload.config.database_url,
      api_key: VECTOR.payload.config.api_key,
      token: 'test-pairing-token-not-a-credential',
      uid: UID,
      expires_at: '2026-11-11T17:50:00Z',
    }),
  );
  assert.equal(scan.ok, true, JSON.stringify(scan));
  const opened = openDelivery({
    envelope: ENVELOPE,
    secret: PHONE_SECRET,
    publicKey: PHONE_PUBLIC,
    uid: UID,
    x25519: nodeX25519,
  });
  const judged = readDelivery({ plaintext: opened.plaintext, scan: scan.payload });
  assert.equal(judged.ok, true, JSON.stringify(judged));
  assert.equal(judged.delivery.config.project, 'aurora');
  assert.equal(judged.delivery.config.databaseHost, 'fp-1234-default-rtdb.firebaseio.com');
  assert.equal(judged.delivery.device.uid, VECTOR.payload.device.uid);
  assert.equal(judged.delivery.device.token, VECTOR.payload.device.token);
  // The MAC key is the bytes the CLI holds, not the string: 32 of them.
  assert.equal(hex(judged.delivery.macKey), '2a'.repeat(32));
});

test('an envelope this build did not write is refused before anything is derived', () => {
  const open = (over) =>
    openDelivery({ envelope: ENVELOPE, secret: PHONE_SECRET, publicKey: PHONE_PUBLIC, uid: UID, x25519: nodeX25519, ...over });

  // A version this build does not read: refused rather than attempted, which
  // is what the byte being first is for.
  const later = Uint8Array.from(ENVELOPE);
  later[0] = DELIVERY_VERSION + 1;
  assert.equal(open({ envelope: later }).code, ENVELOPE_CODES.BAD_VERSION);
  const earlier = Uint8Array.from(ENVELOPE);
  earlier[0] = 0;
  assert.equal(open({ envelope: earlier }).code, ENVELOPE_CODES.BAD_VERSION);

  // Not bytes, or too short to hold the four parts: a version byte, the
  // ephemeral key, a nonce and a tag.
  assert.equal(open({ envelope: VECTOR.envelope }).code, ENVELOPE_CODES.NOT_BYTES);
  assert.equal(open({ envelope: ENVELOPE.subarray(0, 60) }).code, ENVELOPE_CODES.TOO_SHORT);
  assert.equal(open({ envelope: new Uint8Array(0) }).code, ENVELOPE_CODES.TOO_SHORT);

  // A uid that is not a pairing's name, a secret that is not 32 bytes, and a
  // port that is not one.
  assert.equal(open({ uid: 'p~short' }).code, ENVELOPE_CODES.BAD_UID);
  assert.equal(open({ uid: 'm~' + UID.slice(2) }).code, ENVELOPE_CODES.BAD_UID);
  assert.equal(open({ secret: PHONE_SECRET.subarray(0, 31) }).code, ENVELOPE_CODES.BAD_KEY);
  assert.equal(open({ publicKey: PHONE_PUBLIC.subarray(0, 31) }).code, ENVELOPE_CODES.BAD_KEY);
  assert.equal(open({ x25519: {} }).code, ENVELOPE_CODES.BAD_PORT);
  assert.equal(open({ x25519: null }).code, ENVELOPE_CODES.BAD_PORT);
});

test('the delivery node is judged before the envelope is decoded', () => {
  // The node is `pairDeliveryNode`'s document, and the vector's envelope is
  // what the CLI put in `sealed` on the wire.
  const read = readDeliveryNode({ v: DELIVERY_VERSION, sealed: VECTOR.envelope });
  assert.equal(read.ok, true);
  assert.deepEqual(read.bytes, ENVELOPE);

  // The version is judged first, so a format this build does not read is
  // refused before a character of the payload is decoded -- and a version that
  // is quoted, or fractional, is not this build's either (the CLI writes a JSON
  // number, `pairDeliveryNode.V`).
  assert.equal(readDeliveryNode({ v: DELIVERY_VERSION + 1, sealed: VECTOR.envelope }).code, ENVELOPE_CODES.BAD_VERSION);
  assert.equal(readDeliveryNode({ v: String(DELIVERY_VERSION), sealed: VECTOR.envelope }).code, ENVELOPE_CODES.BAD_VERSION);
  assert.equal(readDeliveryNode({ v: DELIVERY_VERSION + 0.5, sealed: VECTOR.envelope }).code, ENVELOPE_CODES.BAD_VERSION);

  // The node has exactly two fields. The envelope on its own -- what the bytes
  // look like before the CLI wraps them -- is not one, and neither is a node
  // carrying a field this build does not know.
  assert.equal(readDeliveryNode(VECTOR.envelope).code, ENVELOPE_CODES.NOT_A_NODE);
  assert.equal(readDeliveryNode(null).code, ENVELOPE_CODES.NOT_A_NODE);
  assert.equal(readDeliveryNode([DELIVERY_VERSION]).code, ENVELOPE_CODES.NOT_A_NODE);
  assert.equal(readDeliveryNode({ v: DELIVERY_VERSION }).code, ENVELOPE_CODES.MISSING_FIELD);
  assert.equal(readDeliveryNode({ v: DELIVERY_VERSION, sealed: VECTOR.envelope, extra: 1 }).code, ENVELOPE_CODES.UNKNOWN_FIELD);
  assert.equal(readDeliveryNode({ v: DELIVERY_VERSION, sealed: 5 }).code, ENVELOPE_CODES.NOT_TEXT);

  // A `sealed` that is not this encoding is `decodeEnvelope`'s refusal, which
  // is the code the node reader answers with rather than a second vocabulary
  // for the same thing.
  assert.equal(readDeliveryNode({ v: DELIVERY_VERSION, sealed: 'not base64url!' }).code, ENVELOPE_CODES.NOT_BYTES);
});

test('a delivery bound to another uid or another phone does not open', () => {
  // A second pairing's uid, in the one canonical spelling (`A` is value 0, so
  // the two bits the encoding discards are zero).
  const other = 'p~' + 'B'.repeat(42) + 'A';
  // The AAD names the uid: an envelope sealed for another pairing's node is
  // refused here even though every other byte is right. It is sealed with the
  // *other* uid in the AAD, so this is the moved-delivery case and not a
  // corrupted envelope.
  const moved = seal({ secret: PHONE_SECRET, publicKey: PHONE_PUBLIC, uid: other, plaintext: JSON.stringify(VECTOR.payload) });
  assert.equal(
    openDelivery({ envelope: moved, secret: PHONE_SECRET, publicKey: PHONE_PUBLIC, uid: UID, x25519: nodeX25519 }).code,
    ENVELOPE_CODES.AUTHENTICATION_FAILED,
  );
  // ... and it opens under its own uid, which is what makes the refusal above
  // the AAD's doing rather than a broken seal.
  assert.equal(
    openDelivery({ envelope: moved, secret: PHONE_SECRET, publicKey: PHONE_PUBLIC, uid: other, x25519: nodeX25519 }).ok,
    true,
  );

  // The AAD names the phone's public key too: a payload sealed for one phone
  // does not open on another that shares the node -- the photographed-QR case
  // the envelope exists for.
  const theirs = seal({ secret: PHONE_SECRET, publicKey: PHONE_PUBLIC, uid: UID, plaintext: 'x', ephemeralSecret: filler(93, 32) });
  assert.equal(
    openDelivery({ envelope: theirs, secret: filler(94, 32), publicKey: nodeX25519.getPublicKey(filler(94, 32)), uid: UID, x25519: nodeX25519 }).ok,
    false,
  );

  // One tampered byte anywhere -- the ephemeral key, the nonce, the body, the
  // tag -- is a refusal, and no refusal carries a plaintext.
  for (const at of [1, 20, 33, 44, ENVELOPE.length - 20, ENVELOPE.length - 1]) {
    const tampered = Uint8Array.from(ENVELOPE);
    tampered[at] ^= 0x01;
    const refused = openDelivery({ envelope: tampered, secret: PHONE_SECRET, publicKey: PHONE_PUBLIC, uid: UID, x25519: nodeX25519 });
    assert.equal(refused.ok, false, `byte ${at}`);
    assert.equal('plaintext' in refused, false, `byte ${at} must not answer a plaintext`);
  }
});

test('a low-order point is refused rather than "agreed"', () => {
  // A dependency that answers the all-zero secret has agreed with a key that
  // has no private half, so every phone computes the same "key" and the
  // envelope is sealed to nobody. `crypto/ecdh` refuses the same case at the
  // sealing end, and so does OpenSSL: a real port throws here, which the
  // module reports as a key it cannot use.
  const zeros = new Uint8Array(32);
  assert.equal(
    openDelivery({ envelope: ENVELOPE, secret: PHONE_SECRET, publicKey: PHONE_PUBLIC, uid: UID, x25519: portAnswering(zeros) }).code,
    ENVELOPE_CODES.LOW_ORDER_POINT,
  );
  const zeroPoint = Uint8Array.from(ENVELOPE);
  zeroPoint.set(zeros, 1);
  let refused;
  try {
    refused = openDelivery({ envelope: zeroPoint, secret: PHONE_SECRET, publicKey: PHONE_PUBLIC, uid: UID, x25519: nodeX25519 });
  } catch {
    // A port that throws on the point is refused by the module as a key it
    // cannot use; either way the envelope does not open.
    refused = { ok: false, code: ENVELOPE_CODES.BAD_KEY };
  }
  assert.equal(refused.ok, false);
  assert.equal('plaintext' in refused, false);
});
