#!/usr/bin/env bash
# Writes the licence and notice texts of every Go module the released binary
# links, for the CLI archive to carry (D307). GoReleaser runs it from
# .goreleaser.yaml's before hooks, so the file is in the tree when the archive
# is built; scripts/notices_test.go runs it into a temporary directory, which is
# why the output path is an argument.
#
#   scripts/third-party-notices.sh [output-path]
#
# `go list -deps` answers per GOOS/GOARCH pair: a module can be linked for one
# target of the build matrix and not another, so the file is the union of the
# four targets .goreleaser.yaml builds. The main module is left out (it carries
# no version), and its own LICENSE ships in the archive separately.
set -eu

repo_root=$(cd "$(dirname "$0")/.." && pwd)
cd "$repo_root"
out=${1:-THIRD_PARTY_NOTICES.md}

# The build matrix .goreleaser.yaml builds; notices_test.go holds this list to
# the config's own goos/goarch.
targets="darwin/amd64 darwin/arm64 linux/amd64 linux/arm64"

work=$(mktemp -d)
trap 'rm -rf "$work"' EXIT

# One line per linked module: path, version, module directory. The main module
# has no version, which is what leaves it out.
for target in $targets; do
  GOOS=${target%/*} GOARCH=${target#*/} CGO_ENABLED=0 \
    go list -deps -f '{{if .Module}}{{if .Module.Version}}{{.Module.Path}}{{"\t"}}{{.Module.Version}}{{"\t"}}{{.Module.Dir}}{{end}}{{end}}' ./cmd/fugaro
done | LC_ALL=C sort -u > "$work/modules"

{
  cat <<'HEADER'
# Third-party notices

The Fugaro CLI binary links the Go modules below. Each section carries the
licence and notice texts that module ships, copied from its own module
directory. The file is generated by `scripts/third-party-notices.sh` when the
release is built and ships in the release archive beside `LICENSE` and
`README.md`; Fugaro's own code is not covered here.

HEADER
  while IFS=$'\t' read -r path version dir; do
    [ -n "$path" ] || continue
    printf '## %s %s\n\n' "$path" "$version"
    found=0
    while IFS= read -r file; do
      found=1
      printf '### %s\n\n' "$(basename "$file")"
      cat "$file"
      printf '\n'
    done < <(find "$dir" -maxdepth 1 \( -type f -o -type l \) \
      \( -iname 'license*' -o -iname 'copying*' -o -iname 'notice*' \) | LC_ALL=C sort)
    # Nothing to copy is not a silence: the test that reads this file fails on
    # a module whose directory carries no licence, and this line says which one
    # a reader is looking at.
    [ "$found" = 1 ] || printf 'This module ships no licence or notice file in its module directory.\n\n'
  done < "$work/modules"
} > "$work/notices"

mv "$work/notices" "$out"
