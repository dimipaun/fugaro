package digest

import (
	"encoding/json"
	"fmt"
	"os"
	"regexp"
	"sort"
	"strings"

	"github.com/dimipaun/fugaro/internal/report"
)

// The report folder's layout (D321): one file per period under <YYYY>/, named
// <key>.md, and a generated index beside them.
//
// The layout lives here, and not in either writer, because there are two:
// `fugaro runs digest` writes these files from a person's terminal and a
// report run (internal/runner's digest step) writes them from the container,
// and a file either wrote must be the one the other regenerates byte for byte
// (G3). Every function below is a pure render over the rows it is handed and
// reads nothing else.
const (
	// Dir is the folder a repository's reports live in.
	Dir = "docs/fugaro-reviews"
	// IndexName is the generated index beside them.
	IndexName = "README.md"
	// IndexHeader is the index's first line, the "generated by <command>; do
	// not edit" shape the backlog's index carries (D28). It names the command
	// that writes the file, so a reader who finds a stale index has the one
	// command that fixes it on the first line.
	IndexHeader = "<!-- generated by fugaro runs digest; do not edit -->"
)

// Row is one report file present under Dir: the period its own path names, and
// the summary block it carries when that can be read at all. Read is false for
// a file that is there but whose block is not one this package wrote.
type Row struct {
	Dim     report.Dim
	Key     string
	Rel     string // the file's path under Dir, <YYYY>/<key>.md
	Summary Summary
	Read    bool
}

// reportShapes are the report file names D321 pins, one per period: the path
// relative to Dir, and the dimension its own name says it is.
var reportShapes = []struct {
	dim report.Dim
	re  *regexp.Regexp
}{
	{report.ByDay, regexp.MustCompile(`^(\d{4})/(\d{4}-\d{2}-\d{2})\.md$`)},
	{report.ByWeek, regexp.MustCompile(`^(\d{4})/(\d{4}-W\d{2})\.md$`)},
	{report.ByMonth, regexp.MustCompile(`^(\d{4})/(\d{4}-\d{2})\.md$`)},
	{report.ByYear, regexp.MustCompile(`^(\d{4})/(\d{4})\.md$`)},
}

// yearDirRE is the one shape of directory the reports live in: D321's <YYYY>.
// A directory of another name is not one a writer of this layout made, and
// what it holds is not a report.
var yearDirRE = regexp.MustCompile(`^\d{4}$`)

// IsYearDir is whether name is a directory of this layout's.
func IsYearDir(name string) bool { return yearDirRE.MatchString(name) }

// PeriodPath is a period's file, D321's <YYYY>/<key>.md, relative to Dir.
func PeriodPath(key string) string {
	return key[:4] + "/" + key + ".md"
}

// ReportName is the period a report file's path names, and whether the path
// names one a writer of this layout wrote. The year directory must be the
// period's own year: a file whose name and directory disagree is a file
// neither writer produced, and nothing may read it as the period it claims.
func ReportName(rel string) (report.Dim, string, bool) {
	for _, shape := range reportShapes {
		m := shape.re.FindStringSubmatch(rel)
		if m == nil {
			continue
		}
		if m[1] != m[2][:4] {
			return "", "", false
		}
		return shape.dim, m[2], true
	}
	return "", "", false
}

// ReadRow is the summary block of one report file at path, and whether it is
// one this layout wrote: a block that decodes, that is one of the report's own
// shapes, and whose period is the one its path names. A file that is not
// there, or cannot be read, is no summary at all.
func ReadRow(path, key string) (Summary, bool) {
	data, err := os.ReadFile(path)
	if err != nil {
		return Summary{}, false
	}
	s, err := ReadSummary(data)
	if err != nil || s.Period != key {
		return Summary{}, false
	}
	return s, true
}

// Prev is the committed summaries the pattern rules read: every readable
// report of a period at or before this report's, except its own period, which
// the rules are handed separately.
//
// A report of a later period is not history: a writer may backfill an older
// period with the later ones already committed, and a rule that read them
// would fire in the backfill's report over periods it does not cover -- "three
// of the last four weeks" over four weeks a year after the one being written
// (G5).
func Prev(rows []Row, p Period) []Summary {
	prev := make([]Summary, 0, len(rows))
	for _, r := range rows {
		if r.Read && r.Key != p.Key && r.Summary.End <= p.End {
			prev = append(prev, r.Summary)
		}
	}
	return prev
}

// MonthsOf is the committed monthly summaries of year, oldest first and one
// per month: the twelve (or fewer) a yearly report rolls up. A report of
// another period shape is not one of the year's months.
func MonthsOf(rows []Row, year string) []Summary {
	var months []Summary
	for _, r := range rows {
		if r.Read && r.Dim == report.ByMonth && r.Summary.Period[:4] == year {
			months = append(months, r.Summary)
		}
	}
	return months
}

// YearMarkdown is a yearly report's head. A year has no runs of its own to
// read -- the records are kept 90 days (F24) -- so the body is the monthly
// reports of that year added up, the months it read listed, and the same
// fenced block every other period's report carries, which is what a later
// report's pattern rules read.
func YearMarkdown(p Period, months []Summary, s Summary) []byte {
	var b strings.Builder
	fmt.Fprintf(&b, "# Run digest: %s\n\n", p.Key)
	fmt.Fprintf(&b, "A yearly report is the monthly reports of %s (%s to %s) added up: %d of the year's twelve are committed, and they hold %d runs in all, %d flagged. Billed %s, notional %s.\n\n",
		p.Key, p.Start, p.End, s.Months, s.Runs, s.Flagged, s.Billed, s.Notional)
	b.WriteString("| month | runs | flagged | billed | notional |\n")
	b.WriteString("| --- | --- | --- | --- | --- |\n")
	for _, m := range months {
		fmt.Fprintf(&b, "| %s | %d | %d | %s | %s |\n", m.Period, m.Runs, m.Flagged, m.Billed, m.Notional)
	}
	b.WriteString("\n## Summary\n\n```json\n")
	// Marshal cannot fail on this type: it holds strings, ints and a map of
	// them, and every dollar figure is one of the strings.
	block, _ := json.Marshal(s)
	b.Write(block)
	b.WriteString("\n```\n")
	return []byte(b.String())
}

// FileBody is the whole file for one period: head, which its writer built from
// the records (Markdown) or from the year's months (YearMarkdown), and then
// the pattern rules over the committed reports before it and this period's own
// figures. Every period's file carries its rules, a year's included, so the
// two writers produce the same bytes for the same rows and period.
func FileBody(head []byte, rows []Row, p Period, s Summary) []byte {
	body := append(head, '\n')
	return append(body, PatternsMarkdown(Patterns(Prev(rows, p), s))...)
}

// IndexMarkdown is the index of the reports the folder holds: one row per
// report file, the period linked to its file, and the figures a reader needs
// to see what changed. It renders the rows it is given and reads nothing else,
// so the same folder gives byte-identical bytes (G3).
//
// A row whose report could not be read is listed with no figures: the file is
// there, which is what the index is for, and saying so is better than leaving
// it out or printing a zero it does not have (G5).
func IndexMarkdown(rows []Row) string {
	var b strings.Builder
	b.WriteString(IndexHeader + "\n\n")
	b.WriteString("# Run digests\n\n")
	b.WriteString("One file per period under `<YYYY>/`, named `<key>.md`, and this index, which\n" +
		"`fugaro runs digest` regenerates from them. **Do not edit it: regenerate it.**\n" +
		"A report is of this repository alone and holds no person and no task text.\n\n")
	if len(rows) == 0 {
		b.WriteString("No reports yet.\n")
		return b.String()
	}
	b.WriteString("| period | runs | flagged | billed | notional |\n")
	b.WriteString("| --- | --- | --- | --- | --- |\n")
	unreadable := 0
	for _, r := range rows {
		if !r.Read {
			unreadable++
			fmt.Fprintf(&b, "| [%s](%s) | - | - | - | - |\n", r.Key, r.Rel)
			continue
		}
		// A year's figures are its months added up (F24), so its row says how
		// many of the twelve it covers: a partial year read as a whole one is
		// the mistake the block's own Months field exists to prevent (G5).
		note := ""
		if r.Summary.Months > 0 {
			note = fmt.Sprintf(" (%d of 12 months)", r.Summary.Months)
		}
		fmt.Fprintf(&b, "| [%s](%s)%s | %d | %d | %s | %s |\n",
			r.Key, r.Rel, note, r.Summary.Runs, r.Summary.Flagged, r.Summary.Billed, r.Summary.Notional)
	}
	fmt.Fprintf(&b, "\n%d reports", len(rows))
	if unreadable > 0 {
		fmt.Fprintf(&b, ", %d of them not readable and left without figures", unreadable)
	}
	b.WriteString(".\n")
	return b.String()
}

// WithRow is rows with the report being written in it: its own row, replacing
// any file of the same period the folder already held, so the index is
// regenerated from the folder as it is after the write.
func WithRow(rows []Row, p Period, s Summary) []Row {
	row := Row{Dim: p.Dim, Key: p.Key, Rel: PeriodPath(p.Key), Summary: s, Read: true}
	out := make([]Row, 0, len(rows)+1)
	for _, r := range rows {
		if r.Key != p.Key {
			out = append(out, r)
		}
	}
	out = append(out, row)
	sort.Slice(out, func(i, j int) bool { return out[i].Key < out[j].Key })
	return out
}
