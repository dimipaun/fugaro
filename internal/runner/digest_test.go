// TestDigestStepCountsDroppedRecords: the manifest names four runs and three of
// them are not records a report may count — one that never wrote a record, one
// whose record is not JSON, and one that has not finished. Each is read past
// and counted once, and the count is logged; the one real record is the only
// thing the report counts. Nothing of the three reaches a file, and a read that
// failed for any other reason would fail the step instead (G5).
