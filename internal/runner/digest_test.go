// The digest step (task-governance plan T3.2). A report run's first step is the
// runner's own work: it reads the records its launcher's manifest names (T3.6),
// writes the reports the tree is missing into docs/fugaro-reviews/, commits
// them as the runner, and leaves the pull request to the recipe's one senior
// review. These tests pin the four properties the step's review rests on: it
// reads its own repository's objects and no others, it never lists a bucket,
// it puts no word of a record into a file, and it makes no model call.
//
// The harness's runs bucket is a real bucket holding every repository's runs/
// prefix (a project job's grant reaches them all, G2), so "the step reads its
// own repository's records only" is tested rather than assumed.

// digestCatalog is the catalog recipe a report run names.
const digestCatalog = "run-digest"

// digestIndexFirstLine is the generated index's first line (D321), the same
// one internal/cli's `fugaro runs digest` writes.
const digestIndexFirstLine = "<!-- generated by fugaro runs digest; do not edit -->"

// digestPlantedText is free text planted in a record's own fields: a record is
// untrusted input (G1), and no file a report run commits may carry it.
const digestPlantedText = "words a task planted in a record"

// digestBucket is the bucket the gcpfake-backed tests run against.
const digestBucket = "fugaro-runs-proj-1234"

// digestSpec is a report run's task: the catalog run-digest recipe embedded
// the way `fugaro run --recipe run-digest` embeds it, and the launcher's
// manifest naming the run IDs the step may read.
func digestSpec(ids ...string) *task.Spec {
	text, ok := recipe.CatalogText(digestCatalog)
	if !ok {
		panic("run-digest is not in the catalog")
	}
	return &task.Spec{
		Version: 1, RunID: runID, Repo: "acme/app", Ref: "main", Workflow: "app",
		Task: "Periodic run review",
		Recipe: &task.Recipe{
			Name: digestCatalog, Source: string(recipe.SourceCatalog),
			SHA256: recipe.Sum(text), YAML: string(text),
		},
		DigestRuns: ids,
	}
}

// digestClock installs a clock the test owns: every due period is derived from
// it, so a test says which day the run believes it is. It is moved forward to a
// Wednesday past the first of the month, so the periods due at it are the seven
// closed days alone: a Monday adds the week that closed, and the first of a
// month the month, and a test that expects exactly the day files would then pass
// on some days of the week and fail on others. The clock is only moved forward,
// since the run's own deadline is taken from it.
func digestClock(h *harness) *testClock {
	clk := newClock()
	for clk.Now().Weekday() != time.Wednesday || clk.Now().Day() == 1 {
		clk.advance(24 * time.Hour)
	}
	h.deps.Now = clk.Now
	return clk
}

// digestGCSBucket moves the harness's runs bucket onto internal/gcpfake's GCS
// fake, so a test can watch every call the run made (Requests) and fail a
// listing or a single object's read. The task is written again to the new
// store, since the harness's first one is left behind.
func digestGCSBucket(t *testing.T, h *harness, spec *task.Spec) *gcpfake.GCS {
	t.Helper()
	g := gcpfake.NewGCS(t)
	h.bucket = g.Bucket(t, digestBucket).Bucket
	h.store = runstore.Open(h.bucket, repoSlug, spec.RunID)
	h.deps.Store = h.store
	if err := h.store.WriteTask(context.Background(), spec); err != nil {
		t.Fatal(err)
	}
	return g
}

// digestCalls is the calls the fake received from the run: the test's own
// seeding is already in the log when the run starts, so a test takes the count
// before it runs the run.
func digestCalls(g *gcpfake.GCS, since int) []gcpfake.Request {
	reqs := g.Requests()
	if since > len(reqs) {
		return nil
	}
	return reqs[since:]
}

// digestRecord writes one finished run's record under slug's prefix: a record
// a report counts, before mutate adds what a test is about.
func digestRecord(t *testing.T, bucket *blob.Bucket, slug, id string, finished time.Time, costUSD float64, mutate func(*runstore.Record)) {
	t.Helper()
	rec := &runstore.Record{
		Version: 1, RunID: id, Repo: "acme/app", Status: runstore.StatusSucceeded,
		Stage: "finalize", Outcome: runstore.OutcomeReady, Branch: "fugaro/" + id,
		StartedAt: finished.Add(-time.Hour), FinishedAt: &finished,
		CostUSD: costUSD, Cost: &runstore.Cost{TotalUSD: costUSD},
	}
	if mutate != nil {
		mutate(rec)
	}
	if err := runstore.Open(bucket, slug, id).WriteRecord(context.Background(), rec); err != nil {
		t.Fatal(err)
	}
}

// digestRawRecord writes raw bytes as a run's result.json: a run that never
// wrote one leaves nothing, and a record that is not one is not JSON.
func digestRawRecord(t *testing.T, bucket *blob.Bucket, slug, id, data string) {
	t.Helper()
	if err := runstore.Open(bucket, slug, id).PutFile(context.Background(), "result.json", []byte(data), "application/json"); err != nil {
		t.Fatal(err)
	}
}

// digestDayPath is one day report's path (D321).
func digestDayPath(day time.Time) string {
	return "docs/fugaro-reviews/" + day.Format("2006") + "/" + day.Format("2006-01-02") + ".md"
}

// digestDuePaths is every path a report run must write when it believes it is
// now: the seven closed days the step catches up, the week, month or year that
// closed with yesterday when one did, and the folder's index beside them.
//
// It is derived here from the calendar rather than read off the step's own
// commit, so a step that wrote a file for a period that is not due, or left one
// out, is caught: a comparison against the step's own commit alone would call
// any file set it committed the right one.
func digestDuePaths(t *testing.T, now time.Time) []string {
	t.Helper()
	today := now.UTC()
	type due struct {
		dim  report.Dim
		date string
	}
	dues := make([]due, 0, 8)
	for i := 1; i <= 7; i++ {
		dues = append(dues, due{report.ByDay, today.AddDate(0, 0, -i).Format("2006-01-02")})
	}
	yesterday := today.AddDate(0, 0, -1).Format("2006-01-02")
	if today.Weekday() == time.Monday {
		dues = append(dues, due{report.ByWeek, yesterday})
	}
	if today.Day() == 1 {
		dues = append(dues, due{report.ByMonth, yesterday})
		if today.Month() == time.January {
			dues = append(dues, due{report.ByYear, yesterday})
		}
	}
	paths := make([]string, 0, len(dues)+1)
	for _, d := range dues {
		p, err := digest.NewPeriod(d.dim, d.date)
		if err != nil {
			t.Fatalf("digest.NewPeriod(%v, %q): %v", d.dim, d.date, err)
		}
		paths = append(paths, digest.Dir+"/"+digest.PeriodPath(p.Key))
	}
	return append(paths, digest.Dir+"/"+digest.IndexName)
}

// digestFiles is every path a ref of the harness's remote holds.
func digestFiles(t *testing.T, h *harness, ref string) []string {
	t.Helper()
	out := strings.TrimSpace(testutil.Git(t, h.remote, "ls-tree", "-r", "--name-only", ref))
	if out == "" {
		return nil
	}
	return strings.Split(out, "\n")
}

// digestSummaryAt is one report file's summary block, read the way a reader of
// the tree reads it.
func digestSummaryAt(t *testing.T, h *harness, ref, rel string) digest.Summary {
	t.Helper()
	s, err := digest.ReadSummary([]byte(fileContentAt(t, h.remote, ref, rel)))
	if err != nil {
		t.Fatalf("%s: %v", rel, err)
	}
	return s
}

// digestBranchAt cuts a new branch in the remote from base and commits files on
// it: the branch an open report run's pull request sits on.
func digestBranchAt(t *testing.T, remote, branch, base string, files map[string]string) {
	t.Helper()
	dir := filepath.Join(t.TempDir(), "branch")
	testutil.Git(t, filepath.Dir(dir), "clone", "--quiet", remote, dir)
	testutil.Git(t, dir, "checkout", "--quiet", "-b", branch, base)
	testutil.WriteFiles(t, dir, files)
	testutil.Git(t, dir, "add", "-A")
	testutil.Git(t, dir, "commit", "--quiet", "-m", "the report run's own commit")
	testutil.Git(t, dir, "push", "--quiet", "origin", "HEAD:refs/heads/"+branch)
}

// digestPlantLink commits one symbolic link onto the remote's main branch: the
// report folder's components come from the base branch, which whoever can
// commit to it chooses, and a report run checks that branch out before the step
// runs.
func digestPlantLink(t *testing.T, remote string, plant func(t *testing.T, dir string)) {
	t.Helper()
	dir := filepath.Join(t.TempDir(), "plant")
	testutil.Git(t, filepath.Dir(dir), "clone", "--quiet", remote, dir)
	plant(t, dir)
	testutil.Git(t, dir, "add", "-A")
	testutil.Git(t, dir, "commit", "--quiet", "-m", "the base branch plants a link in the report folder")
	testutil.Git(t, dir, "push", "--quiet", "origin", "HEAD:refs/heads/main")
}

// TestDigestStepWritesDueFiles: a report run writes one file per closed day the
// tree does not hold yet, and the generated index beside them, out of the
// records its manifest names.
//
// The bucket holds another repository's run too and the manifest names it: on a
// project job one bucket carries every repository's runs/ (G2), so the step's
// own slug-scoped read is the only thing keeping the report of one repository
// out of another's — its figures reach no file and its prefix is never asked
// for. A record's own free text reaches a file the same way it reaches a
// bucket request: never (G1). The run makes one model call in all, its
// recipe's review, and no implement stage.
//
// Mutation (read a manifest ID through any store but the run's own, or render a
// record field): the other repository's figures appear, or the planted text
// does.
func TestDigestStepWritesDueFiles(t *testing.T) {
	const (
		own   = "20261020-101500-aaaa"
		older = "20261019-090000-bbbb"
		other = "20261020-110000-cccc"
	)
	otherSlug := mustSlug("github", "other/repo")
	spec := digestSpec(own, older, other)
	h := newHarnessFiles(t, "", spec, nil)
	clk := digestClock(h)
	g := digestGCSBucket(t, h, spec)
	var logs bytes.Buffer
	h.deps.Log = slog.New(slog.NewTextHandler(&logs, nil))

	now := clk.Now()
	yesterday := now.AddDate(0, 0, -1)
	digestRecord(t, h.bucket, repoSlug, own, yesterday, 1.5, func(rec *runstore.Record) {
		rec.PR = &runstore.PRRef{Number: 7, URL: "https://example.invalid/pr/7"}
		rec.Reason = digestPlantedText
		rec.BaseBranch = digestPlantedText
	})
	digestRecord(t, h.bucket, repoSlug, older, now.AddDate(0, 0, -3), 2.25, nil)
	digestRecord(t, h.bucket, otherSlug, other, yesterday, 99, nil)

	before := len(g.Requests())
	rec, err := h.run(t, review("ship", 0))
	if err != nil {
		t.Fatal(err)
	}
	if rec.Status != runstore.StatusSucceeded || rec.Outcome != runstore.OutcomeReady {
		t.Fatalf("record = status %s, outcome %s, reason %q", rec.Status, rec.Outcome, rec.Reason)
	}
	if got := stageNames(rec); !slices.Equal(got, []string{"digest", "review"}) {
		t.Errorf("stages = %v, want the digest step and the review, and no implement", got)
	}
	if len(h.agent.calls) != 1 {
		t.Fatalf("the run made %d model calls, want its one review", len(h.agent.calls))
	}
	branch := "fugaro/" + runID
	for i := 1; i <= 7; i++ {
		if rel := digestDayPath(now.AddDate(0, 0, -i)); !fileInTree(t, h.remote, branch, rel) {
			t.Errorf("%s is not on the run's branch", rel)
		}
	}
	if got := fileContentAt(t, h.remote, branch, "docs/fugaro-reviews/README.md"); !strings.HasPrefix(got, digestIndexFirstLine) {
		t.Errorf("the index does not start with %q: %.60q", digestIndexFirstLine, got)
	}
	if s := digestSummaryAt(t, h, branch, digestDayPath(yesterday)); s.Period != yesterday.Format("2006-01-02") || s.Runs != 1 || s.Billed != "1.500000" {
		t.Errorf("yesterday's report = period %q, %d runs, billed %s; want %s, 1 run, 1.500000",
			s.Period, s.Runs, s.Billed, yesterday.Format("2006-01-02"))
	}
	if s := digestSummaryAt(t, h, branch, digestDayPath(now.AddDate(0, 0, -3))); s.Runs != 1 || s.Billed != "2.250000" {
		t.Errorf("the report of three days ago = %d runs, billed %s; want 1 and 2.250000", s.Runs, s.Billed)
	}
	// A day with no run of the repository still gets its file, and the file
	// says zero runs rather than nothing (G5).
	if s := digestSummaryAt(t, h, branch, digestDayPath(now.AddDate(0, 0, -5))); s.Runs != 0 || s.Billed != "0.000000" {
		t.Errorf("the report of five days ago = %d runs, billed %s; want 0 and 0.000000", s.Runs, s.Billed)
	}
	for _, rel := range digestFiles(t, h, branch) {
		body := fileContentAt(t, h.remote, branch, rel)
		for _, word := range []string{other, otherSlug, "99.000000", digestPlantedText} {
			if strings.Contains(body, word) {
				t.Errorf("%s holds %q, which is not this repository's or not a figure", rel, word)
			}
		}
	}
	for _, req := range digestCalls(g, before) {
		if strings.Contains(req.Path, otherSlug) || strings.Contains(req.Query, otherSlug) {
			t.Errorf("the bucket was asked for %s: %s %s?%s", otherSlug, req.Method, req.Path, req.Query)
		}
	}
	if !strings.Contains(logs.String(), "dropped=1") {
		t.Errorf("the step did not log the one record it read past:\n%s", logs.String())
	}
}

// TestDigestStepRefusesForeignSlug: a manifest naming another repository's run
// ID does not make that run's record readable, however much the bucket would
// allow it. One bucket holds both repositories' prefixes — a project job's
// reach, G2 — and the step reads under its own slug and nowhere else: the
// record is one the reports read past (counted, named nowhere), its figures
// reach no file, and its object is never fetched. Reading it is wired to fail,
// so an implementation that reached for it fails here instead of quietly
// publishing another repository's runs.
//
// Mutation (open the record's store from the record's own Repo field, or from
// anything but the run's own slug): the foreign object is read, and the fake
// fails the test.
func TestDigestStepRefusesForeignSlug(t *testing.T) {
	const other = "20261020-110000-cccc"
	otherSlug := mustSlug("github", "other/repo")
	spec := digestSpec(other)
	h := newHarnessFiles(t, "", spec, nil)
	clk := digestClock(h)
	g := digestGCSBucket(t, h, spec)
	var logs bytes.Buffer
	h.deps.Log = slog.New(slog.NewTextHandler(&logs, nil))

	now := clk.Now()
	yesterday := now.AddDate(0, 0, -1)
	digestRecord(t, h.bucket, otherSlug, other, yesterday, 99, nil)
	foreign := "runs/" + otherSlug + "/" + other + "/result.json"
	g.FailObjectGetsAfter(digestBucket, foreign, 0)

	before := len(g.Requests())
	rec, err := h.run(t, review("ship", 0))
	if err != nil {
		t.Fatal(err)
	}
	if rec.Status != runstore.StatusSucceeded || rec.Outcome != runstore.OutcomeReady {
		t.Fatalf("record = status %s, outcome %s, reason %q", rec.Status, rec.Outcome, rec.Reason)
	}
	branch := "fugaro/" + runID
	if s := digestSummaryAt(t, h, branch, digestDayPath(yesterday)); s.Runs != 0 || s.Billed != "0.000000" {
		t.Errorf("yesterday's report = %d runs, billed %s; want this repository's own zero", s.Runs, s.Billed)
	}
	for _, rel := range digestFiles(t, h, branch) {
		body := fileContentAt(t, h.remote, branch, rel)
		for _, word := range []string{other, otherSlug, "99.000000"} {
			if strings.Contains(body, word) {
				t.Errorf("%s holds %q, which is another repository's", rel, word)
			}
		}
	}
	for _, req := range digestCalls(g, before) {
		if strings.Contains(req.Path, otherSlug) || strings.Contains(req.Query, otherSlug) {
			t.Errorf("the bucket was asked for %s: %s %s?%s", otherSlug, req.Method, req.Path, req.Query)
		}
	}
	if !strings.Contains(logs.String(), "dropped=1") {
		t.Errorf("the step did not log the one record it read past:\n%s", logs.String())
	}
}

// TestDigestRecordsChecksEveryIDBeforeAnyRead: a manifest whose first ID is
// this repository's own and whose second is a path into another repository's
// prefix is refused with not one call made to the bucket. The shape check is
// the only guard a project job has (G2), so it must judge the whole manifest
// before the first read, not each ID as the read loop reaches it.
//
// Mutation (check each ID inside the read loop): the first record is read
// before the second ID is refused, and the bucket log is not empty.
func TestDigestRecordsChecksEveryIDBeforeAnyRead(t *testing.T) {
	g := gcpfake.NewGCS(t)
	bucket := g.Bucket(t, digestBucket).Bucket
	const own = "20261020-101500-aaaa"
	digestRecord(t, bucket, repoSlug, own, time.Date(2026, 10, 20, 11, 0, 0, 0, time.UTC), 1, nil)
	store := runstore.Open(bucket, repoSlug, runID)

	before := len(g.Requests())
	_, _, err := runner.DigestRecords(context.Background(), store, []string{own, "../other/20261020-110000-cccc"})
	if err == nil || !strings.Contains(err.Error(), "not a run ID") {
		t.Fatalf("err = %v; want the manifest refused for an ID that is not a run ID", err)
	}
	if calls := digestCalls(g, before); len(calls) != 0 {
		t.Errorf("the bucket got %d calls before the manifest was refused; want none: %v", len(calls), calls)
	}
}

// TestDigestStepNeverLists: a bucket that answers every listing with 403 still
// serves the whole report run, and the fake's own log of the calls shows not
