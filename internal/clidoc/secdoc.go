// Command clidoc generates the documents the website renders from the trees
// and files of this repository.
//
// Today it generates two: website/content/security.md from SECURITY.md
// (secdoc.go) and website/content/subscription-terms.md from the draft
// Subscription Terms (termsdoc.go).
//
// The CLI reference -- website/content/cli-reference.md -- used to be the
// third, and it is not generated here any more. The reference describes the
// binary that ships, and that binary is the tagged one, so it is written from
// the tagged command tree by `go run ./ee/clidoc` (design
// docs/design/ee-boundary-moves.md §9). Two generators writing one file would
// overwrite each other, whichever ran last, so this command no longer writes
// it at all. The renderer both generators read is internal/clidoc/cliref.
//
// Hermetic by rule: the standard library only, no network, no clock, no
// credential (website plan Global Constraint 4). It reads its sources in the
// tree and writes their pages there.
//
// Run it from the repository root:
//
//	go run ./internal/clidoc
package main

import (
	"bytes"
	"fmt"
	"os"
	"path/filepath"
)

// securitySource is the document the security page is rendered from, and
// securityPage is the file it is rendered into. Both are relative to the
// repository root the command runs in.
const (
	securitySource = "SECURITY.md"
	securityPage   = "website/content/security.md"
)

// securityHeader is the generated-file header: W1.3's content pipeline reads it
// as what makes a file in content/ generated rather than hand-kept. It names
// this command, which is the one that writes this page — the CLI reference
// carries the same shape with its own generator's name in it, because a header
// naming a command that does not write the file is a header nobody can act on.
// The source document is named on the line under it, which is Global Constraint
// 6 ("every generated file names its source in a header comment") and W0.5's
// own step 1.
const securityHeader = "<!-- generated by go run ./internal/clidoc; do not edit -->"

// securityHeaderBlock is the whole header block, blank line included, so the
// document's own first line (`# Security policy`) follows it as the page's
// first content.
var securityHeaderBlock = securityHeader + "\n<!-- source: " + securitySource + " -->\n\n"

// renderSecurityPage is the whole generator: the header, then SECURITY.md
// byte for byte — title, headings, links and all. Nothing is reworded and
// nothing is added, so no security claim on the site is a paraphrase of the
// document's (D99, finding 41), and the page keeps the document's own
// `# Security policy` title because the title is part of those bytes.
func renderSecurityPage(source []byte) []byte {
	page := make([]byte, 0, len(securityHeaderBlock)+len(source))
	page = append(page, securityHeaderBlock...)
	return append(page, source...)
}

// writeSecurityPage renders the page into root, and reports whether it had
// to change anything, so a regeneration that changes nothing is visible as
// one.
func writeSecurityPage(root string) (bool, error) {
	source, err := os.ReadFile(filepath.Join(root, securitySource))
	if err != nil {
		return false, fmt.Errorf("read %s: %w (run this from the repository root)", securitySource, err)
	}
	out := filepath.Join(root, securityPage)
	page := renderSecurityPage(source)
	if old, err := os.ReadFile(out); err == nil && bytes.Equal(old, page) {
		return false, nil
	}
	if err := os.MkdirAll(filepath.Dir(out), 0o755); err != nil {
		return false, err
	}
	if err := os.WriteFile(out, page, 0o644); err != nil {
		return false, err
	}
	return true, nil
}

// main regenerates every file this command generates (the security page and
// the subscription terms). A failure is named on stderr and exits non-zero, so
// a regeneration that cannot read its source never looks like a successful
// no-op that left a stale page in place.
func main() {
	changed, err := writeSecurityPage(".")
	if err != nil {
		fmt.Fprintln(os.Stderr, "clidoc:", err)
		os.Exit(1)
	}
	switch {
	case changed:
		fmt.Printf("wrote %s from %s\n", securityPage, securitySource)
	default:
		fmt.Printf("%s is already current\n", securityPage)
	}

	changed, err = writeTermsPage(".")
	if err != nil {
		fmt.Fprintln(os.Stderr, "clidoc:", err)
		os.Exit(1)
	}
	switch {
	case changed:
		fmt.Printf("wrote %s from %s\n", termsPage, termsSource)
	default:
		fmt.Printf("%s is already current\n", termsPage)
	}
}
