// Package cliref renders the CLI reference -- website/content/cli-reference.md
// -- from a fugaro command tree.
//
// It is the generator without the command: internal/clidoc is `package main`
// and cannot be imported, and the reference is written from the tree a
// *released* binary builds, which is the tree the ee build tag reaches through
// ee/register (design docs/design/ee-boundary-moves.md §9). So the renderer
// lives here, in a package both generators can read, and the caller supplies
// the tree: `cliref.Generate(cli.NewRootCmd())`.
//
// It reads the command tree and nothing else: no network, no clock, no
// credential, no environment. The same tree produces the same bytes, so the
// file can be regenerated in a review and diffed. Hidden commands are left
// out, with the subtree under them, and so are hidden flags: a hidden command
// is not user documentation (reconciliation F38).
package cliref

import (
	"fmt"
	"sort"
	"strings"

	"github.com/spf13/cobra"
	"github.com/spf13/pflag"
)

// header is the first line of the reference: most of it is generated, and a
// reader who opens the file has to be able to see that before editing it. It
// names the generator that writes the released tree, which is the tagged one
// (ee/clidoc): one binary ships, and the reference describes that binary.
const header = "<!-- generated by go run ./ee/clidoc; do not edit -->"

// Prepare returns root with the commands and flags cobra adds for itself, so
// that the tree a generator reads is the tree a reader runs.
//
// Cobra adds its `help` command, its `completion` command (with one
// subcommand per shell), the root command's `-v, --version` flag (from the
// root's Version field) and the `-h, --help` flag of every command inside
// Execute, not when the tree is built. A reference generated from the
// un-executed tree would therefore print "every command and flag `fugaro`
// ships" while omitting the two commands `fugaro --help` lists under Available
// Commands and the version and help flags of the CLI -- a claim the page
// does not keep, and one no test can catch, because a test that derives its
// expectations from the same un-executed tree agrees with the generator's
// mistake. Calling cobra's own initializers first (they are all exported)
// makes the tree the CLI actually presents.
//
// It is idempotent, and it is the same calls the drift tests in internal/cli
// make (cliRefRoot) -- if the two ever disagree, the reference names a command
// that test calls invented.
func Prepare(root *cobra.Command) *cobra.Command {
	root.InitDefaultHelpCmd()
	root.InitDefaultCompletionCmd()
	root.InitDefaultVersionFlag()
	var walk func(c *cobra.Command)
	walk = func(c *cobra.Command) {
		c.InitDefaultHelpFlag()
		for _, sub := range c.Commands() {
			walk(sub)
		}
	}
	walk(root)
	return root
}

// Generate renders the CLI reference for root: one Markdown section per
// command the tree has and does not hide, in path order, with each command's
// own words (its short and long description), its usage line, its flags with
// their types, defaults and required-ness, and its visible subcommands. It is
// a pure function of the tree, so a test can hold the committed file to it.
//
// It calls Prepare first: see the note there on cobra's own help and
// completion commands.
func Generate(root *cobra.Command) string {
	root = Prepare(root)
	var b strings.Builder
	b.WriteString(header + "\n\n")
	b.WriteString("# Fugaro CLI reference\n\n")
	b.WriteString("Every command and flag `fugaro` ships, generated from the command tree\n")
	b.WriteString("(`internal/cli.NewRootCmd`) by `go run ./ee/clidoc`. Cobra's own `help`\n")
	b.WriteString("and `completion` commands, the root's `-v, --version` flag, and the\n")
	b.WriteString("`-h, --help` flag of every command, are part of what `fugaro --help` lists,\n")
	b.WriteString("so they are here too. Commands the CLI\n")
	b.WriteString("hides are not listed: they are internal, and a hidden command is not user\n")
	b.WriteString("documentation.\n\n")

	byPath := DocumentedCommands(root)
	paths := make([]string, 0, len(byPath))
	for path := range byPath {
		paths = append(paths, path)
	}
	sort.Strings(paths)
	for _, path := range paths {
		writeSection(&b, byPath[path], path)
	}
	return b.String()
}

// DocumentedCommands returns every command under root that neither is hidden
// nor sits under a hidden parent, keyed by its full path ("fugaro budget
// set"). The hidden commands come from the tree itself -- cobra's Hidden field
// -- rather than from a list kept here, so a command that is hidden tomorrow is
// left out tomorrow.
//
// A caller that needs to know which commands a reference covers -- to count
// them, or to hold a subset of them to the file -- reads them here rather than
// walking the tree again, so the rule that decides what is documented stays in
// one place.
func DocumentedCommands(root *cobra.Command) map[string]*cobra.Command {
	out := map[string]*cobra.Command{}
	var walk func(c *cobra.Command, prefix string, documented bool)
	walk = func(c *cobra.Command, prefix string, documented bool) {
		path := commandPath(prefix, c)
		visible := documented && !c.Hidden
		if visible {
			out[path] = c
		}
		for _, sub := range c.Commands() {
			walk(sub, path, visible)
		}
	}
	walk(root, "", true)
	return out
}

// commandPath is the full invocation of c: its ancestors' names, then its own.
func commandPath(prefix string, c *cobra.Command) string {
	return strings.TrimSpace(prefix + " " + c.Name())
}

// writeSection renders one command.
func writeSection(b *strings.Builder, cmd *cobra.Command, path string) {
	fmt.Fprintf(b, "## `%s`\n\n", path)
	if short := cell(cmd.Short); short != "" {
		b.WriteString(short + "\n\n")
	}
	long := strings.TrimSpace(cmd.Long)
	if long != "" && long != strings.TrimSpace(cmd.Short) {
		// The command's own words, verbatim: the reference paraphrases
		// nothing, because a paraphrase is a second copy of a fact.
		b.WriteString(strings.TrimRight(long, "\n") + "\n\n")
	}
	fmt.Fprintf(b, "Usage: `%s`\n\n", usageLine(cmd, path))

	if names := visibleFlagNames(cmd); len(names) == 0 {
		b.WriteString("This command has no flags of its own.\n\n")
	} else {
		b.WriteString("Flags:\n\n")
		b.WriteString("| Flag | Type | Default | Required | Description |\n")
		b.WriteString("| --- | --- | --- | --- | --- |\n")
		for _, name := range names {
			f := cmd.LocalFlags().Lookup(name)
			fmt.Fprintf(b, "| %s | %s | %s | %s | %s |\n",
				flagCell(f), cell(f.Value.Type()), defaultCell(f.DefValue), requiredCell(f), cell(f.Usage))
		}
		b.WriteString("\n")
	}

	b.WriteString("Subcommands:\n\n")
	subs := visibleSubcommands(cmd, path)
	if len(subs) == 0 {
		b.WriteString("This command has no subcommands.\n\n")
		return
	}
	for _, sub := range subs {
		fmt.Fprintf(b, "- `%s` -- %s\n", sub.path, cell(sub.short))
	}
	b.WriteString("\n")
}

// usageLine is the command as a reader types it: its full path followed by
// whatever the command's own Use string puts after its name, so
// `fugaro cancel RUN` and `fugaro budget set (--global | ...)` are the
// command's own words and not a second spelling of them.
func usageLine(cmd *cobra.Command, path string) string {
	rest := strings.TrimSpace(strings.TrimPrefix(strings.TrimSpace(cmd.Use), cmd.Name()))
	if rest == "" {
		return path
	}
	return path + " " + rest
}

// visibleFlagNames returns cmd's own flags -- local and non-inherited, so a
// flag is documented on the command that defines it -- sorted, with the hidden
// ones left out.
func visibleFlagNames(cmd *cobra.Command) []string {
	var names []string
	cmd.LocalFlags().VisitAll(func(f *pflag.Flag) {
		if !f.Hidden {
			names = append(names, f.Name)
		}
	})
	sort.Strings(names)
	return names
}

// subcommand is one line of a command's subcommand list.
type subcommand struct {
	path  string
	short string
}

// visibleSubcommands returns the direct subcommands a reader may be told
// about, in name order.
func visibleSubcommands(cmd *cobra.Command, path string) []subcommand {
	var out []subcommand
	for _, sub := range cmd.Commands() {
		if sub.Hidden {
			continue
		}
		out = append(out, subcommand{path: commandPath(path, sub), short: sub.Short})
	}
	sort.Slice(out, func(i, j int) bool { return out[i].path < out[j].path })
	return out
}

// flagCell is a flag as a reader types it: its shorthand first when it has one
// (`-h, --help`), the long name alone otherwise.
func flagCell(f *pflag.Flag) string {
	if f.Shorthand == "" {
		return "`--" + f.Name + "`"
	}
	return fmt.Sprintf("`-%s`, `--%s`", f.Shorthand, f.Name)
}

// requiredCell says whether cobra refuses to run the command without the flag,
// read off the annotation cobra.MarkFlagRequired sets rather than assumed from
// the flag's default.
func requiredCell(f *pflag.Flag) string {
	if _, ok := f.Annotations[cobra.BashCompOneRequiredFlag]; ok {
		return "yes"
	}
	return "no"
}

// defaultCell renders a flag's default. An empty default is not a missing one
// -- it is the empty string -- so it is shown as such rather than as a blank
// cell a reader would take for an omission.
func defaultCell(def string) string {
	if def == "" {
		return `""`
	}
	return "`" + cell(def) + "`"
}

// cell makes text safe in a Markdown table cell: a pipe would end the row and
// a newline would end the table.
func cell(s string) string {
	s = strings.ReplaceAll(s, "\r\n", " ")
	s = strings.ReplaceAll(s, "\n", " ")
	return strings.ReplaceAll(s, "|", "\\|")
}
