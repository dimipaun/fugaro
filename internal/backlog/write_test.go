package backlog

// The red step of plan T4.5's filing half: an item a caller hands to the folder
// becomes a file the format accepts, with an id the folder's own state
// allocated, the index regenerated beside it, and a second filing of the same
// title refused rather than silently numbered twice.

import (
	"os"
	"path/filepath"
	"strings"
	"testing"
)

// newItem is a well-formed filing: everything but the id, which the folder
// allocates.
func newItem(title string) New {
	return New{
		Title:   title,
		Mode:    "pro",
		Area:    "repo",
		FiledBy: "octocat",
		FiledIn: "run:20261024-120000-abcd",
		Date:    "2026-10-24",
		Body:    Body("the round's findings", "the mode files what it leaves open", "clear them", []string{"run `20261024-120000-abcd`"}),
	}
}

// TestWriteFilesAnItemTheFolderAccepts: Write allocates the id from the folder,
// names the file `<id>-<slug>.md`, writes the eight fields D27 requires, and
// leaves a document this package parses — which is the same claim the folder's
// own pin makes over the tree (D26, D27).
func TestWriteFilesAnItemTheFolderAccepts(t *testing.T) {
	dir := filepath.Join(t.TempDir(), Dir)
	item, err := Write(dir, newItem("Review round 2 left 3 findings open"))
	if err != nil {
		t.Fatal(err)
	}
	if item.ID != "20261024-01" {
		t.Errorf("id = %q, want the day's first free sequence (D26)", item.ID)
	}
	name := "20261024-01-review-round-2-left-3-findings-open.md"
	if filepath.Base(item.Path) != name {
		t.Errorf("path = %q, want %s (D26)", item.Path, name)
	}
	doc, err := os.ReadFile(item.Path)
	if err != nil {
		t.Fatal(err)
	}
	got, err := Parse(item.Path, doc)
	if err != nil {
		t.Fatalf("the file Write wrote is not one the folder accepts: %v\n%s", err, doc)
	}
	for _, want := range []string{"## What was left open", "## Why", "## What done looks like", "## Links"} {
		if !strings.Contains(string(doc), want) {
			t.Errorf("the body does not carry %q (D27)", want)
		}
	}
	if got.Status != "open" {
		t.Errorf("status = %q, want open: an item is filed open", got.Status)
	}
	if got.FiledBy != "octocat" || got.FiledIn != "run:20261024-120000-abcd" {
		t.Errorf("front matter = %+v, want the filer and the run it was filed from", got)
	}
}

// TestWriteAllocatesTheNextSequenceAndRegeneratesTheIndex: a second item filed
// the same day takes the next sequence, and the folder's index is the items
// beside it — regenerated by the filing rather than left stale for the pin to
// catch (D26, D28).
func TestWriteAllocatesTheNextSequenceAndRegeneratesTheIndex(t *testing.T) {
	dir := filepath.Join(t.TempDir(), Dir)
	first, err := Write(dir, newItem("Review round 2 left 3 findings open"))
	if err != nil {
		t.Fatal(err)
	}
	second, err := Write(dir, newItem("Review round 4 left 1 finding open"))
	if err != nil {
		t.Fatal(err)
	}
	if second.ID != "20261024-02" {
		t.Errorf("second id = %q, want the day's next sequence (D26)", second.ID)
	}
	index, err := os.ReadFile(filepath.Join(dir, IndexName))
	if err != nil {
		t.Fatal(err)
	}
	items, err := Load(dir)
	if err != nil {
		t.Fatal(err)
	}
	if string(index) != Render(items) {
		t.Errorf("%s is not what the items beside it render to: filing regenerates the index (D28)", IndexName)
	}
	if !strings.Contains(string(index), first.ID) || !strings.Contains(string(index), second.ID) {
		t.Errorf("%s lists neither filed item:\n%s", IndexName, index)
	}
}

// TestWriteFilesTheSameTitleOnAnotherDay: the same title filed on a later day
// is another item, not a second copy of the first — the two runs that filed
// them are different runs, and each item carries its own run and its own date
// — so it is filed under the new day's own sequence, beside the first. The
// slug is what makes the title readable in a listing, not a key: the id is
// the name that must not repeat (D26).
func TestWriteFilesTheSameTitleOnAnotherDay(t *testing.T) {
	dir := filepath.Join(t.TempDir(), Dir)
	first, err := Write(dir, newItem("Review round 2 left 3 findings open"))
	if err != nil {
		t.Fatal(err)
	}
	later := newItem("Review round 2 left 3 findings open")
	later.Date = "2026-10-25"
	second, err := Write(dir, later)
	if err != nil {
		t.Fatalf("the same title on another day was refused: %v", err)
	}
	want := "20261025-01-review-round-2-left-3-findings-open.md"
	if filepath.Base(second.Path) != want {
		t.Errorf("path = %q, want %s: the later day's own sequence (D26)", second.Path, want)
	}
	if second.ID == first.ID {
		t.Errorf("both filings took the id %s: two items may not share an id (D26)", first.ID)
	}
	items, err := Load(dir)
	if err != nil {
		t.Fatal(err)
	}
	if len(items) != 2 {
		t.Fatalf("the folder holds %d items, want both filings", len(items))
	}
	index, err := os.ReadFile(filepath.Join(dir, IndexName))
	if err != nil {
		t.Fatal(err)
	}
	for _, id := range []string{first.ID, second.ID} {
		if !strings.Contains(string(index), id) {
			t.Errorf("%s does not list %s:\n%s", IndexName, id, index)
		}
	}
}

// TestWriteRefusesAnItemTheFolderAlreadyHolds: the same title filed twice on
// one day would be two files saying the same thing about the same day —
// `<id>-<slug>.md` with a sequence apart — so the second filing is refused and
// the folder is left exactly as it was.
func TestWriteRefusesAnItemTheFolderAlreadyHolds(t *testing.T) {
	dir := filepath.Join(t.TempDir(), Dir)
	first, err := Write(dir, newItem("Review round 2 left 3 findings open"))
	if err != nil {
		t.Fatal(err)
	}
	before, err := os.ReadFile(filepath.Join(dir, IndexName))
	if err != nil {
		t.Fatal(err)
	}
	_, err = Write(dir, newItem("Review round 2 left 3 findings open"))
	if err == nil {
		t.Fatal("a second filing of the same title was accepted")
	}
	if !strings.Contains(err.Error(), first.ID) {
		t.Errorf("the refusal does not name the item already there: %v", err)
	}
	entries, err := os.ReadDir(dir)
	if err != nil {
		t.Fatal(err)
	}
	if len(entries) != 2 {
		t.Errorf("the folder holds %d files after a refused filing, want the item and the index", len(entries))
	}
	after, err := os.ReadFile(filepath.Join(dir, IndexName))
	if err != nil {
		t.Fatal(err)
	}
	if string(after) != string(before) {
		t.Errorf("a refused filing rewrote %s", IndexName)
	}
}

// TestWriteRefusesAFilingItCannotRender: every value the format requires is
// checked before anything is written, so a filing that cannot become a file the
// folder accepts leaves no file at all.
func TestWriteRefusesAFilingItCannotRender(t *testing.T) {
	cases := []struct {
		name string
		mut  func(*New)
		want string
	}{
		{"no title", func(n *New) { n.Title = "" }, "title"},
		{"a title with no word to make a slug from", func(n *New) { n.Title = "!!!" }, "slug"},
		{"a title of two lines", func(n *New) { n.Title = "one\ntwo" }, "title"},
		{"no mode", func(n *New) { n.Mode = "" }, "mode"},
		{"no filer", func(n *New) { n.FiledBy = "" }, "filed-by"},
		{"a date that is not a day", func(n *New) { n.Date = "2026-10-24T10:00:00Z" }, "date"},
		{"a filed-in that is none of the three", func(n *New) { n.FiledIn = "somewhere" }, "filed-in"},
		{"a body with no heading", func(n *New) { n.Body = "the thing." }, "heading"},
	}
	for _, tc := range cases {
		t.Run(tc.name, func(t *testing.T) {
			dir := filepath.Join(t.TempDir(), Dir)
			n := newItem("Review round 2 left 3 findings open")
			tc.mut(&n)
			if _, err := Write(dir, n); err == nil {
				t.Fatal("the filing was accepted")
			} else if !strings.Contains(err.Error(), tc.want) {
				t.Errorf("the refusal does not name %q: %v", tc.want, err)
			}
			if entries, err := os.ReadDir(dir); err == nil && len(entries) != 0 {
				t.Errorf("a refused filing wrote %d files", len(entries))
			}
		})
	}
}

// closeFolder is one open item in a folder of its own, with a snapshot of the
// two files a close can touch: what a refused close has to leave exactly as it
// was.
func closeFolder(t *testing.T) (dir string, item Item, snapshot func() (string, string)) {
	t.Helper()
	dir = filepath.Join(t.TempDir(), Dir)
	item, err := Write(dir, newItem("Review round 2 left 3 findings open"))
	if err != nil {
		t.Fatal(err)
	}
	snapshot = func() (string, string) {
		t.Helper()
		doc, err := os.ReadFile(item.Path)
		if err != nil {
			t.Fatal(err)
		}
		index, err := os.ReadFile(filepath.Join(dir, IndexName))
		if err != nil {
			t.Fatal(err)
		}
		return string(doc), string(index)
	}
	return dir, item, snapshot
}

// TestCloseFlipsTheStatusAndNamesWhatClosedIt: D31's close, as the folder
// writes it (plan T4.7): the status flips to `closed`, the `## Closed by`
// section names the pull request that fixed the item, and the index is
// regenerated in the same write — so the commit that flips an item is the
// commit that moves its row, which is the state the folder's own guards read
// (D28, D31). The filer's own words are left as they were: closing an item
// adds to somebody's account of what was left open rather than rewriting it.
func TestCloseFlipsTheStatusAndNamesWhatClosedIt(t *testing.T) {
	dir, item, _ := closeFolder(t)
	closed, err := Close(dir, item.ID, "#412")
	if err != nil {
		t.Fatalf("closing %s: %v", item.ID, err)
	}
	if closed.Status != "closed" {
		t.Errorf("status = %q, want closed (D31)", closed.Status)
	}
	if closed.ID != item.ID || closed.Title != item.Title || closed.Path != item.Path {
		t.Errorf("closing changed the item's identity: %+v, want %s's own fields", closed, item.ID)
	}
	// What is returned is the file as the folder reads it, not the struct the
	// close built: the two cannot drift apart.
	doc, err := os.ReadFile(item.Path)
	if err != nil {
		t.Fatal(err)
	}
	back, err := Parse(item.Path, doc)
	if err != nil {
		t.Fatalf("what Close wrote is not an item the folder accepts: %v\n%s", err, doc)
	}
	if back != closed {
		t.Errorf("Close returned %+v, but the file reads as %+v", closed, back)
	}
	if !strings.Contains(string(doc), "## What was left open") || !strings.Contains(string(doc), "the round's findings") {
		t.Errorf("closing rewrote the item's own body:\n%s", doc)
	}
	if !strings.Contains(string(doc), "## Closed by") || !strings.Contains(string(doc), "#412") {
		t.Errorf("the item does not name the pull request that closed it:\n%s", doc)
	}
	// D28's regenerate-and-compare: the index is what the items beside it
	// render to, and a flipped status moves the row and the count line with it.
	index, err := os.ReadFile(filepath.Join(dir, IndexName))
	if err != nil {
		t.Fatal(err)
	}
	items, err := Load(dir)
	if err != nil {
		t.Fatal(err)
	}
	if string(index) != Render(items) {
		t.Errorf("%s is not what the items beside it render to: closing regenerates the index in the same write (D28)", IndexName)
	}
	if !strings.Contains(string(index), "1 item: 0 open, 1 closed, 0 dropped.") {
		t.Errorf("the index does not state the flipped status:\n%s", index)
	}
}

// TestCloseRefusesWhatItCannotClose: a close is a step of the run that fixed an
// item, so an id the folder does not hold, an item that is not open and a
// section that names no pull request are all refused, and a refused close
// leaves the folder byte-for-byte as it was — a second close would append a
// second section to a status that already says what closed it, and a section
// naming no pull request is the item the folder's pin refuses (D31).
func TestCloseRefusesWhatItCannotClose(t *testing.T) {
	for _, tc := range []struct {
		name string
		id   string
		by   string
		want string
	}{
		{"an id the folder does not hold", "20261024-09", "#412", "20261024-09"},
		{"a closing that names no pull request", "20261024-01", "fixed, thanks", "pull request"},
		{"a closing that names nothing", "20261024-01", "", "pull request"},
	} {
		t.Run(tc.name, func(t *testing.T) {
			dir, _, snapshot := closeFolder(t)
			beforeItem, beforeIndex := snapshot()
			if _, err := Close(dir, tc.id, tc.by); err == nil {
				t.Fatal("the close was accepted")
			} else if !strings.Contains(err.Error(), tc.want) {
				t.Errorf("the refusal does not name %q: %v", tc.want, err)
			}
			if afterItem, afterIndex := snapshot(); afterItem != beforeItem || afterIndex != beforeIndex {
				t.Errorf("a refused close rewrote the folder:\nitem:\n%s\nindex:\n%s", afterItem, afterIndex)
			}
		})
	}

	t.Run("an item that is already closed", func(t *testing.T) {
		dir, item, snapshot := closeFolder(t)
		if _, err := Close(dir, item.ID, "#412"); err != nil {
			t.Fatal(err)
		}
		beforeItem, beforeIndex := snapshot()
		if _, err := Close(dir, item.ID, "#413"); err == nil {
			t.Fatal("an item that is already closed was closed again")
		} else if !strings.Contains(err.Error(), "closed") {
			t.Errorf("the refusal does not say the item is closed: %v", err)
		}
		afterItem, afterIndex := snapshot()
		if afterItem != beforeItem || afterIndex != beforeIndex {
			t.Errorf("a second close rewrote the folder:\nitem:\n%s\nindex:\n%s", afterItem, afterIndex)
		}
		if strings.Contains(afterItem, "#413") {
			t.Errorf("the second close's pull request reached the item:\n%s", afterItem)
		}
	})
}

// TestSlugIsLowerKebabWordsFromTheTitle: the slug is the part of the file name a
// reader reads, and D26's rule is lower-kebab words.
func TestSlugIsLowerKebabWordsFromTheTitle(t *testing.T) {
	cases := map[string]string{
		"Review round 2 left 3 findings open": "review-round-2-left-3-findings-open",
		"Fix: the  `null` case (again!)":      "fix-the-null-case-again",
		"  spaced  out  ":                     "spaced-out",
		"ALLCAPS":                             "allcaps",
	}
	for title, want := range cases {
		got, err := Slug(title)
		if err != nil {
			t.Errorf("Slug(%q): %v", title, err)
			continue
		}
		if got != want {
			t.Errorf("Slug(%q) = %q, want %q", title, got, want)
		}
	}
	if _, err := Slug("!!!"); err == nil {
		t.Error("a title with no word in it produced a slug")
	}
}
