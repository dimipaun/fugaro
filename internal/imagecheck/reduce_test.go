func TestReduceUnknownFormatIsUnkeyed(t *testing.T) {
	// §2.5: a dependency file Fugaro cannot read makes the repository
	// unkeyed. A lock file of another ecosystem and a tool file that is not a
	// mise config both state a resolved set the key would otherwise be built
	// without, so neither may be dropped.
	for _, path := range []string{
		"bun.lockb",
		"pubspec.lock",
		"flake.lock",
		"Podfile.lock",
		"packages.lock.json",
		"rust-toolchain.toml",
		".python-version",
		".nvmrc",
		".ruby-version",
	} {
		_, err := Reduce(path, []byte("some lock or tool file"))
		if err == nil {
			t.Errorf("Reduce(%s) reduced a file §2.3 does not name", path)
			continue
		}
		var unkeyed *UnkeyedError
		if !errors.As(err, &unkeyed) || unkeyed.Reason != UnkeyedUnknownFormat {
			t.Errorf("Reduce(%s): %v, want an unknown-format reason", path, err)
		}
		if unkeyed.Path != path {
			t.Errorf("Reduce(%s) refused %s", path, unkeyed.Path)
		}
	}
}

// TestReduceKeyLayerFilesContributeNothing: the key-file layer carries more
// than lock files (D620: the install above the source reads them). A file
// that states no resolved version adds no fact and does not make the
// repository unkeyed: its effect is a rebuild, through the image config hash
// and the key files, not a new key.
func TestReduceKeyLayerFilesContributeNothing(t *testing.T) {
	for _, path := range []string{
		"package.json",
		"apps/web/package.json",
		"pnpm-workspace.yaml",
		".npmrc",
		".yarnrc",
		".yarnrc.yml",
		".pnpmfile.cjs",
		".yarn/releases/yarn-4.1.0.cjs",
		".yarn/patches/left-pad-npm-1.3.0.patch",
		"patches/left-pad.patch",
		"mise.toml",
		".tool-versions",
		"mise.lock",
		"docker/thing.Dockerfile",
	} {
		pairs, err := Reduce(path, []byte("what this file holds"))
		if err != nil {
			t.Errorf("Reduce(%s): %v, want no fact and no refusal", path, err)
		}
		if len(pairs) != 0 {
			t.Errorf("Reduce(%s) = %v, want no fact", path, pairs)
		}
	}
}

func TestReduceBoundsInput(t *testing.T) {
	// The bytes come from a checkout the operator does not own, so both the
	// file's size and its entry count are bounded, and a file over either is
	// refused rather than truncated: a truncated set is a different set, and
	// it would take another repository's key.
	huge := `{"packages":{"node_modules/a":{"version":"1.0.0"}}}` + strings.Repeat(" ", maxKeyFileBytes)
	_, err := Reduce("package-lock.json", []byte(huge))
	var unkeyed *UnkeyedError
	if !errors.As(err, &unkeyed) || unkeyed.Reason != UnkeyedTooLarge {
		t.Errorf("a %d-byte lock: %v, want the size cap", len(huge), err)
	}

	var many strings.Builder
	for i := 0; i <= maxKeyFileEntries; i++ {
		many.WriteString("example.invalid/m v1.0.0 h1:aaaa\n")
	}
	_, err = Reduce("go.sum", []byte(many.String()))
	if !errors.As(err, &unkeyed) || unkeyed.Reason != UnkeyedTooManyEntries {
		t.Errorf("%d go.sum lines: %v, want the entry cap", maxKeyFileEntries+1, err)
	}
	// The cap is a cap, not a refusal of large files: a set at the bound is
	// reduced, and the pairs are never truncated to fit.
	fits := strings.Repeat("example.invalid/m v1.0.0 h1:aaaa\n", maxKeyFileEntries)
	pairs := reduced(t, "go.sum", fits)
	if len(pairs) != 1 {
		t.Errorf("a go.sum at the entry cap reduced to %d facts, want the one distinct module", len(pairs))
	}
}

// TestKeyFromReducedSetsIsStable: the reduction feeds Key (§2.4), and two
// files that state the same set — the same facts in another ecosystem's
// format, or the same file read twice — are one key, while a changed version
// is another.
func TestKeyFromReducedSetsIsStable(t *testing.T) {
	npm := reduced(t, "package-lock.json", packageLockFixture)
	yarn := reduced(t, "yarn.lock", yarnLockFixture)
	// The two fixtures state one overlapping set: react and loose-envify are
	// npm's alone. What matters is that each reduction is a plain set of
	// facts, and that Key is a function of exactly those.
	key := func(packages []string) string {
		return Key(Resolved{BaseRef: "web", BaseDigest: baseDigest, Packages: packages, Tools: []string{"node@22.11.0"}})
	}
	if key(npm) != key(npm) {
		t.Error("Key is not a function of the set: reading it twice gave two answers")
	}
	if key(npm) == key(yarn) {
		t.Error("two different sets took one key")
	}
	// The same facts, written in the other file's order, are one key: this is
	// what makes a shared image shared rather than forked per file.
	again := reduced(t, "yarn.lock", `left-pad@^1.3.0:
  version "1.3.0"
"@scope/pkg@^2.0.0":
  version "2.0.0"
`)
	if key(again) != key(yarn) {
		t.Errorf("the same yarn.lock in another order: %s and %s", key(again), key(yarn))
	}
}
