// The wants below state a fact with factOf, so that a want says the three
// fields it means: the encoding itself is pinned literally by
// TestReduceThreeFieldsAreEncodedApart and by key_test's canonical form, and a
// change to it fails there rather than passing here.

// reduced is Reduce's answer for one fixture, with the failure that is a
// refusal reported rather than skipped.
func reduced(t *testing.T, path, data string) []string {
	t.Helper()
	pairs, err := Reduce(path, []byte(data))
	if err != nil {
		t.Fatalf("Reduce(%s): %v", path, err)
	}
	return pairs
}

// reducedKey is the key a set of facts takes, so that a test can compare two
// reductions as the key they would produce rather than as text.
func reducedKey(t *testing.T, path, data string) string {
	t.Helper()
	return Key(Resolved{BaseRef: "web", BaseDigest: baseDigest, Packages: reduced(t, path, data), Tools: []string{"node@22.11.0"}})
}

// refused is the *UnkeyedError Reduce returned for a file it must not reduce,
// with the reason class the test expects.
func refused(t *testing.T, path, data string, reason UnkeyedReason) {
	t.Helper()
	_, err := Reduce(path, []byte(data))
	var unkeyed *UnkeyedError
	switch {
	case err == nil:
		t.Errorf("Reduce(%s) reduced %q", path, data)
		return
	case !errors.As(err, &unkeyed):
		t.Errorf("Reduce(%s): %v, want an unkeyed refusal", path, err)
		return
	}
	if unkeyed.Reason != reason {
		t.Errorf("Reduce(%s): %v, want the %s reason", path, err, reason)
	}
	if unkeyed.Path != path {
		t.Errorf("Reduce(%s) refused %s", path, unkeyed.Path)
	}
}

func TestReducePackageLockToNameAndVersion(t *testing.T) {
	// npm's lock and its shrinkwrap name are one format: a repository's lock
	// file is whichever name npm wrote, and the two reduce alike. Each fact is
	// the entry's own integrity beside its name and version (D618), written as
	// an empty third field when the entry states none — which only an entry
	// resolved from the default registry may have
	// (TestReduceEmptyIntegrityNeedsTheDefaultRegistry).
	want := []string{
		factOf("@scope/pkg", "2.0.0", ""),
		factOf("left-pad", "1.3.0", "sha512-aaa"),
		factOf("loose-envify", "1.4.0", ""),
		factOf("react", "18.3.1", "sha512-bbb"),
	}
	for _, path := range []string{"package-lock.json", "package-lock.json", "npm-shrinkwrap.json"} {
		if got := reduced(t, path, packageLockFixture); !slices.Equal(got, want) {
			t.Errorf("Reduce(%s) = %v, want %v", path, got, want)
		}
	}
	// A nested path's name is the path after the last node_modules/, and the
	// root entry is the repository itself, not a dependency.
	if got := reduced(t, "package-lock.json", `{"packages":{"":{"name":"app","version":"9.9.9"},"node_modules/a/node_modules/b":{"version":"2.0.0","resolved":"https://registry.npmjs.org/b/-/b-2.0.0.tgz"}}}`); !slices.Equal(got, []string{factOf("b", "2.0.0", "")}) {
		t.Errorf("a nested entry or the root entry: %v", got)
	}
	// A workspace member's entry is written under its own path and names
	// itself, which is the name the lock states for it.
	if got := reduced(t, "package-lock.json", `{"packages":{"":{"name":"app","version":"9.9.9"},"packages/a":{"name":"@app/a","version":"1.0.0"}}}`); !slices.Equal(got, []string{factOf("@app/a", "1.0.0", "")}) {
		t.Errorf("a workspace member's own entry: %v", got)
	}
	// An entry with no version states no resolved version (a link or a
	// workspace member's own entry): it is not a fact, and it is skipped.
	if got := reduced(t, "package-lock.json", `{"packages":{"":{},"node_modules/a":{"link":true},"node_modules/b":{"version":"1.0.0","resolved":"https://registry.npmjs.org/b/-/b-1.0.0.tgz"}}}`); !slices.Equal(got, []string{factOf("b", "1.0.0", "")}) {
		t.Errorf("an entry with no version: %v", got)
	}
	// npm 6's lock has no packages map: it nests each package's dependencies
	// under it, and every level states a version, a resolved tarball and an
	// integrity of its own.
	v1 := `{"name":"app","lockfileVersion":1,"dependencies":{"left-pad":{"version":"1.3.0","resolved":"https://registry.npmjs.org/left-pad/-/left-pad-1.3.0.tgz","integrity":"sha512-aaa","dependencies":{"loose-envify":{"version":"1.4.0","resolved":"https://registry.npmjs.org/loose-envify/-/loose-envify-1.4.0.tgz"}}}}}`
	if got := reduced(t, "package-lock.json", v1); !slices.Equal(got, []string{factOf("left-pad", "1.3.0", "sha512-aaa"), factOf("loose-envify", "1.4.0", "")}) {
		t.Errorf("a lockfileVersion 1 lock: %v", got)
	}
	// npm writes an integrity for the tarball it packed for a file: dependency
	// and for the archive it built a git checkout into, so a source that is not
	// the registry's is refused beside an integrity as well as without one: the
	// integrity is of an artifact no digest of the registry's own can be
	// compared with, and the name and version beside it do not say which one
	// this is (D618).
	for _, resolved := range []string{
		"file:vendor/a-1.0.0.tgz",
		"git+https://example.invalid/owner/repo-a.git#aaaa",
	} {
		refused(t, "package-lock.json", `{"packages":{"node_modules/a":{"version":"1.0.0","resolved":"`+resolved+`","integrity":"sha512-aaa"}}}`, UnkeyedNonRegistry)
		refused(t, "package-lock.json", `{"lockfileVersion":1,"dependencies":{"a":{"version":"1.0.0","resolved":"`+resolved+`","integrity":"sha512-aaa"}}}`, UnkeyedNonRegistry)
	}
}

// TestReducePackageLockEntryUnderABareNodeModulesSegment: a path that ends at
// node_modules/ names no package after it, so the entry's own name is what says
// which one it is. Reading the empty last segment as the name would drop a
// package the file states out of the key — and a key that omits a package its
// own lockfile resolved is a key another dependency set can share.
func TestReducePackageLockEntryUnderABareNodeModulesSegment(t *testing.T) {
	data := `{"packages":{"":{"name":"app","version":"9.9.9"},` +
		`"node_modules/":{"name":"left-pad","version":"1.3.0",` +
		`"resolved":"https://registry.npmjs.org/left-pad/-/left-pad-1.3.0.tgz","integrity":"sha512-aaa"}}}`
	want := []string{factOf("left-pad", "1.3.0", "sha512-aaa")}
	if got := reduced(t, "package-lock.json", data); !slices.Equal(got, want) {
		t.Errorf("an entry under a bare node_modules/ path = %v, want %v", got, want)
	}
	// An entry under that path which names nothing still names nothing: it is
	// skipped, never keyed with an empty name.
	nameless := `{"packages":{"node_modules/":{"version":"1.0.0",` +
		`"resolved":"https://registry.npmjs.org/x/-/x-1.0.0.tgz"}}}`
	if got := reduced(t, "package-lock.json", nameless); len(got) != 0 {
		t.Errorf("a nameless entry under a bare node_modules/ path = %v, want no fact", got)
	}
}

// TestUnkeyedErrorNamesEveryReason: each reason a key file can be refused with
// reads as a clause of its own in the error, so a reason whose case is missing
// from Error fails here rather than reaching an operator as a refusal with no
// reason written in it.
func TestUnkeyedErrorNamesEveryReason(t *testing.T) {
	for _, reason := range []UnkeyedReason{UnkeyedUnknownFormat, UnkeyedUnpinned, UnkeyedUnreadable,
		UnkeyedNonRegistry, UnkeyedTooLarge, UnkeyedTooManyEntries} {
		err := (&UnkeyedError{Path: "package-lock.json", Reason: reason}).Error()
		clause, _, ok := strings.Cut(err, ", so this repository is unkeyed")
		if !ok {
			t.Fatalf("the error for %s does not read as an unkeyed refusal: %q", reason, err)
		}
		if _, why, found := strings.Cut(clause, ": "); !found || why == "" {
			t.Errorf("the error for %s states no reason: %q", reason, err)
		}
	}
}

func TestReducePnpmLock(t *testing.T) {
	// A package's integrity is in its packages entry's resolution, and a
	// snapshots entry of the same package adds no fact of its own.
	want := []string{
		factOf("left-pad", "1.3.0", "sha512-aaa"),
		factOf("react", "18.3.1", "sha512-bbb"),
		factOf("react-dom", "18.3.1", ""),
	}
	if got := reduced(t, "pnpm-lock.yaml", pnpmLockFixture); !slices.Equal(got, want) {
		t.Errorf("Reduce(pnpm-lock.yaml) = %v, want %v", got, want)
	}
	// A lockfileVersion 6.0 lock — pnpm 8 — writes the registry path's leading
	// slash; the name is what the key states, without it.
	if got := reduced(t, "pnpm-lock.yaml", "packages:\n  /left-pad@1.3.0: {}\n"); !slices.Equal(got, []string{factOf("left-pad", "1.3.0", "")}) {
		t.Errorf("a key with a leading slash: %v", got)
	}
	// A key that states no version is a dependency whose version is not in
	// the file: the repository is unkeyed rather than keyed by what is.
	refused(t, "pnpm-lock.yaml", "packages:\n  left-pad: {}\n", UnkeyedUnreadable)
	// A lockfileVersion 5.x lock — pnpm 5, 6 and 7 — keys every entry
	// `/name/version` instead, with the peer suffixes its resolution was made
	// under on the version's own text. The two shapes share the leading slash
	// and nothing else, and reading a 5.x key as the one this reads would key a
	// fact whose name is the version's text — a package no registry holds —
	// beside the ones the lock does state. So each of them is refused, which
	// leaves every 5.x lock unkeyed.
	refused(t, "pnpm-lock.yaml", pnpmLockfileV5Fixture, UnkeyedUnreadable)
	for _, c := range []struct{ what, data string }{
		{
			"a 5.x key",
			"lockfileVersion: 5.4\npackages:\n  /left-pad/1.3.0:\n    resolution: {integrity: sha512-aaa}\n",
		},
		{
			"a 5.x key with the peer suffixes its resolution was made under, whose last @ is the peer's",
			"lockfileVersion: 5.4\npackages:\n  /react-dom/18.0.0_react@18.0.0:\n    resolution: {integrity: sha512-aaa}\n",
		},
		{
			"a 5.x key for a scoped package, whose name holds a slash of its own",
			"lockfileVersion: 5.4\npackages:\n  /@babel/core/7.24.0: {}\n",
		},
		{
			"a 5.x key in the snapshots section",
			"lockfileVersion: 5.4\nsnapshots:\n  /react-dom/18.0.0_react@18.0.0: {}\n",
		},
	} {
		refused(t, "pnpm-lock.yaml", c.data, UnkeyedUnreadable)
	}
	// A key line this reader cannot read, beside entries it does read, is
	// refused and not dropped: the set would otherwise be short of a package
	// the lock states, and a set read in part is another repository's key.
	refused(t, "pnpm-lock.yaml",
		"lockfileVersion: 5.4\npackages:\n  left-pad@1.3.0:\n    resolution: {integrity: sha512-aaa}\n  /left-pad/1.3.0: {}\n",
		UnkeyedUnreadable)
	// pnpm writes a resolution that does not fit on one line as a block: the
	// integrity is on the line under `resolution:`, and reading only the
	// schema line would key the entry as one that states neither an integrity
	// nor a source.
	block := "packages:\n  left-pad@1.3.0:\n    resolution:\n      integrity: sha512-aaa\n"
	if got := reduced(t, "pnpm-lock.yaml", block); !slices.Equal(got, []string{factOf("left-pad", "1.3.0", "sha512-aaa")}) {
		t.Errorf("a block resolution: %v", got)
	}
	tarball := "packages:\n  left-pad@1.3.0:\n    resolution:\n      tarball: https://example.invalid/left-pad-1.3.0.tgz\n"
	refused(t, "pnpm-lock.yaml", tarball, UnkeyedNonRegistry)
	// A v9 snapshot key carries the peer suffixes the entry's resolution was
	// made under, while the packages entry for the same package is keyed
	// without them. Keying by the text of the key would read one package as
	// two and key a second fact, with no integrity, beside the one the lock
	// states.
	peers := "lockfileVersion: '9.0'\npackages:\n  react-dom@18.3.1:\n    resolution: {integrity: sha512-ccc}\n" +
		"snapshots:\n  react-dom@18.3.1(react@18.3.1):\n    dependencies:\n      react: 18.3.1\n"
	if got := reduced(t, "pnpm-lock.yaml", peers); !slices.Equal(got, []string{factOf("react-dom", "18.3.1", "sha512-ccc")}) {
		t.Errorf("a key with a peer suffix = %v, want the packages entry's fact alone", got)
	}
	// An integrity and a tarball URL may hold a comma, and a split that ignores
	// the quotes cuts the value in two: the fact would then be keyed by text no
	// artifact was hashed into.
	comma := "packages:\n  left-pad@1.3.0:\n    resolution: {integrity: \"sha512-aa,bb\"}\n"
	if got := reduced(t, "pnpm-lock.yaml", comma); !slices.Equal(got, []string{factOf("left-pad", "1.3.0", "sha512-aa,bb")}) {
		t.Errorf("an integrity holding a comma = %v, want the whole integrity", got)
	}
	commaURL := "packages:\n  left-pad@1.3.0:\n    resolution: {tarball: \"https://example.invalid/a,b.tgz\"}\n"
	refused(t, "pnpm-lock.yaml", commaURL, UnkeyedNonRegistry)
}

func TestReduceYarnLock(t *testing.T) {
	// Yarn 1 writes an integrity line, and it is the fact's third field.
	want := []string{factOf("@scope/pkg", "2.0.0", "sha512-aaa"), factOf("left-pad", "1.3.0", "sha512-bbb")}
	if got := reduced(t, "yarn.lock", yarnLockFixture); !slices.Equal(got, want) {
		t.Errorf("Reduce(yarn.lock) = %v, want %v", got, want)
	}
	// Yarn Berry's lock is the same reduction with a colon after version, its
	// checksum is the integrity, and its __metadata block is not an entry:
	// version 8 is the lock's format version, and a package called __metadata
	// does not exist.
	if got := reduced(t, "yarn.lock", yarnBerryLockFixture); !slices.Equal(got, []string{factOf("left-pad", "1.3.0", "10c0/abcdef")}) {
		t.Errorf("a Yarn Berry lock: %v", got)
	}
	// A workspace member is the repository's own tree rather than an artifact
	// any registry served, and it is keyed by the version the lock states for
	// it, with no integrity to carry.
	berry := yarnBerryLockFixture + `
"@app/a@workspace:packages/a":
  version: 0.0.0-use.local
  resolution: "@app/a@workspace:packages/a"
  languageName: unknown
  linkType: soft
`
	if got := reduced(t, "yarn.lock", berry); !slices.Equal(got, []string{factOf("@app/a", "0.0.0-use.local", ""), factOf("left-pad", "1.3.0", "10c0/abcdef")}) {
		t.Errorf("a Berry workspace member: %v", got)
	}
	// Yarn states version, integrity and checksum as bare values at the end of
	// their own lines, and a lock may carry a comment after one — Yarn 1's
	// header line has one to itself. The comment is not part of the value: read
	// into the version it keys a version no file states, and read into an
	// integrity or a checksum it leaves a space in the fact's third field,
	// which no hash holds, so a lock that comments its own lines would lose the
	// repository its key.
	commented := "left-pad@^1.3.0: # the range\n  version \"1.3.0\" # the version\n" +
		"  resolved \"https://registry.yarnpkg.com/left-pad/-/left-pad-1.3.0.tgz#aaaa\" # where it came from\n" +
		"  integrity sha512-aaa # the artifact\n"
	if got := reduced(t, "yarn.lock", commented); !slices.Equal(got, []string{factOf("left-pad", "1.3.0", "sha512-aaa")}) {
		t.Errorf("a Yarn 1 entry with a comment on every line: %v", got)
	}
	berryComment := "__metadata:\n  version: 8\n\n\"left-pad@npm:^1.3.0\":\n  version: 1.3.0\n" +
		"  resolution: \"left-pad@npm:1.3.0\"\n  checksum: 10c0/abcdef # the archive\n"
	if got := reduced(t, "yarn.lock", berryComment); !slices.Equal(got, []string{factOf("left-pad", "1.3.0", "10c0/abcdef")}) {
		t.Errorf("a Berry entry with a comment on its checksum line: %v", got)
	}
	// The integrity line alone, commented, on an entry the default registry did
	// not serve: read into the integrity, the fact's third field holds a space,
	// which no hash does, and the entry is refused rather than keyed by.
	commentedIntegrity := "left-pad@^1.3.0:\n  version \"1.3.0\"\n" +
		"  resolved \"https://npm.example.invalid/left-pad/-/left-pad-1.3.0.tgz\"\n  integrity sha512-aaa # the artifact\n"
	if got := reduced(t, "yarn.lock", commentedIntegrity); !slices.Equal(got, []string{factOf("left-pad", "1.3.0", "sha512-aaa")}) {
		t.Errorf("a comment on the integrity line of another registry's entry: %v", got)
	}
	// An alias and a package resolved from a git repository (Berry's git:
	// scheme, and the codeload URL Yarn 1 writes for a GitHub dependency) are
	// not the registry's: the alias's header names two packages, and a git or
	// archive URL is a source no registry served.
	refused(t, "yarn.lock", "\"lodash@npm:evil-pkg@^1.0.0\":\n  version: 1.0.0\n  resolution: \"lodash@npm:evil-pkg@1.0.0\"\n", UnkeyedNonRegistry)
	refused(t, "yarn.lock", "\"lodash@npm:evil-pkg@^1.0.0\":\n  version \"1.0.0\"\n  resolved \"https://registry.yarnpkg.com/evil-pkg/-/evil-pkg-1.0.0.tgz#aaaa\"\n  integrity sha512-aaa\n", UnkeyedNonRegistry)
	refused(t, "yarn.lock", "\"y@https://github.com/x/y.git#commit=abc\":\n  version: 1.0.0\n  resolution: \"y@https://github.com/x/y.git#commit=abc\"\n", UnkeyedNonRegistry)
	// Berry writes a checksum for the archive it resolved, so the probe is the
	// same entry with one: the checksum is of the repository's commit, not of a
	// registry's tarball, and the header is what says so.
	refused(t, "yarn.lock", "\"y@https://github.com/x/y.git#commit=abc\":\n  version: 1.0.0\n  resolution: \"y@https://github.com/x/y.git#commit=abc\"\n  checksum: 10c0/abcdef\n", UnkeyedNonRegistry)
	refused(t, "yarn.lock", "left-pad@^1.3.0:\n  version \"1.3.0\"\n  resolved \"https://codeload.github.com/x/y/tar.gz/abc\"\n", UnkeyedNonRegistry)
	// Yarn 1's GitHub dependency: package.json's shorthand specifier, which is
	// what the header repeats, resolving to a codeload archive. The resolved URL
	// is a plain https one at a host that is not the default registry's, which
	// no reading of the URL alone can tell from another registry's tarball, and
	// the integrity beside it is the archive's.
	refused(t, "yarn.lock", "\"left-pad@x/y\":\n  version \"1.3.0\"\n  resolved \"https://codeload.github.com/x/y/tar.gz/abc\"\n  integrity sha512-aaa\n", UnkeyedNonRegistry)
	// A header states one descriptor for each range the entry resolved, and
	// every descriptor is a source the entry was resolved from: reading the
	// first one alone keys a header whose second descriptor is a git specifier
	// as the registry's, and the archive beside it is the repository's.
	refused(t, "yarn.lock", "\"left-pad@^1.3.0, left-pad@github:x/y#abc\":\n  version \"1.3.0\"\n  resolved \"https://codeload.github.com/x/y/tar.gz/abc\"\n  integrity sha512-aaa\n", UnkeyedNonRegistry)
	refused(t, "yarn.lock", "\"left-pad@npm:^1.3.0, left-pad@portal:./x\":\n  version: 1.3.0\n  resolution: \"left-pad@npm:1.3.0\"\n  checksum: 10c0/abcdef\n", UnkeyedNonRegistry)
	// The same header with two registry descriptors is one entry: a header is
	// read for its descriptors and not refused for holding more than one.
	if got := reduced(t, "yarn.lock", "\"left-pad@^1.3.0, left-pad@~1.3.0\":\n  version \"1.3.0\"\n  resolved \"https://registry.yarnpkg.com/left-pad/-/left-pad-1.3.0.tgz#bbbb\"\n  integrity sha512-bbb\n"); !slices.Equal(got, []string{factOf("left-pad", "1.3.0", "sha512-bbb")}) {
		t.Errorf("a header with two registry descriptors: %v", got)
	}
}

func TestReduceGoSum(t *testing.T) {
	// One module is one fact: the /go.mod line is the same module at the same
	// version, and the integrity is the module's own hash — the zip's, from the
	// line that is not the /go.mod one.
	want := []string{
		factOf("github.com/pkg/errors", "v0.9.1", "h1:aaaa"),
		factOf("golang.org/x/text", "v0.14.0", "h1:cccc"),
	}
	if got := reduced(t, "go.sum", goSumFixture); !slices.Equal(got, want) {
		t.Errorf("Reduce(go.sum) = %v, want %v", got, want)
	}
	// The order of a module's two lines is the file's, not the fact's.
	swapped := "github.com/pkg/errors v0.9.1/go.mod h1:bbbb\ngithub.com/pkg/errors v0.9.1 h1:aaaa\n"
	if got := reduced(t, "go.sum", swapped); !slices.Equal(got, []string{factOf("github.com/pkg/errors", "v0.9.1", "h1:aaaa")}) {
		t.Errorf("a /go.mod line before the module's: %v", got)
	}
	// A module the file states only a /go.mod line for is one whose zip was
	// never brought in, and the hash the file states for it is what the key
	// takes.
	if got := reduced(t, "go.sum", "github.com/pkg/errors v0.9.1/go.mod h1:bbbb\n"); !slices.Equal(got, []string{factOf("github.com/pkg/errors", "v0.9.1", "h1:bbbb")}) {
		t.Errorf("a module with only a /go.mod line: %v", got)
	}
	// A module path is case-sensitive and is used as the file writes it.
	if got := reduced(t, "go.sum", "github.com/BurntSushi/toml v1.4.0 h1:aaaa\n"); !slices.Equal(got, []string{factOf("github.com/BurntSushi/toml", "v1.4.0", "h1:aaaa")}) {
		t.Errorf("a mixed-case module path: %v", got)
	}
	// A module Go verified twice at one version has two h1 lines, and both are
	// its hashes: reading the last one alone would give the module one fact or
	// another depending on the order the file wrote them in.
	one := "github.com/pkg/errors v0.9.1 h1:aaaa\ngithub.com/pkg/errors v0.9.1 h1:bbbb\n"
	other := "github.com/pkg/errors v0.9.1 h1:bbbb\ngithub.com/pkg/errors v0.9.1 h1:aaaa\n"
	if got := reduced(t, "go.sum", one); !slices.Equal(got, []string{factOf("github.com/pkg/errors", "v0.9.1", "h1:aaaa,h1:bbbb")}) {
		t.Errorf("two h1 lines for one module: %v", got)
	}
	if reducedKey(t, "go.sum", one) != reducedKey(t, "go.sum", other) {
		t.Error("two h1 lines for one module took two keys, one per order")
	}
	// A line without a hash states no artifact: the key cannot carry an
	// integrity the file does not have.
	refused(t, "go.sum", "github.com/pkg/errors v0.9.1\n", UnkeyedUnreadable)
}

func TestReduceRequirements(t *testing.T) {
	// PyPI normalisation folds case and -/_/. to one name (§2.4), so the pin
	// Left_Pad==1.3.0 is the fact left-pad@1.3.0.
	want := []string{factOf("left-pad", "1.3.0", ""), factOf("requests", "2.31.0", ""), factOf("urllib3", "2.0.7", "")}
	if got := reduced(t, "requirements.txt", requirementsFixture); !slices.Equal(got, want) {
		t.Errorf("Reduce(requirements.txt) = %v, want %v", got, want)
	}
	// An extras pin is a pin, and its extras are not part of the version.
	if got := reduced(t, "requirements.txt", "requests[security]==2.31.0\n"); !slices.Equal(got, []string{factOf("requests", "2.31.0", "")}) {
		t.Errorf("a pin with extras: %v", got)
	}
	// A PEP 440 epoch belongs to the version (`5.4.0` of epoch `1`), so the
	// `!` sits in the version half of the pin and is not one of the operators
	// this reader refuses: the pin is keyed rather than read as a line the file
	// left unpinned.
	if got := reduced(t, "requirements.txt", "zope.interface==1!5.4.0\n"); !slices.Equal(got, []string{factOf("zope-interface", "1!5.4.0", "")}) {
		t.Errorf("a pin with an epoch: %v", got)
	}
	// pip-compile writes a requirement's hashes as continuation lines: they
	// are the pin's integrity (D618), and the order a file writes them in is
	// not a fact.
	if got := reduced(t, "requirements.txt", "requests==2.31.0 \\\n    --hash=sha256:aaaa \\\n    --hash=sha256:bbbb\n"); !slices.Equal(got, []string{factOf("requests", "2.31.0", "sha256:aaaa,sha256:bbbb")}) {
		t.Errorf("a pinned requirement with hashes: %v", got)
	}
	if got := reduced(t, "requirements.txt", "requests==2.31.0 --hash=sha256:bbbb --hash=sha256:aaaa\n"); !slices.Equal(got, []string{factOf("requests", "2.31.0", "sha256:aaaa,sha256:bbbb")}) {
		t.Errorf("the same hashes in the other order: %v", got)
	}
	// The marker and the hashes are written together — pip-tools and
	// `uv pip compile --universal` write the pin's environment marker and end
	// the marker with the continuation backslash — so the pin is one pin whose
	// hashes follow it, and the marker is no more a fact than the hashes are.
	marked := "typing-extensions==4.12.2 ; python_version < \"3.11\" \\\n" +
		"    --hash=sha256:aaaa \\\n    --hash=sha256:bbbb\n"
	if got := reduced(t, "requirements.txt", marked); !slices.Equal(got, []string{factOf("typing-extensions", "4.12.2", "sha256:aaaa,sha256:bbbb")}) {
		t.Errorf("a marker and hashes on one pin: %v", got)
	}
	// The same pin without hashes is the shape a hand-written file has.
	if got := reduced(t, "requirements.txt", "typing-extensions==4.12.2 ; python_version < \"3.11\"\n"); !slices.Equal(got, []string{factOf("typing-extensions", "4.12.2", "")}) {
		t.Errorf("a marker with no hashes: %v", got)
	}
}

func TestReduceUnpinnedRequirementsIsUnkeyed(t *testing.T) {
	// A requirements.txt is only a resolved set when every line states a
	// version. One line that does not — an include, an editable install, an
	// unpinned name — means the file does not state what would be installed,
	// and the repository is unkeyed rather than keyed by the pins beside it.
	for _, data := range []string{
		"requests\n",
		"-r base.txt\n",
		"-e .\n",
		"requests>=2.31.0\n",
		"requests~=2.31\n",
		"requests==\n",
	} {
		refused(t, "requirements.txt", data, UnkeyedUnpinned)
	}
	// A line pip takes from somewhere the index does not serve — a URL, a git
	// requirement, a direct reference `name @ https://…` — is not an unpinned
	// name but a source (D618), and it leaves the repository unkeyed for that
	// reason.
	for _, data := range []string{
		"git+https://example.invalid/owner/repo-a.git#egg=thing\n",
		"https://example.invalid/thing-1.0.0-py3-none-any.whl\n",
		"--index-url https://example.invalid/simple\n",
		"thing @ https://example.invalid/thing-1.0.0.tar.gz\n",
	} {
		refused(t, "requirements.txt", data, UnkeyedNonRegistry)
	}
}

