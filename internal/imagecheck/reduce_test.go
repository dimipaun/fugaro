func TestReduceRequirements(t *testing.T) {
	// PyPI normalisation folds case and -/_/. to one name (§2.4), so the pin
	// Left_Pad==1.3.0 is the fact left-pad@1.3.0.
	want := []string{"left-pad@1.3.0", "requests@2.31.0", "urllib3@2.0.7"}
	if got := reduced(t, "requirements.txt", requirementsFixture); !slices.Equal(got, want) {
		t.Errorf("Reduce(requirements.txt) = %v, want %v", got, want)
	}
	// An extras pin is a pin, and its extras are not part of the version.
	if got := reduced(t, "requirements.txt", "requests[security]==2.31.0\n"); !slices.Equal(got, []string{"requests@2.31.0"}) {
		t.Errorf("a pin with extras: %v", got)
	}
	// pip-compile writes a requirement's hashes as continuation lines: they
	// are integrity, not a version, so they are not a fact and not a refusal.
	if got := reduced(t, "requirements.txt", "requests==2.31.0 \\\n    --hash=sha256:aaaa \\\n    --hash=sha256:bbbb\n"); !slices.Equal(got, []string{"requests@2.31.0"}) {
		t.Errorf("a pinned requirement with hashes: %v", got)
	}
}

func TestReduceUnpinnedRequirementsIsUnkeyed(t *testing.T) {
	// A requirements.txt is only a resolved set when every line states a
	// version. One line that does not — an include, a URL, an unpinned name —
	// means the file does not state what would be installed, and the
	// repository is unkeyed rather than keyed by the pins beside it.
	for _, data := range []string{
		"requests\n",
		"-r base.txt\n",
		"-e .\n",
		"git+https://example.invalid/owner/repo-a.git#egg=thing\n",
		"https://example.invalid/thing-1.0.0-py3-none-any.whl\n",
		"--index-url https://example.invalid/simple\n",
		"requests>=2.31.0\n",
		"requests~=2.31\n",
		"requests==\n",
	} {
		_, err := Reduce("requirements.txt", []byte(data))
		if err == nil {
			t.Errorf("Reduce reduced %q, which is not a pin", data)
			continue
		}
		var unkeyed *UnkeyedError
		if !errors.As(err, &unkeyed) || unkeyed.Reason != UnkeyedUnpinned {
			t.Errorf("Reduce(%q): %v, want an unpinned reason", data, err)
		}
	}
}

