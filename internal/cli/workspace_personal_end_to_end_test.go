// e2ePersonalSecrets is the workspace's Secret Manager as the one seam a
// per-secret read has (credsvc.PerSecretSource): the bundle document the side's
// own service loads, and the per-user containers beside it. One type holds both
// because the deployment's does — the service reads both through the one client
// and project, and perSecrets derives the per-secret reader from the bundle's
// own source rather than from a field of its own (dynamicsecrets.go).
//
// The map is mutated while the service runs (the deleted-container scenario) and
// a read arrives from the service's own goroutine, so both halves are held under
// the one lock.
type e2ePersonalSecrets struct {
	mu     sync.Mutex
	doc    []byte
	tokens map[string]string
}

func (s *e2ePersonalSecrets) Latest(context.Context) ([]byte, error) {
	s.mu.Lock()
	defer s.mu.Unlock()
	return s.doc, nil
}

// Value reads one container by its exact ID. A name the map does not hold is
// found=false, which is R6's absence and not a failure — and for the personal
// name it is ErrPersonalTokenAbsent's state (D2974).
func (s *e2ePersonalSecrets) Value(_ context.Context, secretID string) (string, bool, error) {
	s.mu.Lock()
	defer s.mu.Unlock()
	v, ok := s.tokens[secretID]
	return v, ok, nil
}

// store puts one credential value into one container.
func (s *e2ePersonalSecrets) store(name, value string) {
	s.mu.Lock()
	defer s.mu.Unlock()
	s.tokens[name] = value
}

// drop deletes one container, which is the person's token gone.
func (s *e2ePersonalSecrets) drop(name string) {
	s.mu.Lock()
	defer s.mu.Unlock()
	delete(s.tokens, name)
}

// e2ePersonalStand is the shared harness's stand (e2eStand) with the personal
// half beside it: the two databases as FAKES — the member's policy is rewritten
// mid-test, which the harness's own seeder cannot do — the containers, and the
// one flag the exhaustion scenario turns.
type e2ePersonalStand struct {
	*e2eStand
	memberFake *gcpfake.RTDB
	wsFake     *gcpfake.RTDB
	secrets    *e2ePersonalSecrets
	// route is the record the member's own `fugaro update` published for the
	// Bitbucket repository, as C2's own writer writes it. Its address is the
	// workspace's own listener, because the launcher's grant call goes to the
	// address the record carries.
	route creds.Route
	// personToken is the value of person one's own token: generated here, so
	// "the call was served THIS token" is a fact about the bytes.
	personToken string
	// exhaust, while set, makes the fake Anthropic answer the person's own token
	// with a usage limit (429).
	exhaust *atomic.Bool
}

// e2ePersonalStandUp builds the stand: one workspace, one member of it, the
// roster WC3's people are admitted by, the member's route record moving the
// model kind to the workspace, and the two databases behind the two services.
//
// It is e2eStandUp's sibling and not a call of it: the member's database has to
// be seeded here (the switch moves mid-test) and the workspace's service is the
// personal one below, whose readers the harness's builder does not wire.
func e2ePersonalStandUp(t *testing.T, now time.Time) *e2ePersonalStand {
	t.Helper()
	bitbucket := mustCanonical(gitprov.KindBitbucket, e2eBitbucketRepo)
	github := mustCanonical(gitprov.KindGitHub, e2eGitHubRepo)
	st := &e2ePersonalStand{
		e2eStand: &e2eStand{now: now, google: newE2EGoogle(t)},
		exhaust:  &atomic.Bool{},
	}
	st.personToken = e2eValue(t, "the person's own token")
	st.bb = &e2eMemberRun{
		member: e2eMember, firebase: e2eMemberFire, account: e2eBitbucketAccount,
		slug: mustSlug(gitprov.KindBitbucket, e2eBitbucketRepo), provider: gitprov.KindBitbucket,
		canonical: bitbucket, run: e2eBitbucketRun, google: st.google,
	}
	st.gh = &e2eMemberRun{
		member: e2eMember, firebase: e2eMemberFire, account: e2eGitHubAccount,
		slug: mustSlug(gitprov.KindGitHub, e2eGitHubRepo), provider: gitprov.KindGitHub,
		canonical: github, run: e2eGitHubRun, google: st.google,
	}
	projectSide := newE2ESide(t, "the project's")
	workspaceSide := newE2ESide(t, "the workspace's")
	// The listeners are reserved before either database is seeded, because each
	// service's own address is its audience and the record below carries one of
	// them.
	project := newE2EService(t, "the project's service", projectSide)
	workspace := newE2EService(t, "the workspace's service", workspaceSide)
	st.world = &e2eWorld{project: project, workspace: workspace}

	st.secrets = &e2ePersonalSecrets{doc: workspaceSide.bundle(), tokens: map[string]string{}}
	// The fake Anthropic: every token is answered a 200 with a usage block
	// (which is what the meter prices), and — while the exhaustion scenario has
	// the flag set — the PERSON'S OWN token is answered a usage limit instead,
	// which is R7's one move to the shared entries (D2974, D3144).
	workspaceSide.outside.answer(e2eAnthropicHost, func(r *http.Request, _ []byte) e2eAnswer {
		if st.exhaust.Load() && r.Header.Get("Authorization") == "Bearer "+st.personToken {
			return e2eAnswer{
				status: http.StatusTooManyRequests,
				header: http.Header{"Content-Type": {"application/json"}},
				body:   []byte(`{"type":"error","error":{"type":"rate_limit_error","message":"the test's own usage limit"}}`),
			}
		}
		return e2eAnswer{
			header: http.Header{"Content-Type": {"application/json"}},
			body: []byte(`{"id":"msg_e2e","type":"message","role":"assistant","model":"` + e2eModel +
				`","content":[{"type":"text","text":"ok"}],"stop_reason":"end_turn","usage":{"input_tokens":12,"output_tokens":2}}`),
		}
	})

	// The record the member's own update published, with the workspace's own
	// listener as the address the launcher sends its identity token to: C2's
	// writer admits a loopback address (checkServiceURL) and the launcher's own
	// check admits it too (checkSlipServiceURL), which is what lets the grant
	// call below be the real one.
	route := e2eRouteOf(t, routeFacts{}, st.bb)
	route.Address = workspace.address()
	if _, err := creds.RouteRecord(route); err != nil {
		t.Fatalf("the record this stand publishes is not one the record's own writer accepts: %v", err)
	}
	st.route = route

	st.memberFake, st.member = e2ePersonalMemberDatabase(t, st.bb.slug, route, true)
	st.wsFake, st.ws = e2ePersonalWorkspaceDatabase(t)

	startE2EProjectService(t, project, st.e2eStand, projectSide, st.member)
	startE2EPersonalWorkspaceService(t, workspace, st, workspaceSide)
	return st
}

// e2ePersonalMemberDatabase seeds the MEMBER's own database: the published
// policy carrying R9's switch exactly as a member with the switch `on` wrote it,
// each repository's child node, and the one credential-route record this stand's
// run reads. It answers the fake beside the client because the switch moves in
// the middle of the test.
func e2ePersonalMemberDatabase(t *testing.T, slug string, route creds.Route, on bool) (*gcpfake.RTDB, *rtdb.Client) {
	t.Helper()
	fake := gcpfake.NewRTDB(t)
	fake.Set(projectpolicy.PathRulesMarker(), projectpolicy.RulesVersion)
	fake.Set(projectpolicy.PathShared(), json.RawMessage(e2ePersonalPolicy(on)))
	for _, canonical := range []string{mustCanonical(gitprov.KindBitbucket, e2eBitbucketRepo), mustCanonical(gitprov.KindGitHub, e2eGitHubRepo)} {
		provider, repo, _ := strings.Cut(canonical, "/")
		fake.Set(projectpolicy.PathRepo(mustSlug(provider, repo)), json.RawMessage(e2eMemberChild()))
	}
	raw, err := creds.RouteRecord(route)
	if err != nil {
		t.Fatalf("the route this stand publishes was refused by its own writer: %v", err)
	}
	fake.Set(creds.RoutePath(slug), json.RawMessage(raw))
	client, err := rtdb.New(fake.URL, rtdb.Auth{IDToken: func() string { return "" }})
	if err != nil {
		t.Fatalf("the member's fake database's client: %v", err)
	}
	return fake, client
}

// e2ePersonalPolicy is the member's own published policy with R9's switch set as
// `on`: the harness's own policy (e2eMemberPolicy) plus the one field the
// personal half reads. The field is spliced into the decoded node rather than
// respelled, so the two readers of this document — the member's own launch and
// the workspace's service — cannot be handed two policies that differ in
// anything but the switch.
func e2ePersonalPolicy(on bool) string {
	var node map[string]json.RawMessage
	if err := json.Unmarshal([]byte(e2eMemberPolicy()), &node); err != nil {
		panic("the harness's own policy is not JSON: " + err.Error())
	}
	node[creds.PersonSwitchKey] = json.RawMessage(fmt.Sprintf("%t", on))
	out, err := json.Marshal(node)
	if err != nil {
		panic("the policy this stand publishes could not be built: " + err.Error())
	}
	return string(out)
}

// e2ePersonalWorkspaceDatabase seeds the WORKSPACE's own database: C3's
// published node, the record whose cap the meter holds, and the roster the
// launcher class and the grant's own two roster questions read (R3, D3145).
func e2ePersonalWorkspaceDatabase(t *testing.T) (*gcpfake.RTDB, *rtdb.Client) {
	t.Helper()
	fake := gcpfake.NewRTDB(t)
	node, err := projectpolicy.WorkspaceCredentialsNode(e2eWorkspaceNode())
	if err != nil {
		t.Fatalf("the node this stand publishes is not one a Fugaro writes: %v", err)
	}
	fake.Set(projectpolicy.PathWorkspaceCredentials(e2eWorkspace), json.RawMessage(node))
	record := fmt.Sprintf(`{"version": %d, "name": %q, "members": [{"project": %q, "repos": [%q, %q]}], "cap": {"monthly_micros": %d}}`,
		projectpolicy.WorkspaceVersion, e2eWorkspace, e2eMember,
		mustCanonical(gitprov.KindBitbucket, e2eBitbucketRepo), mustCanonical(gitprov.KindGitHub, e2eGitHubRepo), e2eWorkspaceCap)
	fake.Set(projectpolicy.PathWorkspace(e2eWorkspace), json.RawMessage(record))
	client, err := rtdb.New(fake.URL, rtdb.Auth{IDToken: func() string { return "" }})
	if err != nil {
		t.Fatalf("the workspace's fake database's client: %v", err)
	}
	store, err := workspace.NewRosterStore(client, e2eWorkspace)
	if err != nil {
		t.Fatalf("the workspace's roster node cannot be addressed: %v", err)
	}
	// The roster the workspace owner published: two people, one admin, and the
	// mark the workspace wrote into this member's roster (D2818) — the record of
	// "these people launch in this member", which is what the workspace's grant
	// is held to (D3145).
	raw, err := workspace.EncodeRoster(&workspace.Roster{
		Version:   workspace.RosterVersion,
		Mechanism: workspace.MechanismSA,
		People: []workspace.Person{
			{Address: e2ePersonOne, Kind: workspace.KindHuman},
			{Address: e2ePersonTwo, Kind: workspace.KindHuman},
		},
		Admins: []string{e2ePersonOne},
		Grants: []workspace.StoredGrant{
			{Project: e2eMember, User: e2ePersonOne, Role: workspace.RoleOperator},
			{Project: e2eMember, User: e2ePersonTwo, Role: workspace.RoleOperator},
		},
	})
	if err != nil {
		t.Fatalf("the roster this stand publishes is not one its own encoder writes: %v", err)
	}
	fake.Set(store.Path(), json.RawMessage(raw))
	return fake, client
}

// startE2EPersonalWorkspaceService starts the WORKSPACE's credentials service
// with the personal half wired: the same constructors
// credentialsWorkspaceService calls, in the same order, with the two
// assignments it makes — C2's configuration (WC14) and R9's switch (I1) — set
// BEFORE the resolver is built, because the resolver is what reads them.
//
// The two differences from that function are the two seams a hermetic test needs
// and nothing else: the bundle loader is built over the containers (Secret
// Manager's own is the deployment's), and the launcher class is built over this
// test's own key set (a person's ID token is signed here rather than by Google).
func startE2EPersonalWorkspaceService(t *testing.T, s *e2eService, st *e2ePersonalStand, side *e2eSide) {
	t.Helper()
	cfg := e2eBaseConfig(s, side, st.ws)
	cfg.Bundles = &credsvc.BundleLoader{Source: st.secrets}
	auth, err := credsvc.NewAuthenticator(credsvc.AuthConfig{
		Project: e2eWorkspace, Audience: s.address(), FirebaseProject: e2eWorkspace,
		JobAccounts: []string{st.bb.account, st.gh.account},
		Outcomes:    credsvc.RTDBOutcomes{DB: st.ws},
		Keys:        st.google.runs, JobKeys: st.google.jobs,
	})
	if err != nil {
		t.Fatalf("the workspace's service's front door could not be built: %v", err)
	}
	w, err := credsvc.NewWorkspace(credsvc.WorkspaceConfig{
		Project: e2eWorkspace, Audience: s.address(),
		Members: credsvc.WorkspaceMembersOf(e2eWorkspaceNode()),
		Keys:    st.google.runs, JobKeys: st.google.jobs,
		Open: func(databaseURL string) (credsvc.Getter, error) {
			if databaseURL != e2eMemberDatabaseURL {
				return nil, fmt.Errorf("the workspace's service asked for the database %s, and the one member of this stand has its own at %s", databaseURL, e2eMemberDatabaseURL)
			}
			return st.member, nil
		},
		State: &creds.RTDBStore{DB: st.ws}, Kills: st.ws,
	})
	if err != nil {
		t.Fatalf("the workspace's front door could not be built: %v", err)
	}
	meter, err := credsvc.NewWorkspaceMeter(credsvc.WorkspaceMeterConfig{Name: e2eWorkspace, DB: st.ws})
	if err != nil {
		t.Fatalf("the workspace's meter could not be built: %v", err)
	}
	roster, err := workspace.NewRosterStore(st.ws, e2eWorkspace)
	if err != nil {
		t.Fatalf("the workspace's roster node cannot be addressed: %v", err)
	}
	launchers, err := credsvc.NewLaunchers(credsvc.LauncherConfig{
		Audience: s.address(),
		Accounts: []string{e2ePersonOne, e2ePersonTwo},
		Keys:     st.google.jobs,
	})
	if err != nil {
		t.Fatalf("the workspace's launcher class could not be built: %v", err)
	}
	// The two assignments, and the order they are made in: C2's configuration is
	// what the scope reads at construction, and I1's switch is the reader the
	// personal candidate is decided by. A workspace-mode process whose half was
	// wired and whose switch was left at the process's default refuses every call
	// whose slip names a personal token with personalSwitchOff.
	prevPerson, prevSwitch := credsvc.PersonScopeConfigForServe, credsvc.PersonSwitchForServe
	t.Cleanup(func() {
		credsvc.PersonScopeConfigForServe, credsvc.PersonSwitchForServe = prevPerson, prevSwitch
	})
	credsvc.PersonScopeConfigForServe = e2ePersonScopeConfig(roster, launchers, st.ws)
	credsvc.PersonSwitchForServe = credsvc.ScopePersonSwitch()
	resolver, err := credsvc.NewWorkspaceScopeResolver(credsvc.WorkspaceScopeConfig{
		Workspace: w,
		Node:      e2eWorkspaceNodeReader{db: st.ws},
		Meter:     meter,
	})
	if err != nil {
		t.Fatalf("the workspace's resolver could not be built: %v", err)
	}
	cfg.Auth, cfg.Resolver = auth, resolver
	srv, err := credsvc.NewServer(cfg)
	if err != nil {
		t.Fatalf("the workspace's service could not be built: %v", err)
	}
	s.answers(srv)
}

// e2ePersonScopeConfig is C2's configuration as the serve path hands it on: the
// roster's reader, the launcher class and the slip store, all three over the
// workspace's own database. It is a function of its own for the same reason
// credentialsWorkspacePerson is one — the store leaves this file through the
// service's own value and is never held here (internal/creds'
// TestBoundaryAllowsSlipsOnlyViaService).
func e2ePersonScopeConfig(roster credsvc.RosterReader, launchers credsvc.LauncherVerifier, db *rtdb.Client) credsvc.PersonScopeConfig {
	return credsvc.PersonScopeConfig{
		Roster:    roster,
		Launchers: launchers,
		Slips:     &creds.RTDBStore{DB: db},
	}
}

// e2ePersonalLaunch runs the shipped launch side for one person and answers the
// slip id it was handed (empty when the launch asked for none) and what the
// launch printed, as one string.
//
// It replaces the three seams the launch's own call has and nothing else: the
// two gcloud process seams (the account listing and the identity mint, which is
// signed here with the stand's own key), and the warning writer, which is the
// one line a person reads.
func e2ePersonalLaunch(t *testing.T, st *e2ePersonalStand, person, sub, run string) (string, string) {
	t.Helper()
	(&personGcloudStub{configOut: personalAccountJSON, tokenOut: fakeLauncherToken}).use(t)
	prevIdentity, prevGrant, prevWarn := personGrantIdentity, personGrant, launchWarn
	t.Cleanup(func() { personGrantIdentity, personGrant, launchWarn = prevIdentity, prevGrant, prevWarn })
	personGrantIdentity = func(_ context.Context, serviceURL string) (string, error) {
		return st.google.jobs.sign(t, map[string]any{
			"iss":            "https://accounts.google.com",
			"aud":            serviceURL,
			"email":          person,
			"email_verified": true,
			"sub":            sub,
			"iat":            st.now.Unix(),
			"nbf":            st.now.Unix(),
			"exp":            st.now.Add(time.Hour).Unix(),
		}), nil
	}
	// The real grant call, against the workspace's own listener: the address the
	// record carries is the listener's, which is what the launch reads.
	personGrant = personGrantOverService
	var said strings.Builder
	launchWarn = &said

	env := &cloudEnv{lc: &localcfg.Config{
		Name:      e2eMember,
		Workspace: e2eWorkspace,
		Budget:    &localcfg.Budget{RTDBURL: st.memberFake.URL},
		Endpoints: localcfg.Endpoints{NoAuth: true},
	}}
	got := runPersonalEnv(context.Background(), env, &task.Spec{RunID: run}, st.bb.slug, st.bb.account)
	slip := ""
	for _, entry := range got {
		if v, ok := strings.CutPrefix(entry, creds.PersonSlipEnv+"="); ok {
			slip = v
		}
	}
	return slip, said.String()
}

// e2ePersonalClaim claims one slip as the run it was granted for, in the shape
// the runner's own claim makes: the job's ID token in Authorization, the run's
// own identity beside it, the job name, and the slip id. It answers the status
// as well as the body, so a scenario that expects a refusal can assert on it.
func e2ePersonalClaim(t *testing.T, st *e2ePersonalStand, run *e2eMemberRun, slip string) (credsvc.SlipClaimResponse, int) {
	t.Helper()
	url := strings.TrimSuffix(st.world.workspace.address(), "/") + credsvc.SlipClaimPath
	req, err := http.NewRequest(http.MethodPost, url, strings.NewReader(`{}`))
	if err != nil {
		t.Fatalf("building the run's claim call: %v", err)
	}
	req.Header.Set("Content-Type", "application/json")
	req.Header.Set("Accept", "application/json")
	req.Header.Set("Authorization", "Bearer "+run.jobToken(t, st.world.workspace.address(), st.now))
	req.Header.Set(gateway.HeaderRunIdentity, run.runToken(t, st.now))
	req.Header.Set(gateway.HeaderRunJob, e2eJobName)
	req.Header.Set(creds.PersonSlipHeader, slip)
	resp, err := http.DefaultClient.Do(req)
	if err != nil {
		t.Fatalf("the run's claim call: %v", err)
	}
	defer resp.Body.Close()
	body, err := io.ReadAll(resp.Body)
	if err != nil {
		t.Fatalf("reading the claim's answer: %v", err)
	}
	if resp.StatusCode != http.StatusOK {
		return credsvc.SlipClaimResponse{}, resp.StatusCode
	}
	var ans credsvc.SlipClaimResponse
	if err := json.Unmarshal(body, &ans); err != nil {
		t.Fatalf("the claim's answer is not one this contract reads: %v", err)
	}
	return ans, resp.StatusCode
}

// e2ePersonalGateway is e2eGateway with the run's own slip: the workspace's
// upstream carries C1's two header values (gateway.Workspace's SlipID and
// SlipClaim), which is what a workspace-mode service reads the personal
// candidate out of. Both are empty for the run the workspace granted none.
func e2ePersonalGateway(t *testing.T, ctx context.Context, st *e2ePersonalStand, run *e2eMemberRun, route creds.Route, slip, claim string) *gateway.Server {
	t.Helper()
	ids := newE2EIdentities(t, run, st.e2eStand)
	g, err := gateway.Start(ctx, gateway.Options{
		Upstream: gateway.Upstream{
			Kind:    gateway.KindService,
			BaseURL: st.world.project.address(),
			Service: &gateway.Service{
				IDToken:    func(context.Context) (string, error) { return ids.job(st.world.project.address()), nil },
				RunIDToken: func() string { return ids.run },
				Job:        e2eJobName,
			},
		},
		Workspace: &gateway.Workspace{
			Address:    st.world.workspace.address(),
			IDToken:    func(_ context.Context, audience string) (string, error) { return ids.job(audience), nil },
			RunIDToken: func() string { return ids.run },
			Job:        e2eJobName,
			SlipID:     slip,
			SlipClaim:  claim,
		},
		ModelFromWorkspace: route.Holder(creds.KindModel) == creds.HolderWorkspace,
		Prices:             pricing.Embedded(),
		Mode:               gateway.Enforce,
		Cap:                pricing.Micros(50_000_000),
		Log:                slog.New(slog.NewTextHandler(io.Discard, nil)),
	})
	if err != nil {
		t.Fatalf("the run's gateway could not be started: %v", err)
	}
	t.Cleanup(func() {
		c, cancel := context.WithTimeout(context.Background(), 10*time.Second)
		defer cancel()
		_ = g.Close(c)
	})
	g.BeginStage(gateway.Stage{Name: "implement", Model: e2eModel})
	return g
}

// e2ePersonalModelCall is the run's model call, and it answers whatever came
// back: a scenario about a refusal asserts on the status rather than ending the
// test at the call.
func e2ePersonalModelCall(t *testing.T, g *gateway.Server) (int, string) {
	t.Helper()
	body := `{"model":"` + e2eModel + `","max_tokens":16,"messages":[{"role":"user","content":"hello"}]}`
	req, err := http.NewRequest(http.MethodPost, g.URL()+credsvc.MessagesPath, strings.NewReader(body))
	if err != nil {
		t.Fatalf("building the run's model call: %v", err)
	}
	req.Header.Set("x-api-key", g.Token())
	req.Header.Set("content-type", "application/json")
	req.Header.Set("anthropic-version", "2023-06-01")
	resp, err := http.DefaultClient.Do(req)
	if err != nil {
		t.Fatalf("the run's model call: %v", err)
	}
	defer resp.Body.Close()
	answer, err := io.ReadAll(resp.Body)
	if err != nil {
		t.Fatalf("reading the model call's answer: %v", err)
	}
	return resp.StatusCode, string(answer)
}

// e2eAnthropicCalls is every Anthropic call the WORKSPACE's own service made, in
// order. The side's listener records across scenarios, so each scenario takes a
// baseline and compares the count rather than asking for "exactly one call".
func e2eAnthropicCalls(st *e2ePersonalStand) []e2eCall {
	var out []e2eCall
	for _, c := range st.world.workspace.side.outside.answered() {
		if c.host == e2eAnthropicHost {
			out = append(out, c)
		}
	}
	return out
}

// e2eOffSwitch is the switch a process whose personal half is not wired answers
// with: OFF for every project and no error. It stands in for credsvc's own
// unwiredPersonSwitch (the variable's default) in the wiring test below.
type e2eOffSwitch struct{}

func (e2eOffSwitch) PersonSwitchOn(context.Context, string) (bool, error) { return false, nil }

// TestAPersonsTokenEndToEnd is the plan's own acceptance list, one scenario
// each: a roster person stores a token, launches in a member with the switch on
// and is served it; a second person's run in the same member is served the
// shared entry; the switch off serves no personal token; a deleted container
// refuses; an exhausted token moves to the shared entry and that call is
// reserved.
func TestAPersonsTokenEndToEnd(t *testing.T) {
	now := time.Now().UTC()
	st := e2ePersonalStandUp(t, now)
	ctx := context.Background()
	personName, err := secretname.User(e2ePersonOneSub, creds.PersonTokenName)
	if err != nil {
		t.Fatalf("the personal name this stand stores a token under: %v", err)
	}

	// ---- A roster person stores a token and is served it -------------------
	st.secrets.store(personName, st.personToken)
	before := len(e2eAnthropicCalls(st))
	slip, said := e2ePersonalLaunch(t, st, e2ePersonOne, e2ePersonOneSub, st.bb.run)
	if slip == "" {
		t.Fatalf("the launch on a member whose switch is on and whose person holds a token was handed no slip, and it said: %s", said)
	}
	if !strings.Contains(said, "--no-personal-token") || !strings.Contains(said, e2eWorkspace) {
		t.Errorf("the launch said %q, and a launch that draws on the person's own token prints one line naming the workspace and the flag that turns it off (D3142)", said)
	}
	claim, status := e2ePersonalClaim(t, st, st.bb, slip)
	if status != http.StatusOK || claim.ClaimSecret == "" {
		t.Fatalf("the run's claim of the slip it was granted answered %d with a claim secret of %d bytes, want a claimed slip", status, len(claim.ClaimSecret))
	}
	g := e2ePersonalGateway(t, ctx, st, st.bb, st.route, slip, claim.ClaimSecret)
	if code, body := e2ePersonalModelCall(t, g); code != http.StatusOK {
		t.Fatalf("the model call of a run holding a slip naming its own token answered %d %s, want it served", code, body)
	}
	calls := e2eAnthropicCalls(st)
	if len(calls) != before+1 {
		t.Fatalf("the workspace's service made %d Anthropic calls, want exactly one more: the person's own token is served or the call is refused, and the shared entries are never served in its place while it can serve (D2974)", len(calls)-before)
	}
	served := calls[len(calls)-1]
	if served.auth != "Bearer "+st.personToken {
		t.Errorf("the served call presented %q, want the person's own token as a tier-A bearer: the token a slip names is the OWNER's, and a subscription candidate is presented as a bearer (D2962)", served.auth)
	}
	if served.apiKey != "" {
		t.Errorf("the served call also presented an x-api-key, and a subscription token is presented as a bearer alone")
	}
	// A tier-A token reserves nothing of the workspace's money (D2965).
	if spend, found := e2eWorkspaceSpend(t, st.e2eStand); found && spend.Settled() != 0 {
		t.Errorf("the workspace's meter holds %d settled micros after a call served the person's own token, and the subscription tier reserves none of the workspace's cap", spend.Settled())
	}

	// ---- A second person's run is served the shared entry ------------------
	before = len(e2eAnthropicCalls(st))
	spendBefore, _ := e2eWorkspaceSpend(t, st.e2eStand)
	otherSlip, otherSaid := e2ePersonalLaunch(t, st, e2ePersonTwo, e2ePersonTwoSub, st.bb.run)
	if otherSlip != "" || otherSaid != "" {
		t.Fatalf("the launch of a person who holds no token was handed the slip %q and printed %q: holding no token is an ANSWER, not a fault — that person's runs start on the shared entries and the launch says nothing (R8, D3147)", otherSlip, otherSaid)
	}
	g = e2ePersonalGateway(t, ctx, st, st.bb, st.route, "", "")
	if code, body := e2ePersonalModelCall(t, g); code != http.StatusOK {
		t.Fatalf("the model call of a run the workspace granted no slip answered %d %s, want the shared entry", code, body)
	}
	calls = e2eAnthropicCalls(st)
	if len(calls) != before+1 {
		t.Fatalf("the workspace's service made %d Anthropic calls for a run holding no slip, want exactly one on the shared entry", len(calls)-before)
	}
	shared := calls[len(calls)-1]
	if shared.apiKey != st.world.workspace.side.modelKey {
		t.Errorf("the slip-less run was served the credential %q, want the workspace's own shared model key: a run the workspace granted no slip is served the pool exactly as it was before the personal half existed (A3)", shared.apiKey)
	}
	// The shared entry is the PAID tier, so the call is reserved (D3144).
	spendAfter, found := e2eWorkspaceSpend(t, st.e2eStand)
	if !found || spendAfter.Settled() <= spendBefore.Settled() {
		t.Errorf("the workspace's meter holds %d settled micros after a call on the shared entry, want it above the %d it held: a paid call through the pool is charged to the member that made it", spendAfter.Settled(), spendBefore.Settled())
	}

	// ---- A deleted container refuses --------------------------------------
	// The same slip, the same run, the same claim secret: only the container is
	// gone, and the call must be refused rather than falling to the bundle's own
	// entry — which is the SHARED subscription token, served to a run whose slip
	// named a PERSON's (D2974).
	before = len(e2eAnthropicCalls(st))
	st.secrets.drop(personName)
	g = e2ePersonalGateway(t, ctx, st, st.bb, st.route, slip, claim.ClaimSecret)
	if code, _ := e2ePersonalModelCall(t, g); code == http.StatusOK {
		t.Errorf("the model call of a slip naming a personal token whose container is GONE was served, and the missing token is ErrPersonalTokenAbsent's own refusal: it never falls to the bundle's entry in its place (D2974)")
	}
	if got := len(e2eAnthropicCalls(st)); got != before {
		t.Errorf("the workspace's service reached Anthropic %d times for a call whose personal container is gone, want none", got-before)
	}

	// ---- An exhausted token moves to the shared entry ----------------------
	st.secrets.store(personName, st.personToken)
	st.exhaust.Store(true)
	before = len(e2eAnthropicCalls(st))
	spendBefore, _ = e2eWorkspaceSpend(t, st.e2eStand)
	g = e2ePersonalGateway(t, ctx, st, st.bb, st.route, slip, claim.ClaimSecret)
	code, body := e2ePersonalModelCall(t, g)
	st.exhaust.Store(false)
	if code != http.StatusOK {
		t.Fatalf("the model call answered %d %s after the person's own token met a usage limit, want the shared entry served in its place (D2974)", code, body)
	}
	calls = e2eAnthropicCalls(st)
	if len(calls) != before+2 {
		t.Fatalf("the workspace's service made %d Anthropic calls for an exhausted personal token, want two: the token, then the shared entry the walk moves to", len(calls)-before)
	}
	first, second := calls[len(calls)-2], calls[len(calls)-1]
	if first.auth != "Bearer "+st.personToken {
		t.Errorf("the first call presented %q, want the person's own token", first.auth)
	}
	if second.apiKey != st.world.workspace.side.modelKey {
		t.Errorf("the call the walk moved to was served %q, want the workspace's shared model key", second.apiKey)
	}
	// And that call is RESERVED: the shared entry is the paid tier, so the
	// workspace's own cap pays for it (D2965, D3144).
	spendAfter, found = e2eWorkspaceSpend(t, st.e2eStand)
	if !found || spendAfter.Settled() <= spendBefore.Settled() {
		t.Errorf("the workspace's meter holds %d settled micros after the walk moved to the shared entry, want it above the %d it held: the call that followed the exhausted token is a paid call and is reserved", spendAfter.Settled(), spendBefore.Settled())
	}

	// ---- The switch off serves no personal token ---------------------------
	// The slip was granted while the member's switch was on and the member has
	// turned it off since: the call is REFUSED, and the shared entries are not
	// served in the token's place (R9, R11).
	st.memberFake.Set(projectpolicy.PathShared(), json.RawMessage(e2ePersonalPolicy(false)))
	before = len(e2eAnthropicCalls(st))
	g = e2ePersonalGateway(t, ctx, st, st.bb, st.route, slip, claim.ClaimSecret)
	if code, _ := e2ePersonalModelCall(t, g); code == http.StatusOK {
		t.Errorf("the model call of a slip whose member has the personal half OFF was served, and a call that meets the switch off is refused rather than moved to the shared entries (R11)")
	}
	if got := len(e2eAnthropicCalls(st)); got != before {
		t.Errorf("the workspace's service reached Anthropic %d times with the member's switch off, want none", got-before)
	}
}

// TestWorkspaceModeAnswersTheSwitchThroughTheRealReader is I1's wiring test: a
// workspace-mode process installs WC6's real reader on
// credsvc.PersonSwitchForServe, and not the OFF switch the process's variable
// defaults to.
//
// The reader is read off the process's variable here rather than driven through
// a call, and the reason is the builder's own: credentialsWorkspaceService
// builds its key sources with credsvc.NewGoogleKeys(), which reads Google's
// published certificates and holds no seam, so no hermetic test can present that
// process a run identity it signed. What is left to pin here is the assignment
// and the reader's own shape; the behaviour the assignment turns on is
// TestAPersonsTokenEndToEnd's, which builds its service with the same
// credsvc.ScopePersonSwitch() — and that reader is what serves a person's own
// token at all.
func TestWorkspaceModeAnswersTheSwitchThroughTheRealReader(t *testing.T) {
	const workspaceName = "aurora-ws"
	prevSwitch, prevPerson := credsvc.PersonSwitchForServe, credsvc.PersonScopeConfigForServe
	t.Cleanup(func() {
		credsvc.PersonSwitchForServe, credsvc.PersonScopeConfigForServe = prevSwitch, prevPerson
	})
	// The process's variable before the serve path's line: OFF for every project
	// and no error, which is what a workspace-mode process whose personal half is
	// wired but whose switch was not answers — and the answer a call whose slip
	// names a personal token meets as personalSwitchOff.
	credsvc.PersonSwitchForServe = e2eOffSwitch{}

	for n, v := range workspaceServeEnv(workspaceName) {
		t.Setenv(n, v)
	}
	fakeCredentialsService(t)
	_, client := fakeWorkspaceDatabase(t, workspaceName)
	credentialsTest.database = func(context.Context, string, oauth2.TokenSource) (*rtdb.Client, error) {
		return client, nil
	}

	cfg, err := credentialsServiceConfig(context.Background(), os.Getenv, io.Discard)
	if err != nil {
		t.Fatalf("credentialsServiceConfig in workspace mode: %v", err)
	}
	if cfg.Resolver == nil {
		t.Fatal("the workspace's configuration handed the Server no resolver")
	}

	if _, ok := credsvc.PersonSwitchForServe.(e2eOffSwitch); ok {
		t.Fatalf("the serve path left the process's OFF switch in place: a workspace-mode process whose personal half WC14 wired would refuse every call whose slip names a personal token with personalSwitchOff, whatever the member's published policy says (R9)")
	}
	// And what it installed is the SCOPE-AWARE reader rather than another
	// constant: the switch is asked of the member the CALLER's own verified
	// project names, so the read is the call's own Scope.Policy (WC6), and a
	// reader that answers a caller nobody named is the stub's answer under
	// another name. Asked without a scope it must fail, because a policy that
	// could not be read is never a switch that is off (C1, R9).
	on, err := credsvc.PersonSwitchForServe.PersonSwitchOn(context.Background(), e2eMember)
	if err == nil {
		t.Fatalf("the installed switch answered (%v, nil) with no call of its own, want a refusal: the real reader reads the call's own member's published policy, and there is no member of this call", on)
	}
	if on {
		t.Errorf("the installed switch answered (%v, %v) with no scope, want no ON", on, err)
	}
}
