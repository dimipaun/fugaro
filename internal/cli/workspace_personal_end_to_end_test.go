// workspace_personal_end_to_end_test.go is I1's second file: the workspace's
// personal half driven end to end, from a person's grant to the call their run
// makes, over the fakes — and through the serve path a deployment really runs.
//
// **What "end to end" is here.** A person asks the WORKSPACE's service for a
// slip with their own `gcloud` identity; the run the slip is for claims it with
// the two identities a run holds; and the model call that follows is served the
// person's own token, read out of a container. Every side of that is the
// shipped one: the process is built by credentialsServiceConfig — the function
// `fugaro credentials serve` runs, whose workspace branch installs
// credsvc.PersonSwitchForServe and credsvc.PersonScopeConfigForServe — and it
// serves a real credsvc.Server over a real credsvc.NewWorkspace front door, a
// real workspace scope resolver, WC5's real personal reader and WC6's real
// switch reader. The identities are signed and verified rather than stood in
// for, and the databases are real internal/gcpfake Realtime Databases. What is
// faked is what is outside Fugaro: Anthropic (the service's own outbound client
// is the seam a deployment's host resolution is) and Secret Manager (the
// bundle source below, which also reads the per-person containers).
//
// **What is substituted, and why it has to be.** Three things, all of them the
// same shape of thing — a value a deployment reads from Google, which a
// hermetic test cannot reach:
//
//   - the two key sources. credentialsWorkspaceService builds its verifier and
//     its workspace front door with credsvc.NewGoogleKeys(), which reads
//     Google's published certificates and holds no seam, so the test's own keys
//     have to be put on the workspace, on the launcher class and on the
//     process's verifier. credentialsWorkspaceTest is the hook the serve path
//     already has for exactly this, and the rebuild below is the same
//     constructors with the same fields;
//   - the bundle source, which is Secret Manager's in a deployment
//     (Config.Bundles) and is a fixture's here: a source that reads the shared
//     document and the per-person containers, which is what makes "the person's
//     own token was served" a fact about a value and not about a name;
//   - the outbound client (Config.Client), which is where the fake Anthropic is
//     reached and where the month is read before each upstream call goes out.
//
// **What is NOT exercised is a member's own gateway and forwarder**, which
// workspace_end_to_end_test.go already drives: a run's model call reaches a
// credentials service through the gateway, and the gateway's side of that is
// that file's. This one drives the three calls that gateway makes, over the
// service's own routes, so what it pins is the SERVICE's answers rather than a
// second time over the forwarding.
//
// Nothing in this file is, or looks like, a credential: every identity, every
// value and every bundle entry below is generated by the test, and no fixture
// holds a secret-shaped literal (the credentials-service rule).

