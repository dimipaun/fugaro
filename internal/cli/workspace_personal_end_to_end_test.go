// workspace_personal_end_to_end_test.go is I1's own file: the personal half of
// docs/workspace-credentials driven end to end over the fakes, from the launcher
// that asks the workspace for a grant, through the claim the run makes, to the
// model call a workspace-mode service serves the person's own token on — and the
// wiring that makes the last of those possible at all.
//
// **What "end to end" is here.** The launch is the shipped one (runPersonalEnv,
// WC7): it reads the member's own database for the route record and for R9's
// switch, lists the account gcloud would mint with, and asks the workspace's
// real grant route with a signed identity. The service is the real
// credsvc.Server in workspace mode, over a real internal/gcpfake Realtime
// Database, C1's front door and resolver, WC14's roster wiring and WC5's
// personal candidate. The claim is the shipped shape too (C1's claim call, the
// one internal/runner's slipPost makes). What is faked is only what lies outside
// Fugaro: Anthropic, and Secret Manager's containers — e2ePersonalSecrets, the
// one seam a per-secret read has (credsvc.PerSecretSource).
//
// **The two tests, and why both.** TestAPersonsTokenEndToEnd is the plan's
// acceptance list, one scenario each. TestWorkspaceModeAnswersTheSwitchThrough
// TheRealReader pins the serve path's own line — that a workspace-mode process
// installs the SCOPE-AWARE reader and not the process's OFF default — because
// credentialsWorkspaceService builds its two key sources with
// credsvc.NewGoogleKeys(), which reads Google's published certificates and holds
// no seam: a hermetic test cannot hand that process a run identity it signed. So
// the wiring is read off the process's own variable there, and the behaviour it
// turns on is proven here.
//
// Nothing in this file is, or looks like, a credential: every value below is
// generated by e2eValue, and no fixture holds a secret-shaped literal.

