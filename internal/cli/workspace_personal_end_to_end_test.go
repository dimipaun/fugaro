const personalE2ERateLimitedBody = `{"type":"error","error":{"type":"rate_limit_error","message":"usage limit reached"}}`

// personalE2EBundle is this test's Secret Manager: the bundle document a
// deployment reads for its shared credentials, and the per-person containers it
// reads beside it (credsvc.PerSecretSource).
//
// One source rather than two because a deployment's is one: perSecrets reads
// the containers out of the bundle's own source (dynamicsecrets.go), and the
// accessor this account holds is what scopes the names either read may reach.
// It is a fixture, so nothing here is a real credential and the marker read
// answers false for every name — the marker is a workflow secret's and no
// candidate of this test is one.
type personalE2EBundle struct {
	doc []byte
	// values are the per-person containers by their exact Secret Manager id
	// (secretname.User's spelling). A name the map does not hold is the absence
	// R6 falls from and R7 refuses on, which is how the deleted container below
	// is driven without a cloud call.
	values map[string]string
}

func (b *personalE2EBundle) Latest(context.Context) ([]byte, error) { return b.doc, nil }

func (b *personalE2EBundle) Value(_ context.Context, secretID string) (string, bool, error) {
	v, ok := b.values[secretID]
	return v, ok, nil
}

// Marked answers false for every container: no container of this test carries
// the intake's workflow-secret marker, and a name that is not there is an
// unmarked one. It is implemented because the service requires the interface to
// classify a shared container at all (markedContainer), and a source that
// could not answer would refuse every read rather than serve one.
func (b *personalE2EBundle) Marked(context.Context, string) (bool, error) { return false, nil }

var _ credsvc.PerSecretSource = (*personalE2EBundle)(nil)

// personalE2EWatch is the service's outbound client with the workspace's month
// read immediately before every upstream call goes out. It is the one vantage
// point from which "reserved BEFORE the call" is a fact rather than a
// consequence: the month's figure at the moment of the request is what the call
// was charged before it was made, and the answer's own settle is not visible
// from anywhere else until the call is over.
//
// It is internal/credsvc's own wsMeterWatch copied into this package, because
// that one is unexported and the assertion it makes — a subscription call
// reserves nothing of the workspace's money and the paid call that follows it
// does (D2965, D3144) — is one the acceptance below has to make from here.
type personalE2EWatch struct {
	next  http.RoundTripper
	meter *credsvc.WorkspaceMeter

	mu   sync.Mutex
	sent []budget.WorkspaceRoom
	err  error
}

func (w *personalE2EWatch) RoundTrip(r *http.Request) (*http.Response, error) {
	room, err := w.meter.Room(r.Context())
	w.mu.Lock()
	w.sent = append(w.sent, room)
	if err != nil {
		w.err = err
	}
	w.mu.Unlock()
	return w.next.RoundTrip(r)
}

// seen is how many upstream requests the service has made so far, which is what
// lets one test read the calls of its last case off a list every earlier case
// has already appended to.
func (w *personalE2EWatch) seen() int {
	w.mu.Lock()
	defer w.mu.Unlock()
	return len(w.sent)
}

// reservedAt is the room the workspace held when upstream request i went out.
func (w *personalE2EWatch) reservedAt(t *testing.T, i int) budget.WorkspaceRoom {
	t.Helper()
	w.mu.Lock()
	defer w.mu.Unlock()
	if w.err != nil {
		t.Fatalf("the workspace's month could not be read at request %d: %v", i, w.err)
	}
	if i >= len(w.sent) {
		t.Fatalf("the upstream saw %d requests and the test asks for request %d", len(w.sent), i)
	}
	return w.sent[i]
}

// personalE2EStaleSwitch is the switch a serve path that installed no reader
// leaves in place: it answers OFF for every project and records that it was
// asked. Installing it BEFORE the process is built and finding it was never
// asked is what makes "the serve path installed WC6's reader over the call's
// own policy" a fact rather than an inference — a process that kept this reader
// would refuse the personal call below instead of serving it.
type personalE2EStaleSwitch struct {
	mu    sync.Mutex
	asked bool
}

func (s *personalE2EStaleSwitch) PersonSwitchOn(context.Context, string) (bool, error) {
	s.mu.Lock()
	defer s.mu.Unlock()
	s.asked = true
	return false, nil
}

func (s *personalE2EStaleSwitch) wasAsked() bool {
	s.mu.Lock()
	defer s.mu.Unlock()
	return s.asked
}

// personalE2EWorld is the process under test and the parts of its world a test
// reaches into afterwards: the member's policy (which the switch lives in and
// which is flipped between calls), the containers (one of which is deleted),
// the fake outside, and the month's watch.
type personalE2EWorld struct {
	srv      *credsvc.Server
	audience string
	google   *e2eGoogle
	run      *e2eMemberRun
	runID    string
	jobID    string

	wsFake     *gcpfake.RTDB
	memberFake *gcpfake.RTDB
	bundle     *personalE2EBundle
	outside    *e2eOutside
	watch      *personalE2EWatch

	// nameA is the container A's token is stored under. It is built through the
	// grammar rather than written out, so a test cannot state a spelling the
	// intake could never write.
	nameA string

	// spent arms the fake Anthropic's rate limit for the person's own token.
	// It is off until the last case, because a token that is answered a 429 on
	// EVERY call would make every earlier case move to the shared key and prove
	// nothing about the token itself. It is written and read on one goroutine —
	// the test's own, because the service is driven through ServeHTTP rather
	// than over a listener — so it needs no lock.
	spent bool
}

// personalE2EUp builds the workspace-mode process the way `fugaro credentials
// serve` does, and stands the fake Anthropic and the two databases behind it.
//
// switchOn is the member's own published switch at startup, so the one call
// that reads it before any flip is a call of a workspace whose member turned
// the half on.
func personalE2EUp(t *testing.T, switchOn bool) *personalE2EWorld {
	t.Helper()

	// The two package variables the sides meet on are restored on the way out,
	// because a process's own configuration is not a test's to leave behind:
	// the sibling files set and unset them the same way.
	beforePerson := credsvc.PersonScopeConfigForServe
	beforeSwitch := credsvc.PersonSwitchForServe
	t.Cleanup(func() {
		credsvc.PersonScopeConfigForServe = beforePerson
		credsvc.PersonSwitchForServe = beforeSwitch
	})

	env := workspaceServeEnv(e2eWorkspace)
	for name, value := range env {
		t.Setenv(name, value)
	}
	audience := env[envCredentialsServiceURL]

	// The switch a process that installed none would keep. It is installed
	// before the walk and read after it: the serve path's own assignment is the
	// only thing that takes it away.
	stale := &personalE2EStaleSwitch{}
	credsvc.PersonSwitchForServe = stale

	fakeCredentialsService(t)

	// The workspace's own database: the published credentials node the process
	// binds its callers with, the record whose cap the meter reads, and the
	// roster the personal half is built from.
	wsFake := gcpfake.NewRTDB(t)
	node, err := projectpolicy.WorkspaceCredentialsNode(e2eWorkspaceNode())
	if err != nil {
		t.Fatalf("the node these tests publish is not one a Fugaro writes, so they would prove nothing about the read: %v", err)
	}
	wsFake.Set(projectpolicy.PathWorkspaceCredentials(e2eWorkspace), json.RawMessage(node))
	record := fmt.Sprintf(`{"version": %d, "name": %q, "members": [{"project": %q, "repos": [%q]}], "cap": {"monthly_micros": %d}}`,
		projectpolicy.WorkspaceVersion, e2eWorkspace, e2eMember,
		mustCanonical(gitprov.KindGitHub, e2eGitHubRepo), e2eWorkspaceCap)
	wsFake.Set(projectpolicy.PathWorkspace(e2eWorkspace), json.RawMessage(record))

	wsClient := personalE2EClient(t, wsFake)
	store, err := workspace.NewRosterStore(wsClient, e2eWorkspace)
	if err != nil {
		t.Fatalf("the roster store this test publishes through: %v", err)
	}
	raw, err := workspace.EncodeRoster(personalE2ERoster())
	if err != nil {
		t.Fatalf("the roster this test publishes is not one the roster's own encoder writes, so it would prove nothing about the read: %v", err)
	}
	wsFake.Set(store.Path(), json.RawMessage(raw))

	// The member's own database: the policy the switch is read out of — through
	// the CALL's scope, which is what the reader below is built over — the
	// repository's own admission, and nothing else. No routing table is
	// published, so the call is served by the pre-table path exactly as a
	// member's run whose repository was never migrated is.
	memberFake := gcpfake.NewRTDB(t)
	memberFake.Set(projectpolicy.PathShared(), json.RawMessage(personalE2EMemberPolicy(switchOn)))
	memberFake.Set(projectpolicy.PathRepo(mustSlug(gitprov.KindGitHub, e2eGitHubRepo)), json.RawMessage(e2eMemberChild()))
	memberClient := personalE2EClient(t, memberFake)

	google := newE2EGoogle(t)

	// The process reads three databases: its own (the workspace's, twice — once
	// for the node and once for the roster), the member's a call is about (a
	// read-only open through the front door) and nothing else. A URL this test
	// does not know is refused rather than quietly served, which is the
	// read-only fence seen from the test's side.
	credentialsTest.database = func(_ context.Context, url string, _ oauth2.TokenSource) (*rtdb.Client, error) {
		switch url {
		case env[envRTDBURL]:
			return wsClient, nil
		case e2eMemberDatabaseURL:
			return memberClient, nil
		}
		return nil, fmt.Errorf("the process asked for the database %q, and this test's world has the workspace's and %s", url, e2eMemberDatabaseURL)
	}

	// The hook the serve path already has for a test: the configuration it built
	// is answered by the same constructors with this test's own keys on them.
	// What is re-read here is the node the process itself read, so the members
	// the front door resolves are the published ones rather than a second copy.
	var world *personalE2EWorld
	credentialsWorkspaceTest = func(cfg credsvc.WorkspaceScopeConfig) (credsvc.ScopeResolver, error) {
		published, found, err := cfg.Node.WorkspaceNode(context.Background())
		if err != nil || !found {
			t.Fatalf("the node reader the process handed its resolver answered found=%v err=%v, and this test published a node at the workspace's own path", found, err)
		}
		w, err := credsvc.NewWorkspace(credsvc.WorkspaceConfig{
			Project:  e2eWorkspace,
			Audience: audience,
			Members:  credsvc.WorkspaceMembersOf(published),
			Keys:     google.runs,
			JobKeys:  google.jobs,
			Open: func(databaseURL string) (credsvc.Getter, error) {
				if databaseURL != e2eMemberDatabaseURL {
					return nil, fmt.Errorf("the workspace's front door asked for %s, and this test's one member is at %s", databaseURL, e2eMemberDatabaseURL)
				}
				return memberClient, nil
			},
			State: &creds.RTDBStore{DB: wsClient},
			Kills: wsClient,
		})
		if err != nil {
			t.Fatalf("the workspace's front door could not be built: %v", err)
		}
		launchers, err := credsvc.NewLaunchers(credsvc.LauncherConfig{
			Audience: audience,
			Accounts: workspaceRosterLaunchers(personalE2ERoster()),
			Keys:     google.jobs,
		})
		if err != nil {
			t.Fatalf("the workspace's launcher class could not be built: %v", err)
		}
		person := credsvc.PersonScopeConfigForServe
		person.Launchers = launchers
		credsvc.PersonScopeConfigForServe = person
		return credsvc.NewWorkspaceScopeResolver(credsvc.WorkspaceScopeConfig{Workspace: w, Node: cfg.Node, Meter: cfg.Meter})
	}
	t.Cleanup(func() { credentialsWorkspaceTest = nil })

	cfg, err := credentialsServiceConfig(context.Background(), os.Getenv, io.Discard)
	if err != nil {
		t.Fatalf("the workspace-mode serve path refused this world: %v", err)
	}

	// The month the assertions below read is a second meter over the same
	// database and the same record: the service reserves through its own, and
	// both read the one node, so what this one sees at request time is what the
	// call was charged.
	meter, err := credsvc.NewWorkspaceMeter(credsvc.WorkspaceMeterConfig{Name: e2eWorkspace, DB: wsClient})
	if err != nil {
		t.Fatalf("this test's meter over the workspace's own database: %v", err)
	}

	nameA, err := secretname.User(personalE2ESubA, creds.PersonTokenName)
	if err != nil {
		t.Fatalf("the container A's token is stored under is not one the grammar writes: %v", err)
	}

	world = &personalE2EWorld{
		audience:   audience,
		google:     google,
		wsFake:     wsFake,
		memberFake: memberFake,
		nameA:      nameA,
		bundle: &personalE2EBundle{
			doc:    []byte(config.AnthropicSecret + ": " + e2eValue(t, "personal-e2e-model") + "\n"),
			values: map[string]string{nameA: e2eValue(t, "personal-e2e-token")},
		},
		outside: newE2EOutside(t, "the workspace's"),
	}
	world.run = &e2eMemberRun{
		member: e2eMember, firebase: e2eMemberFire,
		account: e2eGitHubAccount, slug: mustSlug(gitprov.KindGitHub, e2eGitHubRepo),
		provider: gitprov.KindGitHub, canonical: mustCanonical(gitprov.KindGitHub, e2eGitHubRepo),
		run: personalE2ERun, google: google,
	}
	now := time.Now()
	world.runID = world.run.runToken(t, now)
	world.jobID = world.run.jobToken(t, audience, now)

	// The bundle and the client are the process's own fields, replaced after the
	// walk rather than inside it: the serve path reads a Secret Manager document
	// and reaches Google's hosts, and neither is a hermetic test's to give it.
	watch := &personalE2EWatch{meter: meter}
	watch.next = world.outside.client().Transport
	cfg.Bundles = &credsvc.BundleLoader{Source: world.bundle}
	cfg.Client = &http.Client{Transport: watch}
	world.watch = watch

	world.outside.answer(e2eAnthropicHost, func(r *http.Request, _ []byte) e2eAnswer {
		jsonHeader := http.Header{"Content-Type": {"application/json"}}
		if world.spent && r.Header.Get("Authorization") == "Bearer "+world.bundle.values[nameA] {
			// The person's own token, spent until a reset an hour out. It is
			// told apart by the credential the call carries, which is what
			// makes "the first attempt was the person's" and "the retry was
			// the shared key" facts about the bytes.
			return e2eAnswer{
				status: http.StatusTooManyRequests,
				header: http.Header{"Content-Type": {"application/json"}, "Retry-After": {"3600"}},
				body:   []byte(personalE2ERateLimitedBody),
			}
		}
		return e2eAnswer{header: jsonHeader, body: []byte(personalE2EAnswerBody)}
	})

	srv, err := credsvc.NewServer(cfg)
	if err != nil {
		t.Fatalf("the workspace's service could not be built: %v", err)
	}
	world.srv = srv
	t.Cleanup(func() {
		if stale.wasAsked() {
			t.Errorf("the switch a serve path that installed no reader leaves in place was asked for a call, so the process never installed WC6's reader over the call's own policy")
		}
	})
	return world
}

// personalE2EClient is one fake database's client, which is the only shape a
// deployment's own client takes to a test: the URL is the fake's and no
// credential is read from anywhere.
func personalE2EClient(t *testing.T, fake *gcpfake.RTDB) *rtdb.Client {
	t.Helper()
	client, err := rtdb.New(fake.URL, rtdb.Auth{IDToken: func() string { return "" }})
	if err != nil {
		t.Fatalf("the fake database's client: %v", err)
	}
	return client
}

// personalE2ERoster is the workspace's own roster: the two people, both of them
// `human` (which is what the launcher class admits and what the grant's step 6a
// asks for), both of them admins (a roster nobody administers does not
// validate), and each holding a grant into the member — which is D2818's mark
// and the whole of what holds a workspace grant to the member a person launches
// for.
//
// The lists are sorted the way a roster's own writer writes them, because the
// document is validated on the way in: people and admins by address, grants by
// project and then by user.
func personalE2ERoster() *workspace.Roster {
	return &workspace.Roster{
		Version:   workspace.RosterVersion,
		Mechanism: workspace.MechanismSA,
		People: []workspace.Person{
			{Address: personalE2EPersonA, Kind: workspace.KindHuman},
			{Address: personalE2EPersonB, Kind: workspace.KindHuman},
		},
		Admins: []string{personalE2EPersonA, personalE2EPersonB},
		Grants: []workspace.StoredGrant{
			{Project: e2eMember, User: personalE2EPersonA, Role: workspace.RoleViewer},
			{Project: e2eMember, User: personalE2EPersonB, Role: workspace.RoleViewer},
		},
	}
}

// personalE2EMemberPolicy is the member's own published policy (R9's switch
// lives in it, at the key C1 spells `personal_workspace_tokens`), and it is the
// tightest policy the calls below can be served under: the repository is
// allowed, the paid key's own account sentinel admits it, the fallback is the
// automatic one a move lands on, the budget names the model the call sends —
// and the switch is the argument, so one test can flip the half off between two
// calls of the SAME slip.
//
// It is written as JSON rather than through a writer because there is none for
// this node: the published policy is what `fugaro project policy publish`
// computes, and this test's subject is not that computation.
func personalE2EMemberPolicy(switchOn bool) string {
	github := mustCanonical(gitprov.KindGitHub, e2eGitHubRepo)
	return `{
		"version": ` + strconv.Itoa(projectpolicy.Version) + `,
		"budget": {"mode": "enforce", "per_run_usd": 5, "allowed_models": ["` + e2eModel + `"]},
		"allow_repos": ["` + github + `"],
		"accounts": {"` + config.AnthropicKeyAccount + `": {"allow_repos": ["` + github + `"]}},
		"credentials": {"fallback": "auto"},
		"personal_workspace_tokens": ` + strconv.FormatBool(switchOn) + `
	}`
}

// personalE2ESwitch flips the member's published switch. There is no cache
// between the call and this node — the scope's own reader is RTDBPolicy over
// the member's database — so the next call is answered by what is written here
// and nothing else.
func (w *personalE2EWorld) setSwitch(t *testing.T, on bool) {
	t.Helper()
	w.memberFake.Set(projectpolicy.PathShared(), json.RawMessage(personalE2EMemberPolicy(on)))
}

// personalE2ECall makes one call against the service in process: no listener,
// because the audience every identity below is minted for is the environment's
// own value rather than an address something is listening on.
func personalE2ECall(t *testing.T, srv *credsvc.Server, path, body string, headers map[string]string) (int, http.Header, string) {
	t.Helper()
	req := httptest.NewRequest(http.MethodPost, path, strings.NewReader(body))
	req.Header.Set("content-type", "application/json")
	for k, v := range headers {
		req.Header.Set(k, v)
	}
	rec := httptest.NewRecorder()
	srv.ServeHTTP(rec, req)
	return rec.Code, rec.Result().Header, rec.Body.String()
}

// runHeaders is the two identities every call of a run presents, plus the job's
// own name: the run's Firebase ID token in the run identity header, the job
// service account's Google ID token in the Authorization bearer, and the job
// the account belongs to. They are what the front door verifies before any
// route reads anything.
func (w *personalE2EWorld) runHeaders() map[string]string {
	return map[string]string{
		"Authorization":           "Bearer " + w.jobID,
		credsvc.HeaderRunIdentity: w.runID,
		credsvc.HeaderRunJob:      e2eJobName,
	}
}

// launcherToken mints one person's own `gcloud` identity: a Google ID token
// with their address, their numeric account id and the audience of the service
// they are asking.
func (w *personalE2EWorld) launcherToken(t *testing.T, address, sub string) string {
	t.Helper()
	now := time.Now()
	return w.google.jobs.sign(t, map[string]any{
		"iss":            "https://accounts.google.com",
		"aud":            w.audience,
		"sub":            sub,
		"email":          address,
		"email_verified": true,
		"iat":            now.Unix(),
		"nbf":            now.Unix(),
		"exp":            now.Add(time.Hour).Unix(),
	})
}

// grant asks for a slip as one person, and answers the service's own reading of
// it: whether the person holds a token, and the slip if they do. A refusal is a
// failure of the fixture rather than an assertion, because every case below is
// about what happens AFTER the grant.
func (w *personalE2EWorld) grant(t *testing.T, address, sub string) creds.PersonGrant {
	t.Helper()
	body := fmt.Sprintf(`{"slug": %q, "run": %q, "account": %q, "name": %q}`,
		w.run.slug, personalE2ERun, e2eGitHubAccount, creds.PersonTokenName)
	status, _, answer := personalE2ECall(t, w.srv, credsvc.SlipPath, body,
		map[string]string{"Authorization": "Bearer " + w.launcherToken(t, address, sub)})
	if status != http.StatusOK {
		t.Fatalf("the grant is answered %d, want the grant's own 200: %s", status, answer)
	}
	granted, err := creds.ParsePersonGrant([]byte(answer))
	if err != nil {
		t.Fatalf("the grant's answer is not one its own reader accepts: %v (%s)", err, answer)
	}
	return granted
}

// claim takes a slip as the run it was granted for, and answers the claim
// secret the run holds from then on. Both identities are presented, because the
// claim is the run's own first call and every run call carries them.
func (w *personalE2EWorld) claim(t *testing.T, slip string) string {
	t.Helper()
	headers := w.runHeaders()
	headers[creds.PersonSlipHeader] = slip
	status, _, body := personalE2ECall(t, w.srv, credsvc.SlipClaimPath, `{"execution":"personal-e2e"}`, headers)
	if status != http.StatusOK {
		t.Fatalf("the claim is answered %d, want the claim's own 200: %s", status, body)
	}
	var answer credsvc.SlipClaimResponse
	if err := json.Unmarshal([]byte(body), &answer); err != nil {
		t.Fatalf("the claim's answer is not one its own reader accepts: %v (%s)", err, body)
	}
	if answer.ClaimSecret == "" {
		t.Fatalf("the claim answered no claim secret, so no call of this run could present one: %s", body)
	}
	return answer.ClaimSecret
}

// messages is the run's model call: the body the gateway forwards, the two
// identities, and — where the run is under a slip — the two slip headers. An
// empty slip is the run a person holds no token for, which is served the shared
// entries exactly as every run was before this half existed.
func (w *personalE2EWorld) messages(t *testing.T, slip, secret string) (int, http.Header, string) {
	t.Helper()
	headers := w.runHeaders()
	if slip != "" {
		headers[creds.PersonSlipHeader] = slip
		headers[creds.PersonSlipClaimHeader] = secret
	}
	return personalE2ECall(t, w.srv, credsvc.MessagesPath, personalE2EMessagesBody, headers)
}

// served is the credential one answer was served by, as the answer itself
// reports it: the name in the credential header and the tier beside it.
func personalE2EServed(header http.Header) (string, string) {
	return header.Get(credsvc.HeaderCredential), header.Get(credsvc.HeaderTier)
}

// TestAPersonsTokenEndToEnd is I1's acceptance, in the five cases the plan
// names: a roster person stores a token, launches in a member with the switch
// on and is served it; a second person's run in the same member is served the
// shared entry; the switch off serves no personal token; a deleted container
// refuses; and an exhausted token moves to the shared entry and that call is
// reserved.
//
// The five run in one world and in that order, because four of them are states
// of the same slip: one grant, one claim, and one call per state. Every
// assertion is made against what the answer says served it (the credential and
// tier headers) and against what the upstream was really handed, so "the
// person's own token" and "the workspace's paid key" are values rather than
// names.
func TestAPersonsTokenEndToEnd(t *testing.T) {
	w := personalE2EUp(t, true)

	// 1. A person who holds a token: the grant finds it, the claim takes the
	// slip, and the call is served the person's own container — tier A, the
	// subscription tier, which is the tier that reserves none of the
	// workspace's money.
	granted := w.grant(t, personalE2EPersonA, personalE2ESubA)
	if !granted.Held {
		t.Fatalf("the grant answered %+v, want a slip: the person's container is in the bundle's containers", granted)
	}
	secret := w.claim(t, granted.Slip)
	status, header, body := w.messages(t, granted.Slip, secret)
	if status != http.StatusOK {
		t.Fatalf("the person's own token was not served: the call is answered %d: %s", status, body)
	}
	if name, tier := personalE2EServed(header); name != w.nameA || tier != credsvc.TierA {
		t.Errorf("the call was served %q at tier %q, want %q at tier %q: a person's own token is the subscription candidate their slip entitles them to",
			name, tier, w.nameA, credsvc.TierA)
	}
	first := w.outside.answered()
	if len(first) != 1 {
		t.Fatalf("the upstream saw %d calls, want the one the person's token paid for: %v", len(first), first)
	}
	if got := first[0].auth; got != "Bearer "+w.bundle.values[w.nameA] {
		t.Error("the call the person's own token paid for did not carry that token")
	}
	if got := w.watch.reservedAt(t, 0).Reserved; got != 0 {
		t.Errorf("the workspace held %v of its money before the subscription call, want nothing: the cap follows the credential actually served (D2965)", got.USD())
	}

	// 2. A second person of the same member who holds no token: R8's ordinary
	// case. The grant answers "no token held" — an answer and not a refusal, so
	// the launcher prints nothing — and the run that follows carries no slip at
	// all, which is a call served the shared entries exactly as it was before
	// this half existed.
	none := w.grant(t, personalE2EPersonB, personalE2ESubB)
	if none.Held || none.Slip != "" {
		t.Fatalf("the grant for a person who holds no token answered %+v, want no slip and no refusal", none)
	}
	status, header, body = w.messages(t, "", "")
	if status != http.StatusOK {
		t.Fatalf("a run whose person holds no token is answered %d, want the shared entry's 200: %s", status, body)
	}
	if name, tier := personalE2EServed(header); name != config.AnthropicSecret || tier != credsvc.TierB {
		t.Errorf("the shared entry served the call as %q at tier %q, want %q at tier %q", name, tier, config.AnthropicSecret, credsvc.TierB)
	}
	second := w.outside.answered()
	if len(second) != 2 {
		t.Fatalf("the upstream saw %d calls, want this one beside the person's: %v", len(second), second)
	}
	if got := second[1].apiKey; got == "" {
		t.Error("the shared paid key was not presented as the model key it is (x-api-key)")
	}

	// 3. The switch off, under the SAME slip: R11's answer. A slip exists only
	// because the switch was on when it was granted, so a call that meets it
	// off is a run the member turned the half off under — refused, and NOT
	// moved to the shared entries, which is the whole of what R11 is for. The
	// shared entry is deliberately not served here, and the count of upstream
	// calls is what says so rather than the header alone.
	w.setSwitch(t, false)
	before := len(w.outside.answered())
	status, header, body = w.messages(t, granted.Slip, secret)
	if status != http.StatusServiceUnavailable {
		t.Fatalf("a call under a slip whose member has the switch off is answered %d, want the state class: %s", status, body)
	}
	if !strings.Contains(body, "personal workspace token switch off") {
		t.Errorf("the refusal does not say the switch is off, and a member reads that sentence to find it: %s", body)
	}
	if name, _ := personalE2EServed(header); name == config.AnthropicSecret {
		t.Error("the call was moved to the shared paid entry, and R11 refuses it instead: a run the member turned the half off under draws nothing")
	}
	if got := len(w.outside.answered()); got != before {
		t.Errorf("the upstream saw %d calls, want the %d it had: a refused call spends no credential", got, before)
	}

	// ... and on again, under the same slip: the switch is read per CALL, out
	// of the member's published policy and not out of a copy taken at startup,
	// so the very next call is served again.
	w.setSwitch(t, true)
	status, header, body = w.messages(t, granted.Slip, secret)
	if status != http.StatusOK {
		t.Fatalf("the call after the switch was turned back on is answered %d: %s", status, body)
	}
	if name, tier := personalE2EServed(header); name != w.nameA || tier != credsvc.TierA {
		t.Errorf("the call after the switch was turned back on was served %q at tier %q, want %q at tier %q", name, tier, w.nameA, credsvc.TierA)
	}

	// 4. The container deleted. A slip exists because a grant FOUND one (R8), so
	// an absence discovered at call time is the refusal class and never the
	// absence one: the shared entry is not served in the person's place, which
	// is D2974 and the reason a personal name has no fall to a bundle entry of
	// the same name.
	saved := w.bundle.values[w.nameA]
	delete(w.bundle.values, w.nameA)
	before = len(w.outside.answered())
	status, _, body = w.messages(t, granted.Slip, secret)
	if status != http.StatusServiceUnavailable {
		t.Fatalf("a call whose person's container is gone is answered %d, want the state class: %s", status, body)
	}
	if !strings.Contains(body, "fugaro secrets user set") {
		t.Errorf("the refusal does not name the command that stores a token, and that command is what a person reads to fix it: %s", body)
	}
	if got := len(w.outside.answered()); got != before {
		t.Errorf("the upstream saw %d calls, want the %d it had: a refusal serves nothing", got, before)
	}
	w.bundle.values[w.nameA] = saved

	// 5. The token exhausted: the one move R7 allows. The first attempt is the
	// person's own token, the fake answers the rate limit Anthropic answers,
	// and the call is retried on the shared paid entry — which, being the paid
	// one, is RESERVED before it goes out. The two readings are the month as
	// the meter saw it at each upstream request, which is the only vantage
	// point from which "before the call" is a fact.
	w.spent = true
	at := w.watch.seen()
	status, header, body = w.messages(t, granted.Slip, secret)
	if status != http.StatusOK {
		t.Fatalf("the call after the move is answered %d, want the shared entry's 200: %s", status, body)
	}
	if name, tier := personalE2EServed(header); name != config.AnthropicSecret || tier != credsvc.TierB {
		t.Errorf("the exhausted call did not move to the shared paid key: it was served %q at tier %q", name, tier)
	}
	tries := w.outside.answered()[at:]
	if len(tries) != 2 {
		t.Fatalf("the upstream saw %d calls for the exhausted one, want the person's token and the key it moved to: %v", len(tries), tries)
	}
	if got := tries[0].auth; got != "Bearer "+w.bundle.values[w.nameA] {
		t.Error("the exhausted call's first attempt did not carry the person's own token")
	}
	if tries[1].apiKey == "" {
		t.Error("the retry did not carry the shared paid key")
	}
	if got := w.watch.reservedAt(t, at).Reserved; got != 0 {
		t.Errorf("the workspace held %v of its money before the person's own token went out, want nothing (D2965)", got.USD())
	}
	if got := w.watch.reservedAt(t, at+1).Reserved; got == 0 {
		t.Error("the paid call the move lands on was not reserved before it went out, and the cap follows the credential actually served (D3144)")
	}
}

// TestWorkspaceModeAnswersTheSwitchThroughTheRealReader is the other half of
// I1's wiring, and it is one test because the two facts are one mechanism: the
// switch a workspace-mode process reads a call's member with is WC6's reader
// over the CALL's own published policy — built by credsvc, installed by the
// CLI's serve path, and asked per call rather than per process.
//
// The two readings it makes:
//
//   - the reader the process was handed BEFORE it ran is a switch that answers
//     OFF and records that it was asked. The call below is served the person's
//     own token, so the serve path's own assignment is what answered it: a
//     process that kept the installed one would refuse the call with
//     personalSwitchOff, and one that asked it at all fails the check the
//     constructor registers;
//   - the SAME slip is presented across a flip of the member's published
//     switch, served, refused and served again. That is what makes the read the
//     call's own policy rather than a copy taken when the process started: the
//     member's node has no cache between it and the scope's reader, so a switch
//     written between two calls is read between two calls.
func TestWorkspaceModeAnswersTheSwitchThroughTheRealReader(t *testing.T) {
	w := personalE2EUp(t, true)

	granted := w.grant(t, personalE2EPersonA, personalE2ESubA)
	if !granted.Held {
		t.Fatalf("the grant answered %+v, want a slip", granted)
	}
	secret := w.claim(t, granted.Slip)

	status, header, body := w.messages(t, granted.Slip, secret)
	if status != http.StatusOK {
		t.Fatalf("the personal call is answered %d, want it served: a process that kept the switch it was handed before it ran would refuse it: %s", status, body)
	}
	if name, tier := personalE2EServed(header); name != w.nameA || tier != credsvc.TierA {
		t.Errorf("the call was served %q at tier %q, want %q at tier %q", name, tier, w.nameA, credsvc.TierA)
	}

	// Off, under the same slip and the same claim secret.
	w.setSwitch(t, false)
	status, _, body = w.messages(t, granted.Slip, secret)
	if status != http.StatusServiceUnavailable || !strings.Contains(body, "personal workspace token switch off") {
		t.Fatalf("the call under the switch off is answered %d (%s), want the state class and the switch's own sentence: the member's published policy is what the switch is read out of",
			status, body)
	}

	// ... and on again: the same slip, the same secret, served because the
	// policy was read again.
	w.setSwitch(t, true)
	status, header, body = w.messages(t, granted.Slip, secret)
	if status != http.StatusOK {
		t.Fatalf("the call after the switch was turned back on is answered %d: %s", status, body)
	}
	if name, tier := personalE2EServed(header); name != w.nameA || tier != credsvc.TierA {
		t.Errorf("the call after the switch was turned back on was served %q at tier %q, want %q at tier %q", name, tier, w.nameA, credsvc.TierA)
	}
}
