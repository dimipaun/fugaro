const (
	// backlogDir is the folder the items live in, relative to the repository
	// root, and backlogFormat the hand-written document stating the format.
	// README.md, the folder's third file, is generated: it is the index D28
	// specifies, and the two guards over it are at the end of this file.
	backlogDir    = "docs/backlog"
	backlogFormat = "docs/backlog/FORMAT.md"
	// backlogIndex is the generated index, and backlogIndexHeader its first
	// line: the "generated by <command>; do not edit" mark every generated
	// document in this tree carries, naming the one command that rewrites it.
	backlogIndex       = "docs/backlog/README.md"
	backlogIndexHeader = "<!-- generated by fugaro backlog index; do not edit -->"
)

// backlogItemNameRE is D26's file name: the id (the day an item was filed and
// a two-digit sequence that day) and a lower-kebab slug from the title.
var backlogItemNameRE = regexp.MustCompile(`^([0-9]{8}-[0-9]{2})-[a-z0-9]+(?:-[a-z0-9]+)*\.md$`)

// backlogDateRE is D27's `date`: the record's own finish time in UTC, as a
// day. It is a date and never a timestamp, so the index cannot carry a figure
// that moves between two regenerations of an unchanged folder.
var backlogDateRE = regexp.MustCompile(`^[0-9]{4}-[0-9]{2}-[0-9]{2}$`)

// backlogIDRE is D26's id: eight digits, a dash, two digits.
var backlogIDRE = regexp.MustCompile(`^[0-9]{8}-[0-9]{2}$`)

// backlogItemFiles returns the folder's item files — every .md file in it
// except the generated index and the hand-written format — read off the tree
// rather than from a list kept here, so an item filed tomorrow is covered
// tomorrow. A folder that does not exist is an error, not an empty result:
// the red step of plan T4.3 is exactly that state.
func backlogItemFiles(t *testing.T) []string {
	t.Helper()
	entries, err := os.ReadDir(filepath.Join("..", "..", backlogDir))
	if err != nil {
		t.Fatalf("%s: %v (the folder, its format and its first items are plan T4.3)", backlogDir, err)
	}
	var out []string
	for _, e := range entries {
		if e.IsDir() || !strings.HasSuffix(e.Name(), ".md") {
			continue
		}
		if e.Name() == "README.md" || e.Name() == "FORMAT.md" {
			continue
		}
		out = append(out, e.Name())
	}
	sort.Strings(out)
	return out
}

// backlogFrontMatter returns the item's front matter as the file itself
// spells it: the `key: value` lines between the opening and closing `---`
// fences, read here rather than through internal/backlog's parser, so the
// assertions below are about the document and not about the code that reads
// it.
func backlogFrontMatter(t *testing.T, name, doc string) map[string]string {
	t.Helper()
	lines := strings.Split(doc, "\n")
	if len(lines) == 0 || strings.TrimRight(lines[0], "\r") != "---" {
		t.Fatalf("%s: the file does not open with a `---` front-matter fence", name)
	}
	out := map[string]string{}
	for i := 1; i < len(lines); i++ {
		line := strings.TrimRight(lines[i], "\r")
		if line == "---" {
			return out
		}
		if strings.TrimSpace(line) == "" {
			continue
		}
		key, value, ok := strings.Cut(line, ":")
		if !ok {
			t.Fatalf("%s: front-matter line %q is not `key: value`", name, line)
		}
		key, value = strings.TrimSpace(key), strings.TrimSpace(value)
		if _, dup := out[key]; dup {
			t.Fatalf("%s: front matter states %q twice", name, key)
		}
		out[key] = value
	}
	t.Fatalf("%s: the front matter is never closed with a `---` fence", name)
	return nil
}

// backlogBodyHeadings returns the H2 headings of the text after the front
// matter, in order.
func backlogBodyHeadings(doc string) []string {
	var out []string
	for _, line := range strings.Split(doc, "\n") {
		if strings.HasPrefix(strings.TrimRight(line, "\r"), "## ") {
			out = append(out, strings.TrimRight(line, "\r"))
		}
	}
	return out
}

// TestDocsBacklogItemsFollowTheFormat is the folder's own pin on the items:
// every file beside FORMAT.md and README.md is one item, named as D26 names
// it, carrying the eight front-matter fields D27 requires and no ninth, a
// status from D27's three-word vocabulary, and the body headings the format
// names with the first two required. Written red first, against a folder that
// did not exist (plan T4.3's red step), and independent of the tool: the
// parser's own acceptance is asserted separately, below.
func TestDocsBacklogItemsFollowTheFormat(t *testing.T) {
	names := backlogItemFiles(t)
	if len(names) == 0 {
		t.Fatalf("%s holds no item file: the folder, its format and its first items are plan T4.3", backlogDir)
	}
	seen := map[string]string{}
	for _, name := range names {
		path := backlogDir + "/" + name
		m := backlogItemNameRE.FindStringSubmatch(name)
		if m == nil {
			t.Errorf("%s: %q is not an item file name: one file per item, `<id>-<slug>.md`, with a lower-kebab slug (D26)", path, name)
			continue
		}
		doc := readDoc(t, path)
		fm := backlogFrontMatter(t, path, doc)

		// The eight fields, exactly: a missing one is a field a reader cannot
		// trust, and a ninth is a field nobody decided.
		for _, key := range backlog.Fields {
			if _, ok := fm[key]; !ok {
				t.Errorf("%s: the front matter does not carry the required field %q (D27)", path, key)
			}
		}
		for key := range fm {
			if !slices.Contains(backlog.Fields, key) {
				t.Errorf("%s: the front matter carries %q, which is not one of D27's eight fields", path, key)
			}
		}
		for key, value := range fm {
			if value == "" {
				t.Errorf("%s: the front matter's %q is empty: every one of the eight is required (D27)", path, key)
			}
		}

		// The id and the file name are checked against each other, so an id
		// resolves to a path without a lookup (D26).
		if id := fm["id"]; id != "" {
			if !backlogIDRE.MatchString(id) {
				t.Errorf("%s: id %q is not `<YYYYMMDD>-<NN>` (D26)", path, id)
			}
			if id != m[1] {
				t.Errorf("%s: id %q disagrees with the file name's first two segments %q: the name and the field are checked against each other (D26)", path, id, m[1])
			}
			if prev, dup := seen[id]; dup {
				t.Errorf("%s: id %q is already used by %s: two items may not share an id (D26)", path, id, prev)
			}
			seen[id] = path
		}

		// D27's status is three words and no fourth, its date is a day, and its
		// filed-in is one of the three things that can have filed an item.
		if status := fm["status"]; status != "" && !slices.Contains(backlog.Statuses, status) {
			t.Errorf("%s: status %q is not one of %s (D27)", path, status, strings.Join(backlog.Statuses, ", "))
		}
		if date := fm["date"]; date != "" && !backlogDateRE.MatchString(date) {
			t.Errorf("%s: date %q is not `YYYY-MM-DD`: the date is the record's own finish time, never a clock read at regeneration (D27)", path, date)
		}
		if in := fm["filed-in"]; in != "" && !backlogFiledIn(in) {
			t.Errorf("%s: filed-in %q is none of %s (D27)", path, in, strings.Join(backlog.FiledInKinds, ", "))
		}

		// The body's headings are the four the format names, and the first two
		// are required, so an item cannot be a title with no text (D27).
		headings := backlogBodyHeadings(doc)
		have := map[string]bool{}
		for _, h := range headings {
			have[h] = true
			if !slices.Contains(backlog.Headings, h) {
				t.Errorf("%s: the body carries the heading %q, which is not one of the headings the format names (D27, D31)", path, h)
			}
		}
		for _, want := range backlog.Headings[:2] {
			if !have[want] {
				t.Errorf("%s: the body does not carry the required heading %q (D27)", path, want)
			}
		}
		if len(headings) == 0 {
			t.Errorf("%s: the body carries no heading at all", path)
		}

		// D31's closing rule, which the status decides: a closed item names the
		// pull request that closed it and a dropped item states its reason.
		if status := fm["status"]; status != "" {
			if problem := backlogClosingProblem(doc, status); problem != "" {
				t.Errorf("%s: %s", path, problem)
			}
		}

		// The other direction: the tool the folder ships has to accept the
		// same bytes. A file this test reads as well-formed and Parse refuses
		// is a file `fugaro backlog list` cannot show.
		if _, err := backlog.Parse(path, []byte(doc)); err != nil {
			t.Errorf("%s: internal/backlog.Parse refuses an item the folder's format accepts: %v", path, err)
		}
	}
}

// backlogFiledIn reports whether a `filed-in` value is one the format names:
// `hand`, or one of the kinds with a value after the colon.
func backlogFiledIn(value string) bool {
	if value == "hand" {
		return true
	}
	for _, kind := range backlog.FiledInKinds {
		if strings.HasPrefix(value, kind+":") && len(value) > len(kind)+1 {
			return true
		}
	}
	return false
}

// backlogSection returns the text under a `## ` heading: the lines after it,
// up to the next heading. The bool reports whether the heading is there at all,
// so "the section is missing" and "the section is empty" stay different answers
// — D31 refuses a `closed` item for the first, and a `dropped` one for the
// second.
func backlogSection(doc, heading string) (string, bool) {
	var out []string
	seen := false
	for _, line := range strings.Split(doc, "\n") {
		line = strings.TrimRight(line, "\r")
		if strings.HasPrefix(line, "## ") {
			if seen {
				break
			}
			seen = line == heading
			continue
		}
		if seen {
			out = append(out, line)
		}
	}
	return strings.Join(out, "\n"), seen
}

// backlogPullRequestRE is a pull request named the way this repository's
// documents name one: `#412`, or its URL.
var backlogPullRequestRE = regexp.MustCompile(`#[0-9]+\b|/pull/[0-9]+\b`)

// backlogClosingProblem returns the closing rule a status breaks, or "" when it
// breaks none — D31's rule, and the reason it is checked here rather than in
// internal/backlog: the parser is about a file and this is about a status, and
// what a tree can hold is the document.
func backlogClosingProblem(doc, status string) string {
	switch status {
	case "closed":
		section, ok := backlogSection(doc, "## Closed by")
		if !ok {
			return "a `closed` item carries a `## Closed by` section, and this one has none (D31)"
		}
		if !backlogPullRequestRE.MatchString(section) {
			return "the `## Closed by` section does not name a pull request: it names the one that closed the item, as `#<number>` or its URL (D31)"
		}
	case "dropped":
		reason, ok := backlogSection(doc, "## Why")
		if !ok || strings.TrimSpace(reason) == "" {
			return "a `dropped` item states its reason under `## Why`, and this one states none (D31)"
		}
	}
	return ""
}

// TestDocsBacklogClosingRuleIsNotVacuous: both items in the folder today are
// open, so the rule the pin applies above is quiet on the tree, and a rule
// nothing exercises is a rule nobody has checked. This is the same function
// over documents written here, in both directions: what D31 refuses and what it
// accepts, including a `## Closed by` section that is present but names no pull
// request — the case a check for the heading alone would let through.
//
// Mutation (verified, run and restored): drop the pull-request reference from
// the accepted case's `## Closed by` text — this fails naming the case.
func TestDocsBacklogClosingRuleIsNotVacuous(t *testing.T) {
	const body = "## What was left open\n\nthe thing.\n\n## Why\n\nbecause.\n"
	cases := []struct {
		name   string
		status string
		body   string
		want   string // a fragment of the refusal, or "" when the rule is satisfied
	}{
		{"a closed item that names its pull request", "closed", body + "\n## Closed by\n\n#412\n", ""},
		{"a closed item that names it by URL", "closed", body + "\n## Closed by\n\nhttps://github.com/owner/name/pull/412\n", ""},
		{"a closed item with no closing section", "closed", body, "carries a `## Closed by` section"},
		{"a closed item whose closing section names no pull request", "closed", body + "\n## Closed by\n\nfixed, thanks\n", "does not name a pull request"},
		{"a closed item whose closing section is empty", "closed", body + "\n## Closed by\n", "does not name a pull request"},
		{"a dropped item that states its reason", "dropped", body, ""},
		{"a dropped item that states no reason", "dropped", "## What was left open\n\nthe thing.\n\n## Why\n", "states its reason under `## Why`"},
		{"an open item with neither", "open", body, ""},
	}
	for _, tc := range cases {
		t.Run(tc.name, func(t *testing.T) {
			doc := backlogItemDoc("20261021-01", "a title", tc.status, tc.body)
			path := backlogDir + "/20261021-01-a-title.md"

			// The fixtures are items the format accepts, so what is refused
			// below is refused for the status and not for the file: the parser
			// requires the headings, and the closing rule requires the text
			// under one of them.
			if _, err := backlog.Parse(path, []byte(doc)); err != nil {
				t.Fatalf("the fixture is not an item the format accepts: %v", err)
			}
			got := backlogClosingProblem(doc, tc.status)
			if tc.want == "" {
				if got != "" {
					t.Errorf("the closing rule refuses a %s item it accepts: %s", tc.status, got)
				}
				return
			}
			if !strings.Contains(got, tc.want) {
				t.Errorf("the closing rule says %q for a %s item, want it to say %q (D31)", got, tc.status, tc.want)
			}
		})
	}
}

// TestDocsBacklogAStatusFlipMovesTheIndex: D31's "in the same commit" is held
// by the regenerate-and-compare pin above, and that pin can only catch a flip
// the index records. This asserts the flip is recorded — closing an item moves
// its row out of the open group and moves the count line with it — so the pin
// is not quiet on the one edit the rule is about.
//
// Mutation (verified, run and restored): write the flipped item back with its
// old status — this fails, because the two renders are then equal.
func TestDocsBacklogAStatusFlipMovesTheIndex(t *testing.T) {
	dir := filepath.Join(t.TempDir(), backlog.Dir)
	if err := os.MkdirAll(dir, 0o755); err != nil {
		t.Fatal(err)
	}
	itemPath := filepath.Join(dir, "20261021-01-a-title.md")
	write := func(doc string) {
		t.Helper()
		if err := os.WriteFile(itemPath, []byte(doc), 0o644); err != nil {
			t.Fatal(err)
		}
	}
	render := func() string {
		t.Helper()
		items, err := backlog.Load(dir)
		if err != nil {
			t.Fatal(err)
		}
		return backlog.Render(items)
	}

	write(backlogItemDoc("20261021-01", "a title", "open", "## What was left open\n\nthe thing.\n\n## Why\n\nbecause.\n"))
	open := render()
	write(backlogItemDoc("20261021-01", "a title", "closed",
		"## What was left open\n\nthe thing.\n\n## Why\n\nbecause.\n\n## Closed by\n\n#412\n"))
	closed := render()

	if open == closed {
		t.Errorf("closing an item leaves the index byte-identical: a flip the index does not record is a flip the regenerate-and-compare pin cannot catch, and D31's rule is that the flip and the regeneration are one commit")
	}
	if !strings.Contains(closed, "1 item: 0 open, 1 closed, 0 dropped.") {
		t.Errorf("the index of one closed item does not state its count line:\n%s", closed)
	}
}

// backlogItemDoc is an item's bytes from its front matter and its body, so a
// case can write the body it means to test — including a section it
// deliberately leaves out, which is what a closing-rule case is.
func backlogItemDoc(id, title, status, body string) string {
	return "---\n" +
		"id: " + id + "\n" +
		"title: " + title + "\n" +
		"mode: none\n" +
		"area: repo\n" +
		"status: " + status + "\n" +
		"filed-by: dimipaun\n" +
		"filed-in: hand\n" +
		"date: 2026-10-21\n" +
		"---\n\n" + body
}

