// backlogIndexRowRE is one row of the index's table: the id in the first cell,
// linked to the item's file.
var backlogIndexRowRE = regexp.MustCompile(`^\|\s*\[([0-9]{8}-[0-9]{2})\]\(([^)]+)\)\s*\|`)

// backlogIndexLinks returns the id -> link target of every row the index
// document carries, read out of the Markdown rather than from the generator,
// so a row is checked against the tree and not against the code that wrote it.
func backlogIndexLinks(doc string) map[string]string {
	out := map[string]string{}
	for _, line := range strings.Split(doc, "\n") {
		if m := backlogIndexRowRE.FindStringSubmatch(line); m != nil {
			out[m[1]] = m[2]
		}
	}
	return out
}

// backlogItemIDs returns the id -> file name of every item file in dir, read
// off the tree: every .md file in the folder except the generated index and
// the hand-written format, keyed by the id its name starts with. A folder that
// is not there is an error, not an empty result.
func backlogItemIDs(dir string) (map[string]string, error) {
	entries, err := os.ReadDir(dir)
	if err != nil {
		return nil, err
	}
	out := map[string]string{}
	for _, e := range entries {
		if e.IsDir() || !strings.HasSuffix(e.Name(), ".md") {
			continue
		}
		if e.Name() == "README.md" || e.Name() == "FORMAT.md" {
			continue
		}
		m := backlogItemNameRE.FindStringSubmatch(e.Name())
		if m == nil {
			return nil, fmt.Errorf("%s/%s is not an item file name", dir, e.Name())
		}
		out[m[1]] = e.Name()
	}
	return out, nil
}

// TestDocsBacklogIndexIsCurrent is D28's first guard, and the regenerate-and-
// compare kind: the committed index must be byte-for-byte what the folder's
// own items render to. It is what makes a pull request that adds an item
// regenerate the index in the same commit, and what makes the file safe to
// treat as derived state — a regeneration in review diffs only where an item
// changed.
//
// It agrees with whatever the generator does, which is why it is not the only
// guard: the completeness guard below reads the tree and the committed
// document and never calls the generator, so a generator that stopped listing
// an item fails there and not here.
//
// Mutation (verified, run and restored): render one item fewer — this fails
// naming the diff.
func TestDocsBacklogIndexIsCurrent(t *testing.T) {
	items, err := backlog.LoadDir(filepath.Join("..", ".."))
	if err != nil {
		t.Fatal(err)
	}
	got := readDoc(t, backlogIndex)
	if want := backlog.Render(items); got != want {
		t.Errorf("%s is not what the item files render to: run `fugaro backlog index` and commit the result.\n--- committed ---\n%s\n--- rendered ---\n%s", backlogIndex, got, want)
	}
	if !strings.HasPrefix(got, backlogIndexHeader) {
		t.Errorf("%s does not open with %q: the generated file names the one command that rewrites it (D28)", backlogIndex, backlogIndexHeader)
	}
}

// TestDocsBacklogIndexCoversEveryItemInTheTree is D28's second guard, and the
// other kind: it reads the folder and the committed index and derives both
// sides from the tree and the document, so it holds even if the generator
// stopped listing an item, renamed a link or dropped a section. A row per item
// file, each linked to the file it names, and no row for a file that is not
// there.
//
// Mutation (verified, run and restored): delete a row from the committed index
// — this fails naming the id the document does not list. Delete the count
// line's agreement by hand — the pin above fails, not this test, which is the
// difference between the two guards.
func TestDocsBacklogIndexCoversEveryItemInTheTree(t *testing.T) {
	doc := readDoc(t, backlogIndex)

	// The folder on disk, and the repository-relative name this test's
	// messages use: readDoc resolves the latter, os.ReadDir needs the former.
	tree, err := backlogItemIDs(filepath.Join("..", "..", backlogDir))
	if err != nil {
		t.Fatalf("%s: %v (the folder, its format and its first items are plan T4.3)", backlogDir, err)
	}
	if len(tree) == 0 {
		t.Fatalf("%s holds no item file: the index is over an empty folder", backlogDir)
	}
	rows := backlogIndexLinks(doc)
	for id, name := range tree {
		target, ok := rows[id]
		if !ok {
			t.Errorf("%s lists no row for %s/%s: every item file has one, and a file the index does not list is invisible to a reader (D28)", backlogIndex, backlogDir, name)
			continue
		}
		if target != name {
			t.Errorf("%s links id %s to %q, but the file is %s: the row's link is the item's own file name", backlogIndex, id, target, name)
		}
		if strings.Contains(target, "/") {
			t.Errorf("%s links id %s to %q: the link is beside the index, so it is the file's own name and not a path", backlogIndex, id, target)
		}
	}
	for id := range rows {
		if _, ok := tree[id]; !ok {
			t.Errorf("%s lists a row for id %s, which no item file in %s carries: a row without a file is a link a reader cannot follow", backlogIndex, id, backlogDir)
		}
	}

	// The count line, derived from the folder rather than from the generator:
	// the statuses read out of the items' own front matter, counted here.
	counts := map[string]int{}
	for _, name := range tree {
		fm := backlogFrontMatter(t, backlogDir+"/"+name, readDoc(t, backlogDir+"/"+name))
		counts[fm["status"]]++
	}
	line := fmt.Sprintf("%d items: %d open, %d closed, %d dropped.",
		len(tree), counts["open"], counts["closed"], counts["dropped"])
	if !strings.Contains(doc, line) {
		t.Errorf("%s does not state %q: the count line is where a status with no section is stated rather than dropped (D28)", backlogIndex, line)
	}
}

// TestDocsBacklogIndexGuardCatchesAnUnregeneratedItem is the completeness
// guard's own red step, on a folder this test builds: an item added and the
// index not regenerated is exactly the state the guard exists to catch, and it
// is caught by reading the tree and the document, with no generator in the
// loop. Without this, the guard could pass by being vacuous.
//
// Mutation (verified, run and restored): make backlogItemIDs return an empty
// map — this fails, because the second item is then not reported.
func TestDocsBacklogIndexGuardCatchesAnUnregeneratedItem(t *testing.T) {
	dir := filepath.Join(t.TempDir(), backlog.Dir)
	if err := os.MkdirAll(dir, 0o755); err != nil {
		t.Fatal(err)
	}
	write := func(name, doc string) {
		t.Helper()
		if err := os.WriteFile(filepath.Join(dir, name), []byte(doc), 0o644); err != nil {
			t.Fatal(err)
		}
	}
	write("20261021-01-a-title.md", itemDoc("20261021-01", "a title"))
	items, err := backlog.Load(dir)
	if err != nil {
		t.Fatal(err)
	}
	index := backlog.Render(items)

	// The index as it stands covers the folder: the guard is quiet.
	tree, err := backlogItemIDs(dir)
	if err != nil {
		t.Fatal(err)
	}
	if _, ok := backlogIndexLinks(index)["20261021-01"]; !ok {
		t.Fatalf("the guard's own fixture does not hold: %s does not list the one item", backlogIndex)
	}

	// An item filed and the index not regenerated with it: the guard sees it.
	write("20261021-02-another.md", itemDoc("20261021-02", "another"))
	tree, err = backlogItemIDs(dir)
	if err != nil {
		t.Fatal(err)
	}
	if len(tree) != 2 {
		t.Fatalf("the tree holds %d item files, want 2", len(tree))
	}
	rows := backlogIndexLinks(index)
	var missing []string
	for id := range tree {
		if _, ok := rows[id]; !ok {
			missing = append(missing, id)
		}
	}
	if len(missing) != 1 || missing[0] != "20261021-02" {
		t.Errorf("the guard reports %v as unlisted, want the one item added after the index was written: an unregenerated index has to be caught by the tree, not by the generator", missing)
	}
}

// itemDoc is a well-formed item's bytes, so the guard's own fixture is a file
// the format accepts rather than a stub.
func itemDoc(id, title string) string {
	return backlogItemDoc(id, title, "open", "## What was left open\n\nthe thing.\n\n## Why\n\nbecause.\n")
}

// TestDocsBacklogIndexIsDeterministic: the index is a pure function of the
// item files. The same folder renders to the same bytes — which is what makes
// the pin above a diff of the items and not of the moment — and no source file
// in internal/backlog reads a clock, so a date in the document can only come
// from the item that carries it (D27).
//
// Mutation (verified, run and restored): add `time.Now()` to Render's count
// line's neighbourhood — the source scan fails naming internal/backlog.
func TestDocsBacklogIndexIsDeterministic(t *testing.T) {
	items, err := backlog.LoadDir(filepath.Join("..", ".."))
	if err != nil {
		t.Fatal(err)
	}
	if backlog.Render(items) != backlog.Render(items) {
		t.Errorf("Render is not deterministic: two renders of one folder differ")
	}
	for _, src := range backlogPackageSources(t) {
		if strings.Contains(src.body, `"time"`) {
			t.Errorf("internal/backlog/%s imports \"time\": the index is regenerated from the items alone, so a clock in this package is a figure that moves between two regenerations of an unchanged folder (D27)", src.name)
		}
	}
}

// backlogSource is one file of a package, as its own bytes.
type backlogSource struct{ name, body string }

// backlogPackageSources returns internal/backlog's non-test sources, so the
// determinism check is over the code the index is actually rendered by.
func backlogPackageSources(t *testing.T) []backlogSource {
	t.Helper()
	entries, err := os.ReadDir(filepath.Join("..", "..", "internal", "backlog"))
	if err != nil {
		t.Fatal(err)
	}
	var out []backlogSource
	for _, e := range entries {
		if e.IsDir() || !strings.HasSuffix(e.Name(), ".go") || strings.HasSuffix(e.Name(), "_test.go") {
			continue
		}
		out = append(out, backlogSource{e.Name(), readDoc(t, path.Join("internal", "backlog", e.Name()))})
	}
	if len(out) == 0 {
		t.Fatal("internal/backlog has no non-test source: the scan lost the package")
	}
	return out
}
