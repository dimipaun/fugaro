// execute runs the fugaro command tree with args and captures its output.
func execute(t *testing.T, args ...string) (string, string, error) {
	t.Helper()
	cmd := NewRootCmd()
	var out, errOut bytes.Buffer
	cmd.SetOut(&out)
	cmd.SetErr(&errOut)
	cmd.SetArgs(NormalizeArgs(args))
	err := cmd.Execute()
	return out.String(), errOut.String(), err
}

func TestVersion(t *testing.T) {
	out, _, err := execute(t, "version")
	if err != nil {
		t.Fatal(err)
	}
	if out != "dev\n" {
		t.Fatalf("version output = %q, want %q", out, "dev\n")
	}
}

// The M4 bootstrap's hidden `gcp job-spec` is gone: the converge computes
// every name now.
func TestNoGCPCommand(t *testing.T) {
	if _, _, err := execute(t, "gcp", "--help"); err == nil || !strings.Contains(err.Error(), "unknown command") {
		t.Fatalf("fugaro gcp: err = %v, want unknown command", err)
	}
}

// TestReviewIsRegisteredInTheCoreRoot: `fugaro review` and its `show`
// subcommand are names the released binary answers to, each with the flags a
// user types at it. The command family, its refusal and its reader were written
// and tested on a tree that added the constructor by hand (review_test.go's
// reviewCLI), so until newCoreRoot's AddCommand list carried it the whole file
// was dead code: no tree the CLI builds reached it, and the refusal the design
// leans on was a sentence nothing could print.
//
// Registering the name changes nothing else. The refusal it can still print is
// E7's installation half — a project with no published credentials service —
// and the binary half that used to join it is the flip this command family's
// own file carries now (reviewJobAdmitted, true since 0.21.0).
func TestReviewIsRegisteredInTheCoreRoot(t *testing.T) {
	root := NewRootCmd()
	for _, c := range []struct {
		path  string
		flags []string
	}{
		// The launch: the pull request, the account it runs as, the one
		// mutation check it may carry, and the machine-readable result.
		{"review", []string{"pr", "token", "mutate", "json"}},
		// The read of what the job wrote: the artifact's own bytes, or the
		// rendered review beside them.
		{"review show", []string{"json"}},
	} {
		cmd, _, err := root.Find(strings.Fields(c.path))
		if err != nil || cmd == nil || cmd == root {
			t.Fatalf("`fugaro %s` does not resolve in the core tree (err = %v): the command family beside it is dead code until newReviewCmd joins newCoreRoot's AddCommand list", c.path, err)
		}
		for _, name := range c.flags {
			f := cmd.Flags().Lookup(name)
			if f == nil {
				t.Errorf("`fugaro %s` has no --%s flag, which is one a user types at the command", c.path, name)
				continue
			}
			if f.Hidden {
				t.Errorf("`fugaro %s`'s --%s is hidden: the flags a user types are the command's visible surface", c.path, name)
			}
		}
	}
}

// TestCliReferenceNamesTheReviewCommand: the generated reference carries the
// registered command and its reader, with every visible flag of each. The
// whole-file drift check lives with the tagged generator
// (ee/clidoc's TestCliReferenceIsCurrent) and the core's own loop is
// docs_website_cliref_test.go's TestCliReferenceNamesEveryCommandAndFlag; what
// this adds is the two sections read by name, so a registration that lands
// without its regeneration fails here with the generator's command in the
// message rather than only inside that loop.
func TestCliReferenceNamesTheReviewCommand(t *testing.T) {
	documented := cliRefDocumented(cliRefRoot())
	sections := cliRefSections(readDoc(t, cliRefPath))
	for _, path := range []string{"fugaro review", "fugaro review show"} {
		cmd, ok := documented[path]
		if !ok {
			t.Fatalf("the core tree does not document %q, so this check would pass on a page that names nothing", path)
		}
		lines, ok := sections[path]
		if !ok {
			t.Errorf("%s has no `%s` section: it is generated by `go run ./ee/clidoc`, and the commit that registers the command regenerates it", cliRefPath, path)
			continue
		}
		names, _ := cliRefFlagRows(lines)
		visible, _ := cliRefFlagNames(cmd)
		for _, name := range visible {
			if !slices.Contains(names, name) {
				t.Errorf("%s's %q section does not name the flag --%s, which the command has", cliRefPath, path, name)
			}
		}
	}
}

func TestExitErrorNilErr(t *testing.T) {
	e := &ExitError{Code: ExitRemoteError}
	if got, want := e.Error(), "exit code 2"; got != want {
		t.Errorf("Error() = %q, want %q", got, want)
	}
}

func TestExitCode(t *testing.T) {
	remote := &ExitError{Code: ExitRemoteError, Err: errors.New("boom")}
	cases := []struct {
		name string
		err  error
		want int
	}{
		{"nil", nil, ExitOK},
		{"plain error", errors.New("x"), ExitUserError},
		{"exit error", remote, ExitRemoteError},
		{"wrapped exit error", fmt.Errorf("wrap: %w", remote), ExitRemoteError},
	}
	for _, tc := range cases {
		if got := ExitCode(tc.err); got != tc.want {
			t.Errorf("%s: ExitCode = %d, want %d", tc.name, got, tc.want)
		}
	}
}
