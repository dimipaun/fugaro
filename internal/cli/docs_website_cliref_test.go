package cli

// The CLI reference's drift tests (website plan, Task W0.4).
//
// website/content/cli-reference.md is generated from the command tree by
// `go run ./ee/clidoc` -- the tagged tree, because one binary ships and the
// page describes that binary (design docs/design/ee-boundary-moves.md §9) --
// and it is what the site's docs hub renders (W1.7), so a command or a flag
// that lands in the tree without the reference being regenerated is a page that
// lies to a reader. The two tests here are the two directions the console
// contract's own tests use (docs_desktop_console_test.go):
//
//   - TestCliReferenceNamesEveryCommandAndFlag -- every non-hidden command
//     reachable from NewRootCmd(), and every non-hidden flag of each one, must
//     appear in the file. Both lists are derived from the tree, never
//     hand-kept, so a rename fails here rather than quietly leaving a stale
//     page behind.
//   - TestCliReferenceInventsNothing -- the other direction: every command the
//     file names must be one the tree has and does not hide, every flag it
//     names must be a flag of the command whose section names it, and a hidden
//     command or a hidden flag must appear nowhere.
//
// Both are subset checks, and deliberately so: the file is the tagged tree's
// output and may carry sections for commands whose code this build does not
// have, which is what cliRefPaidSection admits. The whole-file check lives with
// the tagged generator -- ee/clidoc/cliref_test.go's TestCliReferenceIsCurrent
// asserts the committed file is exactly its output -- and it cannot live in
// this package: ee/ is the one thing a core package may not import. The core's
// own subset check is internal/clidoc/cliref_test.go's
// TestCoreCommandsAreInTheReference.

import (
	"maps"
	"regexp"
	"slices"
	"strings"
	"testing"

	"github.com/spf13/cobra"
	"github.com/spf13/pflag"
)

const (
	// cliRefPath is the generated reference, relative to the repository root.
	cliRefPath = "website/content/cli-reference.md"
	// cliRefHeader is the marker the generator writes on the first line, the
	// same shape every generated file in this tree carries.
	cliRefHeader = "<!-- generated by go run ./ee/clidoc; do not edit -->"
)

// cliRefHeadingRE matches the one section-heading shape the generator writes:
// a command's full path, backticked, as an H2. Nothing else in the file is an
// H2.
var cliRefHeadingRE = regexp.MustCompile("^## `(.+)`$")

// cliRefFlagCellRE matches a flag-table row's first cell, "| `--name` |" or
// "| `-h`, `--help` |": the only place a flag is a fact rather than prose. A
// flag named inside a command's long description is read as text, not as a
// documented flag.
var cliRefFlagCellRE = regexp.MustCompile("^\\| (`-{1,2}[A-Za-z0-9][A-Za-z0-9-]*`[^|]*?) \\|")

// cliRefFlagTokenRE finds the flag tokens of a flag-table row's first cell.
var cliRefFlagTokenRE = regexp.MustCompile("`(-{1,2}[A-Za-z0-9][A-Za-z0-9-]*)`")

// cliRefRoot is the tree the reference is generated from: NewRootCmd() with
// cobra's own defaults filled in -- the `help` command, the `completion`
// command, the root's `-v, --version` flag and the `-h, --help` flag of every
// command, all of which cobra adds inside Execute. The generator makes the same
// calls (internal/clidoc/cliref's Prepare), and it has to: a test that read the un-executed tree would call
// `fugaro completion` invented, because the reference names it and this walk
// would not have seen it. A walk that skipped them would instead agree with a
// reference that omits two commands `fugaro --help` lists.
func cliRefRoot() *cobra.Command {
	root := NewRootCmd()
	root.InitDefaultHelpCmd()
	root.InitDefaultCompletionCmd()
	root.InitDefaultVersionFlag()
	var walk func(c *cobra.Command)
	walk = func(c *cobra.Command) {
		c.InitDefaultHelpFlag()
		for _, sub := range c.Commands() {
			walk(sub)
		}
	}
	walk(root)
	return root
}

// cliRefSections splits the reference into its command sections, keyed by the
// command path in the heading, with every line below the heading up to the
// next one. A file with no heading at all yields an empty map, which is
// exactly what the red step starts from.
func cliRefSections(doc string) map[string][]string {
	sections := map[string][]string{}
	var current string
	for _, line := range strings.Split(doc, "\n") {
		if m := cliRefHeadingRE.FindStringSubmatch(line); m != nil {
			if _, seen := sections[m[1]]; !seen {
				sections[m[1]] = nil
			}
			current = m[1]
			continue
		}
		if current != "" {
			sections[current] = append(sections[current], line)
		}
	}
	return sections
}

// cliRefDocumented returns the commands the reference documents -- the ones the
// tree has and does not hide, which is the rule the generator applies, derived
// here from the tree rather than kept as a list. A hidden command takes its
// subtree with it: a visible child of a hidden parent is not a command a reader
// can find.
func cliRefDocumented(root *cobra.Command) map[string]*cobra.Command {
	out := map[string]*cobra.Command{}
	var walk func(c *cobra.Command, prefix string, documented bool)
	walk = func(c *cobra.Command, prefix string, documented bool) {
		path := strings.TrimSpace(prefix + " " + c.Name())
		visible := documented && !c.Hidden
		if visible {
			out[path] = c
		}
		for _, sub := range c.Commands() {
			walk(sub, path, visible)
		}
	}
	walk(root, "", true)
	return out
}

// cliRefFlagNames returns a command's own flags -- local and non-inherited, so
// a flag appears in the section of the command that defines it -- split into
// the ones a reader may be told about and the ones the tree hides.
func cliRefFlagNames(c *cobra.Command) (visible, hidden []string) {
	c.LocalFlags().VisitAll(func(f *pflag.Flag) {
		if f.Hidden {
			hidden = append(hidden, f.Name)
			return
		}
		visible = append(visible, f.Name)
	})
	slices.Sort(visible)
	slices.Sort(hidden)
	return visible, hidden
}

// cliRefFlagRows returns what the given section's flag table names: the long
// names, stripped of the dashes a reader types (pflag's own names carry none),
// and the shorthands.
func cliRefFlagRows(lines []string) (names, shorthands []string) {
	for _, line := range lines {
		m := cliRefFlagCellRE.FindStringSubmatch(line)
		if m == nil {
			continue
		}
		for _, tok := range cliRefFlagTokenRE.FindAllStringSubmatch(m[1], -1) {
			if strings.HasPrefix(tok[1], "--") {
				names = append(names, tok[1][2:])
				continue
			}
			shorthands = append(shorthands, tok[1][1:])
		}
	}
	return names, shorthands
}

// cliRefShorthands maps a command's shorthands to the flags they stand for,
// read off the flags themselves. The `-h` of cobra's help flag is one of
// these, which is why the reference prints it.
func cliRefShorthands(c *cobra.Command) map[string]string {
	out := map[string]string{}
	c.LocalFlags().VisitAll(func(f *pflag.Flag) {
		if !f.Hidden && f.Shorthand != "" {
			out[f.Shorthand] = f.Name
		}
	})
	return out
}

// TestCliReferenceNamesEveryCommandAndFlag asserts the reference covers the
// command tree: every command NewRootCmd() has and does not hide, and every
// flag of each one. The list comes from the tree, so a new command fails this
// test until the reference is regenerated.
func TestCliReferenceNamesEveryCommandAndFlag(t *testing.T) {
	doc := readDoc(t, cliRefPath)
	if !strings.HasPrefix(doc, cliRefHeader) {
		t.Errorf("%s does not begin with the generated-file header %q: it is generated, and a reader has to be able to see that", cliRefPath, cliRefHeader)
	}
	sections := cliRefSections(doc)
	documented := cliRefDocumented(cliRefRoot())
	for _, path := range slices.Sorted(maps.Keys(documented)) {
		lines, ok := sections[path]
		if !ok {
			t.Errorf("%s does not name command %q", cliRefPath, path)
			continue
		}
		names, shorthands := cliRefFlagRows(lines)
		visible, _ := cliRefFlagNames(documented[path])
		for _, name := range visible {
			if !slices.Contains(names, name) {
				t.Errorf("%s's %q section does not name the flag --%s, which the command has", cliRefPath, path, name)
			}
		}
		for shorthand, name := range cliRefShorthands(documented[path]) {
			if slices.Contains(visible, name) && !slices.Contains(shorthands, shorthand) {
				t.Errorf("%s's %q section does not name -%s, the shorthand of --%s", cliRefPath, path, shorthand, name)
			}
		}
	}
}

// cliRefPaidSection reports whether path is a section the reference carries and
// this build cannot judge: a paid command's name at the root, or a command
// under one, that the released tree does not itself hold.
//
// The reference is generated from the tagged tree, so once a paid command's
// code moves out of the core its section ships in full while this build knows
// the name only as a stub with no flags of its own -- which is not what the
// section documents, and not something to hold it to. Before the move the
// released tree holds the command itself, and the section is judged like any
// other. The tagged generator's own test holds the whole file either way.
func cliRefPaidSection(path string) bool {
	fields := strings.Fields(path)
	if len(fields) < 2 || !slices.Contains(paidCommandNames, fields[1]) {
		return false
	}
	return !coreSurface().rootCommands[fields[1]]
}

// TestCliReferenceInventsNothing is the other direction, and it is the half
// that catches a document written from a design rather than read from the
// tree: every command the file names must be one NewRootCmd() has and does not
// hide, every flag a section names must be a flag of that command, and neither
// a hidden command nor a hidden flag may appear anywhere in the file.
func TestCliReferenceInventsNothing(t *testing.T) {
	doc := readDoc(t, cliRefPath)
	root := cliRefRoot()
	documented := cliRefDocumented(root)
	sections := cliRefSections(doc)
	for _, path := range slices.Sorted(maps.Keys(sections)) {
		lines := sections[path]
		if cliRefPaidSection(path) {
			continue
		}
		cmd, ok := documented[path]
		if !ok {
			t.Errorf("%s names command %q, which the command tree does not have or hides: a command a reader cannot run is a command the reference must not document", cliRefPath, path)
			continue
		}
		visible, hidden := cliRefFlagNames(cmd)
		names, shorthands := cliRefFlagRows(lines)
		real := cliRefShorthands(cmd)
		for _, name := range names {
			if !slices.Contains(visible, name) {
				t.Errorf("%s's %q section names the flag --%s, which that command does not have", cliRefPath, path, name)
			}
		}
		for _, shorthand := range shorthands {
			if _, ok := real[shorthand]; !ok {
				t.Errorf("%s's %q section names -%s, which is no flag of that command", cliRefPath, path, shorthand)
			}
		}
		section := strings.Join(lines, "\n")
		for _, name := range hidden {
			if strings.Contains(section, "`--"+name+"`") {
				t.Errorf("%s's %q section names the flag --%s, which the tree hides", cliRefPath, path, name)
			}
			if f := cmd.LocalFlags().Lookup(name); f != nil && f.Shorthand != "" && strings.Contains(section, "`-"+f.Shorthand+"`") {
				t.Errorf("%s's %q section names -%s, the shorthand of the hidden flag --%s", cliRefPath, path, f.Shorthand, name)
			}
		}
	}
	undocumented := map[string]bool{}
	for path := range cliRefEveryCommand(root) {
		if _, ok := documented[path]; !ok {
			undocumented[path] = true
		}
	}
	for _, path := range slices.Sorted(maps.Keys(undocumented)) {
		if strings.Contains(doc, "`"+path+"`") {
			t.Errorf("%s names the command %q, which the tree does not document: it is hidden, or it sits under a hidden command, and a hidden command is not user documentation (F38)", cliRefPath, path)
		}
	}
}

// cliRefEveryCommand returns every command under root, hidden ones included,
// keyed by full path -- the set the reference must leave out.
func cliRefEveryCommand(root *cobra.Command) map[string]*cobra.Command {
	out := map[string]*cobra.Command{}
	var walk func(c *cobra.Command, prefix string)
	walk = func(c *cobra.Command, prefix string) {
		path := strings.TrimSpace(prefix + " " + c.Name())
		out[path] = c
		for _, sub := range c.Commands() {
			walk(sub, path)
		}
	}
	walk(root, "")
	return out
}
