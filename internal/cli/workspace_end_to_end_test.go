// workspace_end_to_end_test.go is I1's own file: the two stubs the workspace
// plan left behind while its sides were built one at a time are gone
// (internal/credsvc/scope_stub.go and internal/creds/route_stub.go), and what
// replaces them is one member's run driven end to end over fakes — through its
// gateway and its git forwarder, at a workspace-mode service built by
// credsvc.NewServer over C1's resolver and C3's node.
//
// **What "end to end" is here, and what it is not.** The run's side is the
// shipped one: gateway.Start with a Workspace upstream built from a route
// record the member's own publisher wrote (creds.RouteRecord, read back by
// creds.DecodeRoute), and gateway.StartGitForward pointed at the service the
// record's holder named. The service's side is the real credsvc.Server in both
// of its modes, over a real internal/gcpfake Realtime Database and a real
// credsvc.NewWorkspace front door — so the run identities below are signed,
// issued and verified rather than stood in for. What is faked is only what is
// outside Fugaro: Anthropic, Bitbucket and GitHub, each reached through the
// service's own outbound client (Config.Client's transport), which is the seam
// a deployment's host resolution is.
//
// **Why the service is built here rather than by this package's own builder.**
// credentialsWorkspaceService is what a deployment runs, and it cannot be used
// hermetically: it builds its key sources with credsvc.NewGoogleKeys(), which
// reads Google's published certificates and holds no seam, and a test that
// wanted run identities it could sign would have to sign them with Google's own
// keys. So this file calls the same constructors that function calls, in the
// same order and with the same fields — NewWorkspaceScopeResolver over
// NewWorkspace over the published node and the workspace's own database — and
// what is not exercised is the four lines of that function's wiring rather than
// any behaviour of the service.
//
// Nothing in this file is, or looks like, a credential: every identity, every
// token and every bundle value below is generated by the test (e2eKey, the
// per-side literals), and no fixture holds a secret-shaped literal (the
// credentials-service rule).

