// e2eValue is one credential value of one side. Every value this test writes
// into a bundle is generated here, so no fixture holds a secret-shaped literal
// and no two sides hold the same value: which side served a call is then a fact
// the call itself carries, which is what the provenance assertions read.
func e2eValue(t *testing.T, what string) string {
	t.Helper()
	var raw [16]byte
	if _, err := rand.Read(raw[:]); err != nil {
		t.Fatalf("the value this test generates for %s: %v", what, err)
	}
	return "not-a-real-credential-" + what + "-" + hex.EncodeToString(raw[:])
}

// e2eAppKey is one side's GitHub App key: the private half the service signs an
// installation-token mint's assertion with, and the PEM that side's bundle is
// written with. The public half is what the test verifies a mint against, so
// "the workspace's key signed this token" is a fact about the bytes rather than
// an assumption about which service answered.
type e2eAppKey struct{ priv *rsa.PrivateKey }

func newE2EAppKey(t *testing.T) *e2eAppKey {
	t.Helper()
	priv, err := rsa.GenerateKey(rand.Reader, 2048)
	if err != nil {
		t.Fatalf("this test's own App key: %v", err)
	}
	return &e2eAppKey{priv: priv}
}

// pem is the key as a bundle entry holds it: an RSA PEM, which is the shape
// github.ParsePrivateKey reads (the mint's own parser).
func (k *e2eAppKey) pem() string {
	return string(pem.EncodeToMemory(&pem.Block{Type: "RSA PRIVATE KEY", Bytes: x509.MarshalPKCS1PrivateKey(k.priv)}))
}

// signed reports whether this key signed a compact JWT, which is how the two
// sides' mints are told apart: the assertion a service sends GitHub is signed
// with the App key ITS bundle holds, so a token that verifies here came from
// this side and no other.
func (k *e2eAppKey) signed(t *testing.T, token string) bool {
	t.Helper()
	parts := strings.Split(token, ".")
	if len(parts) != 3 {
		t.Fatalf("the mint's assertion is not a compact JWT: %q", token)
	}
	sig, err := base64.RawURLEncoding.DecodeString(parts[2])
	if err != nil {
		t.Fatalf("the mint's assertion carries a signature that is not base64url: %v", err)
	}
	sum := sha256.Sum256([]byte(parts[0] + "." + parts[1]))
	return rsa.VerifyPKCS1v15(&k.priv.PublicKey, crypto.SHA256, sum[:], sig) == nil
}

// e2eSide is one installation's worth of credentials service: the values only
// its own bundle holds, and the world outside Fugaro it may reach.
type e2eSide struct {
	// name is what the side is called in a failure message.
	name string
	// modelKey is the paid model credential (config.AnthropicSecret's entry), the
	// bitbucketToken is the proxied git credential and appKey is the App key the
	// mint signs with. They are this side's alone.
	modelKey       string
	bitbucketToken string
	appKey         *e2eAppKey
	// installationToken is the token this side's fake GitHub issues a mint: a
	// generated value of its own, so which installation issued the token a run
	// holds is a fact about the value and not about which service answered.
	installationToken string
	// outside is the three parties this side's service may reach, and the record
	// of every call it made to one.
	outside *e2eOutside
}

func newE2ESide(t *testing.T, name string) *e2eSide {
	t.Helper()
	return &e2eSide{
		name:              name,
		modelKey:          e2eValue(t, name+"-model"),
		bitbucketToken:    e2eValue(t, name+"-bitbucket"),
		appKey:            newE2EAppKey(t),
		installationToken: e2eValue(t, name+"-installation"),
		outside:           newE2EOutside(t, name),
	}
}

// bundle is the document this side's service loads: the three credentials above,
// keyed by the Secret Manager spelling each is served under (credsvc's bundle
// format), and nothing else. The App key is the block-scalar entry it has to be
// — its value is a PEM, many lines — and the other two are one line each.
func (s *e2eSide) bundle() []byte {
	pemBody := "  " + strings.ReplaceAll(strings.TrimRight(s.appKey.pem(), "\n"), "\n", "\n  ")
	return []byte(
		config.AnthropicSecret + ": " + s.modelKey + "\n" +
			config.BitbucketSecret + ": " + s.bitbucketToken + "\n" +
			config.GitHubAppKeySecret + ": |\n" + pemBody + "\n")
}

// callTo is the one call this side's service made to a party, matched on the
// host it was addressed to and the tail of the path. It fails rather than
// answering the zero value when the side made none or several: every assertion
// below is "this side paid for this act", and a side that made no call at all is
// exactly the failure the helper has to report.
func (o *e2eOutside) callTo(t *testing.T, host, pathTail string) e2eCall {
	t.Helper()
	var found []e2eCall
	for _, c := range o.answered() {
		if c.host == host && strings.HasSuffix(c.path, pathTail) {
			found = append(found, c)
		}
	}
	if len(found) != 1 {
		t.Fatalf("%s made %d calls to %s…%s (%v), want exactly one", o.name, len(found), host, pathTail, o.answered())
	}
	return found[0]
}

