// e2eMemberRun is one member's run of one of its repositories: the pins its
// identity carries and the job service account its calls are admitted as. Both
// are read off the published node's own row (e2eWorkspaceNode), so a run this
// test drives and a member the workspace declares cannot drift apart.
type e2eMemberRun struct {
	// member is the member's Fugaro project name — the node row's project and
	// the fp claim the workspace verifies — and firebase is its Firebase
	// project, which is the aud and iss of its run identities and the fact the
	// member's database is derived from.
	member, firebase string
	// account is the job service account this run presents, from the row's job
	// accounts, and slug is the repository's slug: the run identity's fs, the
	// key the member's route record is published at, and the name the
	// workspace's coverage and the repository's admission are asked about.
	account, slug string
	// provider and canonical are the repository's provider kind and canonical
	// name, which is what its record is derived from.
	provider, canonical string
	// run is the run id: the fr claim, the id the branch names, and the run
	// whose outcome the service looks for to decide the run is still live.
	run string

	google *e2eGoogle
}

// branch is the run's own branch (fb): the one ref the run may push.
func (r *e2eMemberRun) branch() string { return "fugaro/" + r.run }

// runToken mints this run's Firebase ID token, whose claims are the launcher's
// and credsvc's own reader's (verifyRun, internal/credsvc/auth.go): the aud and
// iss of the member's own Firebase project, a uid of r~<slug>~<run> that the fs
// and fr claims agree with, the member's fugaro project in fp, the run's branch
// in fb, and an fx far enough ahead that the identity is live. The pub/priv
// pairs are the test's own, which is what a real deployment's Google keys are
// not — and the whole reason this file builds the service directly.
func (r *e2eMemberRun) runToken(t *testing.T, now time.Time) string {
	t.Helper()
	uid := "r~" + r.slug + "~" + r.run
	return r.google.runs.sign(t, map[string]any{
		"aud":     r.firebase,
		"iss":     "https://securetoken.google.com/" + r.firebase,
		"sub":     uid,
		"user_id": uid,
		"fs":      r.slug,
		"fr":      r.run,
		"fp":      r.member,
		"fb":      r.branch(),
		"iat":     now.Unix(),
		"exp":     now.Add(time.Hour).Unix(),
		"fx":      now.Add(time.Hour).UnixMilli(),
	})
}

// jobToken mints the job service account's Google ID token for one service's
// address: the identity Cloud Run IAM admits, which every call presents beside
// the run's own. It is minted per audience and never reused across two services,
// because the audience IS one of them — the two services of this test are two
// addresses, and a token minted for one is refused by the other.
func (r *e2eMemberRun) jobToken(t *testing.T, audience string, now time.Time) string {
	t.Helper()
	return r.google.jobs.sign(t, map[string]any{
		"iss":            "https://accounts.google.com",
		"aud":            audience,
		"sub":            r.account,
		"email":          r.account,
		"email_verified": true,
		"iat":            now.Unix(),
		"nbf":            now.Unix(),
		"exp":            now.Add(time.Hour).Unix(),
	})
}

// e2eIdentities is one run's two identities, already minted: the values a
