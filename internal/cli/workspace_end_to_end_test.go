// mustCanonical is one repository's canonical name, in the spelling every node
// of a policy and every allow-list is written in (projectpolicy.Canonical, the
// one implementation of the rule).
func mustCanonical(provider, repo string) string {
	c, err := projectpolicy.Canonical(provider, repo)
	if err != nil {
		panic(err)
	}
	return c
}

// e2eWorkspaceNode is the workspace's published credentials node (C3's version
// 2), and it is what makes the workspace's front door a workspace's: the member
// row names the two job accounts the two runs below present, each with the one
// repository it is a job of, and the shared pool names the three credentials
// the workspace offers that member — the paid model key, its Bitbucket token and
// its GitHub App key, each spelled as the bundle holds it.
//
// Projects rather than AllMembers is the owner's per-member allow-list (D1298):
// this node names the member, which is the tighter of the two readings and the
// one an operator's own file produces for a workspace that shares with one
// member.
func e2eWorkspaceNode() *projectpolicy.WorkspaceCredentials {
	bitbucket := mustCanonical(gitprov.KindBitbucket, e2eBitbucketRepo)
	github := mustCanonical(gitprov.KindGitHub, e2eGitHubRepo)
	return &projectpolicy.WorkspaceCredentials{
		Version: projectpolicy.WorkspaceCredentialsVersion,
		Name:    e2eWorkspace,
		Members: []projectpolicy.WorkspaceCredentialMember{{
			Project:         e2eMember,
			FirebaseProject: e2eMemberFire,
			FP:              e2eMember,
			JobAccounts:     []string{e2eBitbucketAccount, e2eGitHubAccount},
			JobAccountRepos: []projectpolicy.WorkspaceJobAccount{
				{Account: e2eBitbucketAccount, Repos: []string{bitbucket}},
				{Account: e2eGitHubAccount, Repos: []string{github}},
			},
			ExchangeURL: "https://" + e2eMember + ".example.com/exchange",
		}},
		Shared: []projectpolicy.WorkspaceShared{
			// The pool's model entry: the paid key, which is the tier this test
			// has to share for the call to be METERED at all — the meter counts a
			// call at the messages path whose tier is not the reserved one
			// (workspace_cap.go's paidCall), so a tier-A pool would serve the
			// call and charge the workspace nothing.
			{Name: config.AnthropicSecret, Kind: projectpolicy.SharedKindModel, Projects: []string{e2eMember}},
			{Name: config.BitbucketSecret, Kind: gitprov.KindBitbucket, Projects: []string{e2eMember}, Covers: []string{bitbucket}},
			{Name: config.GitHubAppKeySecret, Kind: gitprov.KindGitHub, Projects: []string{e2eMember}, Covers: []string{github}},
		},
	}
}

// e2eMemberPolicy is the member's own published policy (projectpolicy.PathShared
// in the member's own database), and every leg of it is required for the two
// runs below to be served at all:
//
//   - allow_repos admits both repositories, which is whether they may run;
//   - the accounts block holds the one account the workspace's pool is spelled
//     under — the paid key's own sentinel, config.AnthropicKeyAccount, which is
//     the name creds.policyKey translates a tier-B pool entry into — and admits
//     both repositories for it, which is the leg a workspace can only tighten;
//   - the bitbucket block is the legacy token entry with the proxy switch on,
//     which is what gitproxy.Decide holds a proxied push to (B1.13 part two);
//   - the budget block names the model the call below sends, which the model
//     path holds the body to.
//
// It is written as JSON rather than through a writer because there is none for
// this node: the published policy is what `fugaro project policy publish`
// computes, and this test's subject is not that computation.
func e2eMemberPolicy() string {
	bitbucket := mustCanonical(gitprov.KindBitbucket, e2eBitbucketRepo)
	github := mustCanonical(gitprov.KindGitHub, e2eGitHubRepo)
	both := `["` + bitbucket + `", "` + github + `"]`
	return `{
		"version": ` + strconv.Itoa(projectpolicy.Version) + `,
		"budget": {"mode": "enforce", "per_run_usd": 5, "allowed_models": ["` + e2eModel + `"]},
		"allow_repos": ` + both + `,
		"accounts": {"` + config.AnthropicKeyAccount + `": {"allow_repos": ` + both + `}},
		"credentials": {"fallback": "auto"},
		"bitbucket_token": {"allow_repos": ["` + bitbucket + `"], "proxy": true}
	}`
}

// e2eMemberChild is one repository's own policy node (projectpolicy.PathRepo of
// the repository's slug): the accounts that repository's runs are admitted to,
// which is the node a member's publish derives from the accounts block above.
// The workspace's pool is offered only to a repository that is admitted to the
// pool's own name, which is the sentinel the node carries.
func e2eMemberChild() string {
	return `{"credentials": {"accounts": ["` + config.AnthropicKeyAccount + `"]}}`
}

// e2eMemberDatabase seeds the MEMBER's own database — the one the run reads its
// route record from, the one the workspace's service opens read-only to read
// this member's policy and admission, and the one the project's own service
// reads when the project holds its own copy:
//
//   - the published policy and each repository's child, which is what a member
//     that published its own policy has;
//   - one credential-route record per repository, written by C2's own writer,
//     carrying whatever the caller passed as each kind's holder.
func e2eMemberDatabase(t *testing.T, routes map[string]creds.Route) *rtdb.Client {
	t.Helper()
	fake := gcpfake.NewRTDB(t)
	fake.Set(projectpolicy.PathShared(), json.RawMessage(e2eMemberPolicy()))
	for _, canonical := range []string{mustCanonical(gitprov.KindBitbucket, e2eBitbucketRepo), mustCanonical(gitprov.KindGitHub, e2eGitHubRepo)} {
		provider, repo, _ := strings.Cut(canonical, "/")
		fake.Set(projectpolicy.PathRepo(mustSlug(provider, repo)), json.RawMessage(e2eMemberChild()))
	}
	for slug, route := range routes {
		raw, err := creds.RouteRecord(route)
		if err != nil {
			t.Fatalf("the route the member's own update would publish was refused by its own writer: %v", err)
		}
		fake.Set(creds.RoutePath(slug), json.RawMessage(raw))
	}
	client, err := rtdb.New(fake.URL, rtdb.Auth{IDToken: func() string { return "" }})
	if err != nil {
		t.Fatalf("the member's fake database's client: %v", err)
	}
	return client
}

// e2eWorkspaceDatabase seeds the WORKSPACE's own database: C3's published
// credentials node, which is the table the workspace's service resolves its
// callers and its pool out of, and the workspace's own record, whose cap the
// meter holds the pool to.
func e2eWorkspaceDatabase(t *testing.T, capMicros pricing.Micros) *rtdb.Client {
	t.Helper()
	fake := gcpfake.NewRTDB(t)
	node, err := projectpolicy.WorkspaceCredentialsNode(e2eWorkspaceNode())
	if err != nil {
		t.Fatalf("the node these tests publish is not one a Fugaro writes, so they would prove nothing about the read: %v", err)
	}
	fake.Set(projectpolicy.PathWorkspaceCredentials(e2eWorkspace), json.RawMessage(node))
	record := fmt.Sprintf(`{"version": %d, "name": %q, "members": [{"project": %q, "repos": [%q, %q]}], "cap": {"monthly_micros": %d}}`,
		projectpolicy.WorkspaceVersion, e2eWorkspace, e2eMember,
		mustCanonical(gitprov.KindBitbucket, e2eBitbucketRepo), mustCanonical(gitprov.KindGitHub, e2eGitHubRepo), capMicros)
	fake.Set(projectpolicy.PathWorkspace(e2eWorkspace), json.RawMessage(record))
	client, err := rtdb.New(fake.URL, rtdb.Auth{IDToken: func() string { return "" }})
	if err != nil {
		t.Fatalf("the workspace's fake database's client: %v", err)
	}
	return client
}

