// e2eGateway starts the run's gateway, wired as internal/runner wires one
// (routeGateway, internal/runner/gateway.go): the run's own project service is
// the upstream, the workspace is the second one whenever the record moves any
// kind to it, and the model kind is served from the workspace exactly when the
// record moved THAT one — which is what makes the choice final rather than a
// fallback (gateway.Options.ModelFromWorkspace, D2982 and D2989).
func e2eGateway(t *testing.T, ctx context.Context, st *e2eStand, run *e2eMemberRun, route creds.Route) *gateway.Server {
	t.Helper()
	ids := newE2EIdentities(t, run, st)
	var ws *gateway.Workspace
	if st.world.moves(route) {
		ws = &gateway.Workspace{
			Address:    st.world.workspace.address(),
			IDToken:    func(_ context.Context, audience string) (string, error) { return ids.job(audience), nil },
			RunIDToken: func() string { return ids.run },
			Job:        e2eJobName,
		}
	}
	g, err := gateway.Start(ctx, gateway.Options{
		Upstream: gateway.Upstream{
			Kind:    gateway.KindService,
			BaseURL: st.world.project.address(),
			Service: &gateway.Service{
				IDToken:    func(context.Context) (string, error) { return ids.job(st.world.project.address()), nil },
				RunIDToken: func() string { return ids.run },
				Job:        e2eJobName,
			},
		},
		Workspace:          ws,
		ModelFromWorkspace: route.Holder(creds.KindModel) == creds.HolderWorkspace,
		Prices:             pricing.Embedded(),
		Mode:               gateway.Enforce,
		Cap:                pricing.Micros(50_000_000),
		Log:                slog.New(slog.NewTextHandler(io.Discard, nil)),
	})
	if err != nil {
		t.Fatalf("the run's gateway could not be started: %v", err)
	}
	t.Cleanup(func() {
		c, cancel := context.WithTimeout(context.Background(), 10*time.Second)
		defer cancel()
		_ = g.Close(c)
	})
	g.BeginStage(gateway.Stage{Name: "implement", Model: e2eModel})
	return g
}

// e2eForwarder starts the run's git forwarder, wired as internal/runner wires
// one (its GitForwardOptions, internal/runner/runner.go): the run's own service
// is what it is built against, and the workspace is handed over only when the
// record moves the Bitbucket kind — a forwarder built with one follows the
// record's answer for that kind and never the environment's (WS18, D2979).
func e2eForwarder(t *testing.T, ctx context.Context, st *e2eStand, run *e2eMemberRun, route creds.Route) *gateway.GitForward {
	t.Helper()
	ids := newE2EIdentities(t, run, st)
	o := gateway.GitForwardOptions{
		Service: st.world.project.address(),
		Identity: gateway.Service{
			IDToken:    func(context.Context) (string, error) { return ids.job(st.world.project.address()), nil },
			RunIDToken: func() string { return ids.run },
			Job:        e2eJobName,
		},
		Log: slog.New(slog.NewTextHandler(io.Discard, nil)),
	}
	if route.Holder(creds.KindBitbucket) == creds.HolderWorkspace {
		o.Workspace = &gateway.Workspace{
			Address:    st.world.workspace.address(),
			IDToken:    func(_ context.Context, audience string) (string, error) { return ids.job(audience), nil },
			RunIDToken: func() string { return ids.run },
			Job:        e2eJobName,
		}
	}
	f, err := gateway.StartGitForward(ctx, o)
	if err != nil {
		t.Fatalf("the run's git forwarder could not be started: %v", err)
	}
	t.Cleanup(func() {
		c, cancel := context.WithTimeout(context.Background(), 10*time.Second)
		defer cancel()
		_ = f.Close(c)
	})
	return f
}

// e2eModelCall is the run's model call: the Messages request Claude Code sends
// its own gateway, with the gateway's own token in x-api-key (which is what the
// gateway's authorized reads), forwarded by the gateway to whichever service the
// record named for the model kind.
func e2eModelCall(t *testing.T, g *gateway.Server) (int, string) {
	t.Helper()
	body := `{"model":"` + e2eModel + `","max_tokens":16,"messages":[{"role":"user","content":"hello"}]}`
	req, err := http.NewRequest(http.MethodPost, g.URL()+credsvc.MessagesPath, strings.NewReader(body))
	if err != nil {
		t.Fatalf("building the run's model call: %v", err)
	}
	req.Header.Set("x-api-key", g.Token())
	req.Header.Set("content-type", "application/json")
	req.Header.Set("anthropic-version", "2023-06-01")
	resp, err := http.DefaultClient.Do(req)
	if err != nil {
		t.Fatalf("the run's model call: %v", err)
	}
	defer resp.Body.Close()
	answer, err := io.ReadAll(resp.Body)
	if err != nil {
		t.Fatalf("reading the model call's answer: %v", err)
	}
	if resp.StatusCode != http.StatusOK {
		t.Fatalf("the model call answered %d %s, want it served", resp.StatusCode, answer)
	}
	return resp.StatusCode, string(answer)
}

// e2ePushBody is the update request git sends a push's git-receive-pack: one
// pkt-line naming the ref the run moves, then the flush. It is the shape
// internal/gitproxy's own reader parses (ReadUpdateRequest), and the ref is the
// run's own branch — the one ref the run may move (decidePush).
func e2ePushBody(run *e2eMemberRun) string {
	old := strings.Repeat("0", 40)
	fresh := strings.Repeat("a", 40)
	line := old + " " + fresh + " refs/heads/" + run.branch() + "\x00 report-status\n"
	return fmt.Sprintf("%04x", len(line)+4) + line + "0000"
}

// e2eGitPath is one repository's path inside the forwarder's route: the
// canonical name's owner and name, without the provider kind — the kind is the
// route's own prefix. It is the shape the run's git is pointed at
// (runner.go's bitbucketRemote: the forwarder's URL, then owner, then name).
func e2eGitPath(run *e2eMemberRun) string {
	_, path, _ := strings.Cut(run.canonical, "/")
	return path
}

// e2ePush is the run's push: the update request above, posted to the forwarder
// at the repository's git-receive-pack — the URL a run's git is pointed at
// (GitForward.URL).
func e2ePush(t *testing.T, f *gateway.GitForward, run *e2eMemberRun) (int, string) {
	t.Helper()
	req, err := http.NewRequest(http.MethodPost, f.URL()+e2eGitPath(run)+".git/git-receive-pack", strings.NewReader(e2ePushBody(run)))
	if err != nil {
		t.Fatalf("building the run's push: %v", err)
	}
	req.Header.Set("content-type", "application/x-git-receive-pack-request")
	resp, err := http.DefaultClient.Do(req)
	if err != nil {
		t.Fatalf("the run's push: %v", err)
	}
	defer resp.Body.Close()
	answer, err := io.ReadAll(resp.Body)
	if err != nil {
		t.Fatalf("reading the push's answer: %v", err)
	}
	if resp.StatusCode != http.StatusOK {
		t.Fatalf("the push answered %d %s, want it forwarded", resp.StatusCode, answer)
	}
	return resp.StatusCode, string(answer)
}

// e2eMint is the run's GitHub installation-token mint: the client a run of a
// GitHub repository installs (github.ServiceTokens, C2.2), pointed at the
// service the run's record names for the GitHub kind — which is the same
// decision the gateway and the forwarder make and the whole of what "on
// workspace credentials" means for a mint.
func e2eMint(t *testing.T, ctx context.Context, st *e2eStand, run *e2eMemberRun, route creds.Route, appID string) (string, time.Time) {
	t.Helper()
	ids := newE2EIdentities(t, run, st)
	url := st.world.serviceFor(route, creds.KindGitHub).address()
	s := &github.ServiceTokens{
		URL:        url,
		AppID:      appID,
		IDToken:    func(context.Context) (string, error) { return ids.job(url), nil },
		RunIDToken: func() string { return ids.run },
		Job:        e2eJobName,
	}
	tok, expires, err := s.Token(ctx, 0)
	if err != nil {
		t.Fatalf("the run's GitHub installation token could not be minted: %v", err)
	}
	return tok, expires
}

