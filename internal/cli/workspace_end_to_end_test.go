// e2eStandUp builds the whole stand over the facts the member's own `fugaro
// update` read of itself: its bundle and its policy. THE FACTS ARE THE ONLY
// INPUT, and both tests differ in nothing else — the record each run reads, the
// service each kind is served by and the credentials every call carries are all
// derived from them, which is what makes the two tests the same run with one
// project's copy in two different places.
func e2eStandUp(t *testing.T, facts routeFacts, now time.Time) *e2eStand {
	t.Helper()
	bitbucket := mustCanonical(gitprov.KindBitbucket, e2eBitbucketRepo)
	github := mustCanonical(gitprov.KindGitHub, e2eGitHubRepo)
	bitbucketSlug, err := task.Slug(gitprov.KindBitbucket, e2eBitbucketRepo)
	if err != nil {
		t.Fatalf("the Bitbucket repository's slug: %v", err)
	}
	githubSlug, err := task.Slug(gitprov.KindGitHub, e2eGitHubRepo)
	if err != nil {
		t.Fatalf("the GitHub repository's slug: %v", err)
	}
	st := &e2eStand{now: now, google: newE2EGoogle(t)}
	st.bb = &e2eMemberRun{
		member: e2eMember, firebase: e2eMemberFire, account: e2eBitbucketAccount,
		slug: bitbucketSlug, provider: gitprov.KindBitbucket, canonical: bitbucket,
		run: e2eBitbucketRun, google: st.google,
	}
	st.gh = &e2eMemberRun{
		member: e2eMember, firebase: e2eMemberFire, account: e2eGitHubAccount,
		slug: githubSlug, provider: gitprov.KindGitHub, canonical: github,
		run: e2eGitHubRun, google: st.google,
	}
	projectSide := newE2ESide(t, "the project's")
	workspaceSide := newE2ESide(t, "the workspace's")
	projectSide.promiseAnthropic(t)
	workspaceSide.promiseAnthropic(t)
	projectSide.promiseBitbucket(t)
	workspaceSide.promiseBitbucket(t)
	projectSide.promiseGitHub(t)
	workspaceSide.promiseGitHub(t)
	// The two listeners are reserved before either service is built, because
	// each service's own address is its audience: the identity every caller
	// presents is minted for the address the listener ends up on
	// (AuthConfig.Audience, WorkspaceConfig.Audience), and a service built
	// against another address would refuse every call of this test rather than
	// prove anything about it.
	project := newE2EService(t, "the project's service", projectSide)
	workspace := newE2EService(t, "the workspace's service", workspaceSide)
	st.world = &e2eWorld{project: project, workspace: workspace}

	// The two records the member's own update publishes for the two
	// repositories, derived by the CLI's own rule (routeFacts.holder over the
	// kinds C2 names, routeWithKind's own loop in update_route.go's rowFor), so
	// "the project holds its own copy" is the CLI's answer and not this test's.
	// They are then written through C2's own writer and read back through its
	// own reader: what the runs below act on is a record that has been through
	// the database, not one this test kept in hand.
	st.bbRoute = e2eRouteOf(t, facts, st.bb)
	st.ghRoute = e2eRouteOf(t, facts, st.gh)
	st.member = e2eMemberDatabase(t, map[string]creds.Route{st.bb.slug: st.bbRoute, st.gh.slug: st.ghRoute})
	st.ws = e2eWorkspaceDatabase(t, e2eWorkspaceCap)
	st.bbRoute = e2ePublishedRoute(t, st.member, st.bb.slug)
	st.ghRoute = e2ePublishedRoute(t, st.member, st.gh.slug)

	startE2EProjectService(t, project, st, projectSide, st.member)
	startE2EWorkspaceService(t, workspace, st, workspaceSide)
	return st
}

// e2eRouteOf is one repository's published record: the address the member's own
// pin carries and each kind's holder as the CLI's own rule answers it.
func e2eRouteOf(t *testing.T, facts routeFacts, run *e2eMemberRun) creds.Route {
	t.Helper()
	route := creds.Route{Version: creds.RouteVersion, Address: e2eWorkspaceAddress}
	for _, kind := range creds.Kinds {
		route = routeWithKind(route, kind, facts.holder(kind, run.provider, run.canonical, run.slug))
	}
	if _, err := creds.RouteRecord(route); err != nil {
		t.Fatalf("the record this test derived is not one the record's own writer accepts: %v", err)
	}
	return route
}

// e2ePublishedRoute is one repository's record as the run reads it: C2's own
// reader over the member's own database, so the holder every act below is
// routed by is the published one.
func e2ePublishedRoute(t *testing.T, db *rtdb.Client, slug string) creds.Route {
	t.Helper()
	var raw json.RawMessage
	found, err := db.Get(context.Background(), creds.RoutePath(slug), &raw)
	if err != nil || !found {
		t.Fatalf("the record this test published for %s could not be read back (found %v): %v", slug, found, err)
	}
	route, found, err := creds.DecodeRoute(raw)
	if err != nil || !found {
		t.Fatalf("the record published for %s is not one its own reader accepts (found %v): %v", slug, found, err)
	}
	return route
}

