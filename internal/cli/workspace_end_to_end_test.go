// promiseAnthropic is the answer to a Messages call: a small, complete answer
// with a usage block, because the model path reads the answer's usage to price
// the call — an answer without one is a call the meter cannot charge for.
func (s *e2eSide) promiseAnthropic(t *testing.T) {
	t.Helper()
	s.outside.answer(e2eAnthropicHost, func(*http.Request, []byte) e2eAnswer {
		return e2eAnswer{
			header: http.Header{"Content-Type": {"application/json"}},
			body: []byte(`{"id":"msg_e2e","type":"message","role":"assistant","model":"` + e2eModel +
				`","content":[{"type":"text","text":"ok"}],"stop_reason":"end_turn","usage":{"input_tokens":12,"output_tokens":2}}`),
		}
	})
}

// promiseBitbucket is the answer to a proxied push: Bitbucket's own
// report-status result for a receive-pack that took the ref, which is what the
// proxy relays and what git reads.
func (s *e2eSide) promiseBitbucket(t *testing.T) {
	t.Helper()
	s.outside.answer(e2eBitbucketHost, func(*http.Request, []byte) e2eAnswer {
		return e2eAnswer{
			header: http.Header{"Content-Type": {"application/x-git-receive-pack-result"}},
			body:   []byte("000eunpack ok\n0000"),
		}
	})
}

// promiseGitHub is the two answers a mint takes: the installation GitHub has
// for the repository (the read that finds its id) and the access token itself.
// The token is this side's own generated value, so the run's answer says which
// side's key signed for it without the test having to reason about which
// service it talked to.
func (s *e2eSide) promiseGitHub(t *testing.T) {
	t.Helper()
	s.outside.answer(e2eGitHubHost, func(r *http.Request, _ []byte) e2eAnswer {
		jsonHeader := http.Header{"Content-Type": {"application/json"}}
		switch {
		case r.Method == http.MethodGet && strings.HasSuffix(r.URL.Path, "/installation"):
			return e2eAnswer{header: jsonHeader, body: []byte(`{"id":4242}`)}
		case r.Method == http.MethodPost && strings.HasSuffix(r.URL.Path, "/access_tokens"):
			return e2eAnswer{header: jsonHeader, body: []byte(`{"token":"` + s.installationToken +
				`","expires_at":"` + time.Now().UTC().Add(time.Hour).Format(time.RFC3339) + `"}`)}
		}
		return e2eAnswer{status: http.StatusNotFound, body: []byte(`{}`)}
	})
}

// silent fails the test if this side's service made any call to a party outside
// Fugaro: a side whose service serves nothing reaches nothing, and a call here
// is a credential of that side having been spent.
func (o *e2eOutside) silent(t *testing.T, why string) {
	t.Helper()
	if got := o.answered(); len(got) != 0 {
		t.Errorf("%s reached %v, and %s", o.name, got, why)
	}
}

