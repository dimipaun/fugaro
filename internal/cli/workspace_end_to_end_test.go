// e2eActs is what the three acts answered, kept so a test can assert on an
// answer rather than only on the calls behind it.
type e2eActs struct {
	modelStatus int
	modelAnswer string
	pushStatus  int
	pushAnswer  string
	mintToken   string
}

// e2eDriveTheThreeActs is the run the two tests share: the member's Bitbucket
// run makes a model call through its gateway and a push through its forwarder,
// and its GitHub run mints an installation token — every one of them through
// the run's own components, wired from the record its own project published.
//
// It is one function because the two tests must differ in NOTHING but where the
// project's copy of a credential lives: the same three acts, the same wiring,
// the same assertions.
func e2eDriveTheThreeActs(t *testing.T, ctx context.Context, st *e2eStand) e2eActs {
	t.Helper()
	var acts e2eActs

	g := e2eGateway(t, ctx, st, st.bb, st.bbRoute)
	acts.modelStatus, acts.modelAnswer = e2eModelCall(t, g)

	f := e2eForwarder(t, ctx, st, st.bb, st.bbRoute)
	acts.pushStatus, acts.pushAnswer = e2ePush(t, f, st.bb)

	acts.mintToken, _ = e2eMint(t, ctx, st, st.gh, st.ghRoute, e2eAppID)
	return acts
}

// e2eAssertTheModelCall is the model act's provenance: the call the run's
// gateway forwarded was paid for with the serving side's own key, the answer
// the run got is the fake's, and no other side's service reached Anthropic.
func e2eAssertTheModelCall(t *testing.T, act string, world *e2eWorld, route creds.Route, acts e2eActs) *e2eSide {
	t.Helper()
	serving := world.serviceFor(route, creds.KindModel)
	call := serving.side.outside.callTo(t, e2eAnthropicHost, credsvc.MessagesPath)
	if call.apiKey != serving.side.modelKey {
		t.Errorf("%s sent api.anthropic.com the key %q and %s's own bundle holds %q: the model call was not paid for with the serving side's credential",
			serving.name, call.apiKey, serving.name, serving.side.modelKey)
	}
	if call.method != http.MethodPost {
		t.Errorf("%s reached Anthropic with %s, want the POST a Messages call is", serving.name, call.method)
	}
	if acts.modelStatus != http.StatusOK {
		t.Errorf("%s answered the run's model call %d %s, want it served", serving.name, acts.modelStatus, acts.modelAnswer)
	}
	world.other(serving).side.outside.silent(t, act+" was served by "+serving.name+" alone")
	return serving.side
}

// e2eAssertThePush is the push's provenance: the proxied receive-pack carried
// the serving side's own Bitbucket token, and no other side's service reached
// Bitbucket.
func e2eAssertThePush(t *testing.T, act string, world *e2eWorld, route creds.Route, acts e2eActs) *e2eSide {
	t.Helper()
	serving := world.serviceFor(route, creds.KindBitbucket)
	call := serving.side.outside.callTo(t, e2eBitbucketHost, "/git-receive-pack")
	basic := strings.TrimPrefix(call.auth, "Basic ")
	raw, err := base64.StdEncoding.DecodeString(basic)
	if err != nil {
		t.Fatalf("%s reached Bitbucket with an Authorization header that is not Basic credentials: %q", serving.name, call.auth)
	}
	if !strings.Contains(string(raw), serving.side.bitbucketToken) {
		t.Errorf("%s pushed with credentials that do not carry its own Bitbucket token: a push is paid for with the serving side's git credential", serving.name)
	}
	if acts.pushStatus != http.StatusOK {
		t.Errorf("%s answered the run's push %d %s, want it forwarded", serving.name, acts.pushStatus, acts.pushAnswer)
	}
	world.other(serving).side.outside.silent(t, act+" was served by "+serving.name+" alone")
	return serving.side
}

// e2eAssertTheMint is the mint's provenance: the assertion the serving side's
// service sent GitHub verifies under that side's own App key and no other, and
// the token the run holds is the one that side's fake issued.
func e2eAssertTheMint(t *testing.T, act string, world *e2eWorld, route creds.Route, acts e2eActs) *e2eSide {
	t.Helper()
	serving := world.serviceFor(route, creds.KindGitHub)
	call := serving.side.outside.callTo(t, e2eGitHubHost, "/access_tokens")
	assertion := strings.TrimPrefix(call.auth, "Bearer ")
	if assertion == call.auth {
		t.Fatalf("%s reached GitHub's mint endpoint without a bearer assertion: %q", serving.name, call.auth)
	}
	if !serving.side.appKey.signed(t, assertion) {
		t.Errorf("%s minted with an assertion its own App key did not sign: a mint is signed by the serving side's key alone", serving.name)
	}
	other := world.other(serving).side
	if other.appKey.signed(t, assertion) {
		t.Errorf("%s minted with %s's App key, which is the other installation's credential", serving.name, other.name)
	}
	if acts.mintToken != serving.side.installationToken {
		t.Errorf("the run holds the installation token %q, and %s's fake issued %q: the token the run was handed did not come from the serving side",
			acts.mintToken, serving.name, serving.side.installationToken)
	}
	other.outside.silent(t, act+" was served by "+serving.name+" alone")
	return serving.side
}

// e2eWorkspaceSpend reads the workspace's meter node for the month this stand
// runs in: what the pool has been charged, per member.
func e2eWorkspaceSpend(t *testing.T, st *e2eStand) (budget.WorkspaceSpend, bool) {
	t.Helper()
	var spend budget.WorkspaceSpend
	found, err := st.ws.Get(context.Background(), budget.PathWorkspaceSpend(e2eWorkspace, budget.MonthKey(st.now)), &spend)
	if err != nil {
		t.Fatalf("the workspace's meter could not be read: %v", err)
	}
	return spend, found
}

// e2eKindsOf is the kinds that reach one repository's run: the model kind and
// the run's own forge's — the two forge kinds are their forge's own name, so a
// repository's provider kind IS the kind of credential its git traffic uses. The
// other forge's kind reaches no run of this repository at all (a run of a GitHub
// repository never takes a Bitbucket credential), so the record leaves it with
// the project and this test asks nothing of it.
func e2eKindsOf(run *e2eMemberRun) []creds.Kind {
	return []creds.Kind{creds.KindModel, creds.Kind(run.provider)}
}

// e2eAssertRouted holds one run's record to the service each kind of it must be
// served by: the whole of what these two tests differ in.
func e2eAssertRouted(t *testing.T, st *e2eStand, run *e2eMemberRun, route creds.Route, want *e2eService) {
	t.Helper()
	for _, kind := range e2eKindsOf(run) {
		if got := st.world.serviceFor(route, kind); got != want {
			t.Errorf("the %s run of %s: the record its own project published names the %s kind's holder as %q, and this test needs every act served by %s",
				run.provider, run.canonical, kind, route.Holder(kind), want.name)
		}
	}
}

// e2eAppID is the App ID the mint call carries: a number, not a credential, and
// the only field of a mint the caller supplies.
const e2eAppID = "1234567"

// TestWorkspaceServesAMemberRunEndToEnd is the plan's own red step, green: the
// member's project holds none of the three credentials its two runs need
// (routeFacts{} is a repository with no copy of its own), so every act is
// served by the workspace's service, on the workspace's credentials, and the
// project's own service is never called at all.
//
// The three acts are the three the workspace-service plan's C2 and C3 serve: a
// model call, metered against the workspace's own cap; a Bitbucket push through
// the routed git path; and a GitHub installation-token mint.
func TestWorkspaceServesAMemberRunEndToEnd(t *testing.T) {
	now := time.Now().UTC()
	st := e2eStandUp(t, routeFacts{}, now)
	ctx := context.Background()

	for _, run := range []struct {
		run   *e2eMemberRun
		route creds.Route
	}{{st.bb, st.bbRoute}, {st.gh, st.ghRoute}} {
		e2eAssertRouted(t, st, run.run, run.route, st.world.workspace)
	}

	acts := e2eDriveTheThreeActs(t, ctx, st)

	e2eAssertTheModelCall(t, "the model call", st.world, st.bbRoute, acts)
	e2eAssertThePush(t, "the push", st.world, st.bbRoute, acts)
	e2eAssertTheMint(t, "the mint", st.world, st.ghRoute, acts)

	// The project's service was never called — not for the model call, not for
	// the push and not for the mint. It is built whole and would have served
	// each of them had the run reached it, so this is a statement about what
	// the run did rather than about what the project's copy could do.
	st.world.project.quiet(t)
	st.world.project.side.outside.silent(t, "the project's credentials were never spent")

	// The model call is metered: the workspace's own record holds what the
	// member's call cost it.
	spend, found := e2eWorkspaceSpend(t, st)
	if !found {
		t.Fatalf("the workspace's meter was never written, and a paid call through its pool is the one thing this test meters")
	}
	if spend.Settled() <= 0 {
		t.Errorf("the workspace's meter holds %d settled micros for %s after a paid model call, want the call charged to the member that made it",
			spend.Settled(), e2eMember)
	}
}

// TestTheProjectsOwnCopyKeepsTheWorkspaceUntouched is the same run with the
// project holding its own copy of all three credentials: the facts are the ones
// `fugaro update` reads from a project whose bundle and policy carry them
// (routeFacts.names, bitbucket, appKey and the policy's own admissions), so the
// record it publishes moves no kind and every act is served by the project's own
// service — the workspace's service is never called and the workspace's meter is
// never written.
func TestTheProjectsOwnCopyKeepsTheWorkspaceUntouched(t *testing.T) {
	now := time.Now().UTC()
	policy, found, err := projectpolicy.Decode([]byte(e2eMemberPolicy()))
	if err != nil || !found {
		t.Fatalf("the member's own published policy is not one its own reader accepts (found %v): %v", found, err)
	}
	admissions, err := repoAdmissions(policy)
	if err != nil {
		t.Fatalf("the admissions the member's own policy publish derives: %v", err)
	}
	facts := routeFacts{
		names:      map[string]bool{config.AnthropicSecret: true},
		bitbucket:  true,
		appKey:     true,
		policy:     policy,
		admissions: admissions,
	}
	st := e2eStandUp(t, facts, now)
	ctx := context.Background()

	for _, run := range []struct {
		run   *e2eMemberRun
		route creds.Route
	}{{st.bb, st.bbRoute}, {st.gh, st.ghRoute}} {
		e2eAssertRouted(t, st, run.run, run.route, st.world.project)
	}

	acts := e2eDriveTheThreeActs(t, ctx, st)

	e2eAssertTheModelCall(t, "the model call", st.world, st.bbRoute, acts)
	e2eAssertThePush(t, "the push", st.world, st.bbRoute, acts)
	e2eAssertTheMint(t, "the mint", st.world, st.ghRoute, acts)

	// The workspace was never called, and never paid: a member that holds its
	// own copy is served entirely by its own service.
	st.world.workspace.quiet(t)
	st.world.workspace.side.outside.silent(t, "the workspace's credentials were never spent")
	if spend, found := e2eWorkspaceSpend(t, st); found && spend.Settled() != 0 {
		t.Errorf("the workspace's meter holds %d settled micros, and a member served by its own copy spends none of the workspace's cap", spend.Settled())
	}
}
