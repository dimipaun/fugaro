// e2eKey is one RS256 key pair, and the key set a service reads it by: the
// public half is served under the kid every token this test signs carries, so a
// verifier in credsvc accepts what the run below presents and refuses anything
// else. It is generated per test (no fixture holds a key) and it is a KeySource
// itself, which is what AuthConfig.Keys and AuthConfig.JobKeys take.
type e2eKey struct {
	kid  string
	priv *rsa.PrivateKey
}

func newE2EKey(t *testing.T, kid string) *e2eKey {
	t.Helper()
	priv, err := rsa.GenerateKey(rand.Reader, 2048)
	if err != nil {
		t.Fatalf("the test's own signing key: %v", err)
	}
	return &e2eKey{kid: kid, priv: priv}
}

// Key is credsvc.KeySource over this one key pair. A kid this set does not
// publish is ErrUnknownKeyID, which is the refusal the contract names for a
// miss, so a token signed by another key fails the way a real one does rather
// than with an error of this test's invention.
func (k *e2eKey) Key(_ context.Context, kid string) (*rsa.PublicKey, error) {
	if kid != k.kid {
		return nil, fmt.Errorf("%w: this test publishes one key", credsvc.ErrUnknownKeyID)
	}
	return &k.priv.PublicKey, nil
}

// sign builds a compact RS256 JWT over these claims, as Google's own minters
// do: a base64url header naming the kid, a base64url payload and the RS256
// signature over the two.
func (k *e2eKey) sign(t *testing.T, claims map[string]any) string {
	t.Helper()
	head := base64.RawURLEncoding.EncodeToString([]byte(`{"alg":"RS256","kid":"` + k.kid + `","typ":"JWT"}`))
	payload, err := json.Marshal(claims)
	if err != nil {
		t.Fatalf("the claims of the token this test signs: %v", err)
	}
	body := head + "." + base64.RawURLEncoding.EncodeToString(payload)
	sum := sha256.Sum256([]byte(body))
	sig, err := rsa.SignPKCS1v15(rand.Reader, k.priv, crypto.SHA256, sum[:])
	if err != nil {
		t.Fatalf("signing the token this test mints: %v", err)
	}
	return body + "." + base64.RawURLEncoding.EncodeToString(sig)
}

// e2eCall is one call a service made to a party outside Fugaro, as the test
// reads it back: where it went, what it carried and — the field most of the
// assertions below are about — the credential it authenticated with.
type e2eCall struct {
	method string
	host   string
	path   string
	// auth is the Authorization header verbatim, which is where a proxied git
	// call's Basic credential and a REST call's bearer token both arrive.
	auth string
	// apiKey is the x-api-key header, which is how a model call presents the
	// key the service settled on.
	apiKey string
	body   string
}

// String is the one line a failure message carries: where the call went and
// what it was, never what it presented. The two headers that hold a credential
// are compared by the assertions below and are not something an operator should
// have to read past in a test's output.
func (c e2eCall) String() string { return c.method + " " + c.host + c.path }

// e2eAnswer is what one fake party answers.
type e2eAnswer struct {
	status int
	header http.Header
	body   []byte
}

// e2eOutside is one side's view of the world outside Fugaro: a single listener
// that stands in for Anthropic, Bitbucket and GitHub at once, and the record of
// every call the side's service made to any of them.
//
// One listener rather than three, because the seam is the service's own
// outbound client: Config.Client's transport is where a deployment resolves a
// host name, so rewriting the hop to a loopback address here is exactly what a
// test may do and what a service cannot tell apart — except for the record,
// which is the point. The transport checks the host it is asked for against the
// three parties a credentials service may reach, so a service that resolved a
// destination of its own fails this test rather than leaving the process.
type e2eOutside struct {
	// name is what this side is called in a failure message.
	name string
	srv  *httptest.Server
	// answers is what the fake says to a call, keyed by the party's host. A
	// host with no answer is a 404, which is a call this test did not expect.
	answers map[string]func(*http.Request, []byte) e2eAnswer

	mu    sync.Mutex
	calls []e2eCall
}

// The three parties a credentials service reaches, and the hosts each is
// addressed at. They are the production spellings (internal/gitprov's
// bitbucket and github, and the Anthropic API's own host), so a service that
// asked for another one is not answered here at all.
const (
	e2eAnthropicHost = "api.anthropic.com"
	e2eBitbucketHost = "bitbucket.org"
	e2eBitbucketAPI  = "api.bitbucket.org"
	e2eGitHubHost    = "api.github.com"
)

func newE2EOutside(t *testing.T, name string) *e2eOutside {
	t.Helper()
	o := &e2eOutside{name: name, answers: map[string]func(*http.Request, []byte) e2eAnswer{}}
	o.srv = httptest.NewServer(http.HandlerFunc(o.serve))
	t.Cleanup(o.srv.Close)
	return o
}

// serves stands in for whichever party the call was addressed to. The original
// host survives the rewrite as the Host header, which is what tells the three
// apart here.
func (o *e2eOutside) serve(w http.ResponseWriter, r *http.Request) {
	body, err := io.ReadAll(r.Body)
	if err != nil {
		http.Error(w, "the test could not read the call", http.StatusInternalServerError)
		return
	}
	o.mu.Lock()
	o.calls = append(o.calls, e2eCall{
		method: r.Method, host: r.Host, path: r.URL.Path,
		auth: r.Header.Get("Authorization"), apiKey: r.Header.Get("x-api-key"), body: string(body),
	})
	answer := o.answers[r.Host]
	o.mu.Unlock()
	if answer == nil {
		w.WriteHeader(http.StatusNotFound)
		return
	}
	a := answer(r, body)
	if a.status == 0 {
		a.status = http.StatusOK
	}
	for k, vs := range a.header {
		w.Header()[k] = vs
	}
	w.WriteHeader(a.status)
	_, _ = w.Write(a.body)
}

// answer sets what this side's fake says to one party.
func (o *e2eOutside) answer(host string, f func(*http.Request, []byte) e2eAnswer) {
	o.mu.Lock()
	defer o.mu.Unlock()
	o.answers[host] = f
}

// answered is every call this side's service made, in order.
func (o *e2eOutside) answered() []e2eCall {
	o.mu.Lock()
	defer o.mu.Unlock()
	return append([]e2eCall(nil), o.calls...)
}

// client is the outbound client one side's service is configured with: the one
// seam this test needs, since the service builds its own destinations (the
// provider's host, bitbucket.org, api.github.com) and no configuration and no
// caller can name another.
func (o *e2eOutside) client() *http.Client {
	base, err := url.Parse(o.srv.URL)
	if err != nil {
		panic("the fake's own address is not a URL: " + err.Error())
	}
	return &http.Client{Transport: e2eTransport{base: base, out: o}}
}

// e2eTransport is that client's transport: it pins every call to one of the
// three parties, records it and rewrites the hop to the fake's loopback
// listener, keeping the original host so the fake knows who it is standing in
// for.
type e2eTransport struct {
	base *url.URL
	out  *e2eOutside
}

func (h e2eTransport) RoundTrip(r *http.Request) (*http.Response, error) {
	host := r.URL.Hostname()
	switch host {
	case e2eAnthropicHost, e2eBitbucketHost, e2eBitbucketAPI, e2eGitHubHost:
	default:
		return nil, fmt.Errorf("a service reached %s, and a credentials service reaches Anthropic, Bitbucket and GitHub alone", r.URL)
	}
	c := r.Clone(r.Context())
	c.URL.Scheme, c.URL.Host = h.base.Scheme, h.base.Host
	// The original host is what the fake dispatches on, so the request is
	// labelled with the party it was addressed to rather than with the
	// loopback address it is delivered to.
	c.Host = r.URL.Host
	return http.DefaultTransport.RoundTrip(c)
}

