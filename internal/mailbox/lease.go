// The consumer's lease on the heartbeat (mobile P4.1, Task T3): the Go binding
// of shared/lease (P1.2, merged), and the store that holds it.
//
// Ruling M1 of docs/plans/2026-10-18-mobile-mailbox-consumer.md: **the lease IS
// the heartbeat, taken by an ETag compare-and-swap, and there is no fourth
// node.** The consumer reads `mailbox/$mb/heartbeat` with
// `internal/rtdb`'s `GetETag` and writes `{at, boot, mac}` back with
// `PutIfMatch`; a `rtdb.ErrPrecondition` (the 412) is a lost race, re-read a
// **bounded** number of times and never forced — the shape
// `internal/budget/kill.go`'s `SetKill` already uses in production. Two
// consumers that both read an empty heartbeat and both get `ok: true` from
// `TakeLease` must not both be able to write: the store's if-match is the
// fence, and `TestTwoConsumersOneLease` is this repository's evidence for it.
//
// **The credential is the operator's ADC** (C0 of the plan). The heartbeat's
// only `.read` grant is the phone's (`MAILBOX`), and the consumer's token
// (`CONSUMER`) appears in no `.read` in the mailbox subtree at all, so the ETag
// read would be refused it; the CAS's arbitration is the store's `if-match`,
// evaluated for whoever sends the write, so the fence is unaffected by that
// choice. This file therefore holds no credential logic — the caller opens the
// client once, as every cloud command does.
//
// **Fail closed.** Every error path here writes nothing and takes no lease: a
// heartbeat that does not validate as one is refused rather than believed (an
// unreadable claim is never taken over — shared/lease's own rule, deliberately
// stricter than the CLI's launch claim), a signer that fails means no write and
// therefore no lease (M4b: the heartbeat write IS the lease), and a store that
// keeps changing under the write ends as an error rather than a forced write.
//
// **What this file is not.** It holds no tag function, no key and no keychain
// (those are T2 and T2a's, in mac.go, so the two halves of the protocol cannot
// drift into two implementations of the same covered field set); no ledger
// (T4's); no command, no flag and no output (T5's). The heartbeat it writes is
// signed by a **signer the caller passes in** — `LeaseSigner` — which is how
// M4b's rule is enforced here without this package owning the key.
//
// **One thing the plan's loop does not do, said out loud:** the heartbeat this
// file reads back is validated as a heartbeat (its shape) but its **tag is not
// verified** before its claim is believed — the plan's §7 loop goes straight
// from the ETag read to `takeLease`, and the verification function is mac.go's
// (T2). The exposure is bounded and named: the read is under the operator's ADC
// and the CAS is still the fence, so a forged heartbeat can at most make one
// consumer yield, never make two act. It is listed in the pull request rather
// than fixed here, because fixing it would take a task this one is not.
package mailbox

import (
	"context"
	"errors"
	"fmt"
	"strings"
	"unicode/utf8"

	"github.com/dimipaun/fugaro/internal/rtdb"
)

// The bounds shared/lease owns. They are declared here because Go cannot import
// the module, and the corpus its own test writes
// (`internal/mailbox/testdata/lease-parity.json`, generated by
// `shared/lease/parity.test.js`) carries the module's values for
// TestLeaseCorpusReplay to hold these to, so a bound that moves on either side
// is a failing test rather than two ends disagreeing about who holds a mailbox
// (M9).
const (
	// ClaimTTL is CLAIM_TTL: how long a lease protects its holder, in
	// milliseconds — ten minutes.
	ClaimTTL = 10 * 60 * 1000
	// MaxClockSkew is MAX_CLOCK_SKEW: how far ahead of the caller's clock a
	// held lease may be and still be honoured — five minutes. Past it the lease
	// counts as expired and may be taken over, so no timestamp can block a
	// mailbox for ever.
	MaxClockSkew = 5 * 60 * 1000
	// MaxTTL is MAX_TTL: the longest TTL a lease state may carry — one day.
	MaxTTL = 24 * 60 * 60 * 1000
	// MaxTimestamp is MAX_TIMESTAMP: 2100-01-01T00:00:00Z in milliseconds since
	// the epoch. A later instant is refused, not clamped.
	MaxTimestamp = 4102444800000
	// MaxHolderLength is MAX_HOLDER_LENGTH, in Unicode code points.
	MaxHolderLength = 256
	// LeaseAttempts bounds the ETag retries of one take, like
	// `budget.SetAttempts` bounds a kill switch's.
	LeaseAttempts = 5
)

// The refusal codes, spelled exactly as the module's LEASE_CODES spells them.
// The corpus pins the vocabulary: a code added, dropped or reworded on one end
// is a failing test, not a log line that quietly means something else.
const (
	// LeaseUnknownField: a lease, a state or a request carries a field the
	// module does not define.
	LeaseUnknownField Code = "unknown-field"
	// LeaseMissingField: one of the fields above is absent.
	LeaseMissingField Code = "missing-field"
	// LeaseBadType: the value is not a plain object at all.
	LeaseBadType Code = "bad-type"
	// LeaseBadHolder: the holder is not a string, is blank, padded, or carries
	// a character the holder's shape refuses.
	LeaseBadHolder Code = "bad-holder"
	// LeaseBadTimestamp: an instant is not a whole number of milliseconds from
	// 1 to MaxTimestamp.
	LeaseBadTimestamp Code = "bad-timestamp"
	// LeaseBadTTL: the state's TTL is not a whole number of milliseconds from 1
	// to MaxTTL.
	LeaseBadTTL Code = "bad-ttl"
	// LeaseOversize: the holder is longer than MaxHolderLength code points.
	LeaseOversize Code = "oversize"
	// LeaseUnreadableClaim: the state holds something that is not a lease.
	LeaseUnreadableClaim Code = "unreadable-claim"
	// LeaseNotHolder: a release names a holder other than the one holding the
	// lease.
	LeaseNotHolder Code = "not-holder"
	// LeaseNoLease: a release names a holder and nothing is held.
	LeaseNoLease Code = "no-lease"
	// LeaseAlreadyClaimed: a lease is held, by anyone, and its TTL has not run
	// out. It is the answer a second holder gets.
	LeaseAlreadyClaimed Code = "already-claimed"
)

// LeaseCodes is every code the lease module speaks, held to the module's own
// LEASE_CODES by TestLeaseCorpusReplay.
var LeaseCodes = []Code{
	LeaseUnknownField, LeaseMissingField, LeaseBadType, LeaseBadHolder,
	LeaseBadTimestamp, LeaseBadTTL, LeaseOversize, LeaseUnreadableClaim,
	LeaseNotHolder, LeaseNoLease, LeaseAlreadyClaimed,
}

// The field sets, exactly: a record carrying anything else is refused rather
// than stored, the way the rules template closes a subtree with
// `"$other": { ".validate": false }`.
var (
	leaseFields        = []string{"holder", "at"}
	leaseStateFields   = []string{"claim", "ttl"}
	leaseTakeFields    = []string{"holder", "at"}
	leaseReleaseFields = []string{"holder"}
)

// Lease is a holder and the instant its claim was taken at: `{holder, at}`,
// `internal/runstore`'s `Claim`, in the module's milliseconds.
type Lease struct {
	Holder string
	At     int64
}

// LeaseResult is one answer of the lease module, in the shape the corpus
// records it: whether the call was refused, the refusal's code (and, for an
// unreadable claim, the code of the lease that was unreadable), the lease the
// call read, held, refused by or released, and the state the call answers with.
//
// State is nil when the state itself was unreadable — the module hands no state
// back when it has none to hand back — and a caller threads it otherwise.
type LeaseResult struct {
	OK       bool
	Code     Code
	Because  Code
	Lease    *Lease
	Existing *Lease
	Released *Lease
	State    Record
}

// EmptyLeaseState is the state a lease is taken from: no claim held, and the
// TTL any claim taken from it will be protected for.
func EmptyLeaseState(ttl int64) Record {
	return stateRecord(nil, ttl)
}

// stateRecord builds the state the module answers with. A nil claim is the
// state's own `null`: nothing is held.
func stateRecord(claim *Lease, ttl int64) Record {
	var held any
	if claim != nil {
		held = leaseRecord(*claim)
	}
	return Record{"claim": held, "ttl": ttl}
}

// leaseRecord is a lease as the module stores one.
func leaseRecord(lease Lease) Record {
	return Record{"holder": lease.Holder, "at": lease.At}
}

// ReadLease is the claim this state holds, or null. A state holding something
// that is not a lease is refused, never read as a zero lease a caller would
// then have to remember not to trust.
func ReadLease(state Record) LeaseResult {
	claim, _, refused := readLeaseState(state)
	if refused != nil {
		return *refused
	}
	return LeaseResult{OK: true, Lease: claim}
}

// TakeLease takes the lease, or is told who holds it.
//
// The request is `{holder, at}`: `at` is the caller's own reading of ONE
// authoritative clock (D117 — the server's, never each consumer's own), and it
// becomes the lease's timestamp when the take succeeds. A held lease is stale —
// and so takeable — when the caller's instant is at least the TTL past it; one
// timestamped ahead by at most MaxClockSkew is fresh (two clocks disagreeing is
// not a dead holder), and one ahead by more than that is treated as expired, so
// no timestamp holds a lease for ever. A holder that already holds the lease is
// answered `already-claimed` too, whatever its holder string: a lease is
// renewed by taking it again once it has gone stale, never by re-taking a fresh
// one.
//
// It is the module's function, not the store's: it decides, and writes nothing.
// Take is the store half, below.
func TakeLease(state Record, request Record) LeaseResult {
	claim, ttl, refused := readLeaseState(state)
	if refused != nil {
		return *refused
	}
	held := stateRecord(claim, ttl)

	snap, code := leaseSnapshot(request, leaseTakeFields)
	if code != "" {
		return LeaseResult{Code: code, State: held}
	}
	holder, ok := snap["holder"].(string)
	if !ok {
		return LeaseResult{Code: LeaseBadHolder, State: held}
	}
	if code := validateLeaseHolder(holder); code != "" {
		return LeaseResult{Code: code, State: held}
	}
	at, code := leaseInstant(snap["at"])
	if code != "" {
		return LeaseResult{Code: code, State: held}
	}

	mine := Lease{Holder: holder, At: at}
	if claim != nil && leaseIsFresh(*claim, at, ttl) {
		return LeaseResult{Code: LeaseAlreadyClaimed, Existing: claim, State: held}
	}
	return LeaseResult{OK: true, Lease: &mine, State: stateRecord(&mine, ttl)}
}

// ReleaseLease releases the lease, if it is the caller's own. A release is
// never a takeover, so releasing another holder's lease is refused rather than
// done; the TTL is carried on, so the next take is protected the same way.
func ReleaseLease(state Record, request Record) LeaseResult {
	claim, ttl, refused := readLeaseState(state)
	if refused != nil {
		return *refused
	}
	held := stateRecord(claim, ttl)

	snap, code := leaseSnapshot(request, leaseReleaseFields)
	if code != "" {
		return LeaseResult{Code: code, State: held}
	}
	holder, ok := snap["holder"].(string)
	if !ok {
		return LeaseResult{Code: LeaseBadHolder, State: held}
	}
	if code := validateLeaseHolder(holder); code != "" {
		return LeaseResult{Code: code, State: held}
	}
	if claim == nil {
		return LeaseResult{Code: LeaseNoLease, State: held}
	}
	if claim.Holder != holder {
		return LeaseResult{Code: LeaseNotHolder, State: held}
	}
	return LeaseResult{OK: true, Released: claim, State: EmptyLeaseState(ttl)}
}

// readLeaseState reads a state's claim and TTL, each judged once. A refusal
// from here is the same refusal from every function that reads a state — which
// is why they all agree about a malformed one — and it carries **no** state:
// there is none read to hand back.
func readLeaseState(state Record) (*Lease, int64, *LeaseResult) {
	snap, code := leaseSnapshot(state, leaseStateFields)
	if code != "" {
		return nil, 0, &LeaseResult{Code: code}
	}
	ttl, ok := intValue(snap["ttl"])
	if !ok || ttl < 1 || ttl > MaxTTL {
		return nil, 0, &LeaseResult{Code: LeaseBadTTL}
	}
	if snap["claim"] == nil {
		return nil, ttl, nil
	}
	claim, code := validateLease(snap["claim"])
	if code != "" {
		// Deliberately stricter than the CLI's launch claim, which treats an
		// unreadable claim as stale and takes it over: a state value carries no
		// generation, so an unreadable claim here is an ambiguity, and the
		// answer to an ambiguity about who holds the lease is a refusal.
		return nil, 0, &LeaseResult{Code: LeaseUnreadableClaim, Because: code}
	}
	return claim, ttl, nil
}

// validateLease decides whether a value is a lease, and answers the inner code
// when it is not.
func validateLease(value any) (*Lease, Code) {
	snap, code := leaseSnapshot(value, leaseFields)
	if code != "" {
		return nil, code
	}
	holder, ok := snap["holder"].(string)
	if !ok {
		return nil, LeaseBadHolder
	}
	if code := validateLeaseHolder(holder); code != "" {
		return nil, code
	}
	at, code := leaseInstant(snap["at"])
	if code != "" {
		return nil, code
	}
	return &Lease{Holder: holder, At: at}, ""
}

// leaseSnapshot reads a value as an object with exactly these fields: the
// module's order, unknown first and then missing, so the two ends answer a
// record carrying both with the same code. Every field is read once, here —
// Go has no getters to answer one value to the validation and another to the
// comparison, but reading each field from this one snapshot keeps the two ends'
// shapes the same to read.
func leaseSnapshot(value any, fields []string) (Record, Code) {
	obj, isObject := asObject(value)
	if !isObject || obj == nil {
		return nil, LeaseBadType
	}
	for _, key := range sortedKeys(obj) {
		if !contains(fields, key) {
			return nil, LeaseUnknownField
		}
	}
	for _, key := range fields {
		if _, present := obj[key]; !present {
			return nil, LeaseMissingField
		}
	}
	return obj, ""
}

// leaseInstant reads an instant: a whole number of milliseconds from 1 to
// MaxTimestamp. Zero and -0 are refused — a lease taken at zero is stale the
// instant it is written — and a value that arrives as a string is refused
// rather than parsed, because a guessed instant is how a lease goes stale
// early.
func leaseInstant(value any) (int64, Code) {
	at, isInteger := intValue(value)
	if !isInteger {
		return 0, LeaseBadTimestamp
	}
	if at < 1 || at > MaxTimestamp {
		return 0, LeaseBadTimestamp
	}
	return at, ""
}

// leaseIsFresh is the module's freshness rule: a claim is fresh until its own
// timestamp plus the TTL, and a claim ahead of the caller by more than
// MaxClockSkew is not fresh whatever the TTL says.
func leaseIsFresh(current Lease, at, ttl int64) bool {
	if current.At-at > MaxClockSkew {
		return false
	}
	return at-current.At < ttl
}

// validateLeaseHolder answers the module's own code for a holder this consumer
// will not accept, and "" for one it will.
//
// **The shape here is the schema's, not the module's**, and it is deliberately
// the stricter of the two: the holder this consumer passes is a heartbeat's
// `boot` id, whose shape the merged `shared/mailbox-schema` already fixes (an
// ASCII identity of at most BootMax characters — T1 binds it). The module's own
// holder rule is looser: it accepts any printable NFC name, a CJK one included.
// The codes are still the module's, so the two ends agree about *why* a holder
// was refused — `oversize` past the module's own bound, `bad-holder` for the
// rest — and the corpus's holder cases are the classes both ends refuse. A
// holder the module accepts and this end refuses (a non-ASCII name, or one
// longer than BootMax) is a value that can never reach here from a heartbeat.
func validateLeaseHolder(holder string) Code {
	if utf8.RuneCountInString(holder) > MaxHolderLength {
		return LeaseOversize
	}
	if strings.TrimSpace(holder) == "" {
		return LeaseBadHolder
	}
	if holder != strings.TrimSpace(holder) {
		return LeaseBadHolder
	}
	if !identityPattern.MatchString(holder) {
		return LeaseBadHolder
	}
	if utf16Len(holder) > BootMax {
		return LeaseBadHolder
	}
	return ""
}

// HeartbeatPath is the one node the lease lives in: `mailbox/<mailbox>/heartbeat`
// (M1 — no fourth node). The mailbox is the account's own key — the rules bind
// `$mb == auth.uid` — so the name is validated as what the database will treat
// it as: **a node key**. A name carrying one of the characters the database
// refuses in a key (`.`, `$`, `#`, `[`, `]`, `/`, `%`, or a control character)
// is refused here rather than escaped or sent, because an escaped path would
// name a different node than the rules grant.
//
// The bound is SenderMax, not the schema's IDMax: a mailbox is a Firebase uid
// (at most 128 characters), and it is also the `sender` of every message it
// writes, which is the string that bound is the tree's (MaxString, 200).
func HeartbeatPath(mailbox string) (string, error) {
	if strings.TrimSpace(mailbox) == "" {
		return "", errors.New("mailbox: a mailbox name is the account's key, and it is blank")
	}
	if utf16Len(mailbox) > SenderMax {
		return "", fmt.Errorf("mailbox: a mailbox name is at most %d characters", SenderMax)
	}
	for _, r := range mailbox {
		if forbiddenKeyChars[r] || r < 0x20 || r == 0x7f {
			return "", fmt.Errorf("mailbox: a mailbox name is a database key, and it may not contain %q", r)
		}
	}
	return "mailbox/" + mailbox + "/heartbeat", nil
}

// HeartbeatStore is the part of the database the lease needs, which is exactly
// the compare-and-swap M1 rests on: a read that carries the node's ETag, and a
// write conditional on it. `*rtdb.Client` is one.
type HeartbeatStore interface {
	GetETag(ctx context.Context, path string, out any) (etag string, found bool, err error)
	PutIfMatch(ctx context.Context, path, etag string, v any) error
}

// LeaseSigner signs the heartbeat a take writes, in the `heartbeat` direction,
// and answers the tag (M4b). It is the caller's — T2a's `Sign`, with the key
// read from the OS keychain by item name — because this package holds no key.
// A signer that fails means **no write and therefore no lease**: the heartbeat
// write IS the lease, so a consumer that cannot sign acts on nothing.
type LeaseSigner func(hb Heartbeat) (string, error)

// LeaseVerdict is what a take, a renewal check or a re-read answered, in the
// words the command reports them in: held, taken over, lost — or none, when
// `--no-heartbeat` says the consumer holds no lease at all.
type LeaseVerdict string

const (
	// LeaseHeld: the lease is this consumer's and it may act.
	LeaseHeld LeaseVerdict = "held"
	// LeaseTakenOver: the lease was stale (or absent) and this consumer now
	// holds it.
	LeaseTakenOver LeaseVerdict = "taken-over"
	// LeaseLost: someone else holds it, the store refused the write, or the
	// re-read no longer found this consumer's claim — either way this consumer
	// writes nothing and acts on nothing until the next take.
	LeaseLost LeaseVerdict = "lost"
	// LeaseNone: no lease was taken because no heartbeat is written
	// (`--no-heartbeat`), so nothing may be acted on.
	LeaseNone LeaseVerdict = "none"
)

// LeaseRun is the outcome of one take or re-read.
type LeaseRun struct {
	Verdict LeaseVerdict
	// Lease is the claim this run is about: the one this consumer now holds
	// when the verdict is held or taken-over, and the one it found — the other
	// holder's — when the verdict is lost. It is nil only for LeaseNone.
	Lease *Lease
	// Holder names whoever holds the mailbox when the verdict is lost.
	Holder string
	// ExpiresAt is the instant the claim stops being fresh: `at + ttl`. It is
	// the module's arithmetic, not a deadline this package watches.
	ExpiresAt int64
	// Attempts is how many compare-and-swap attempts the run spent, so a caller
	// can see the retry stayed inside its bound.
	Attempts int
}

// LeaseOptions is what one take or re-read needs.
type LeaseOptions struct {
	// Mailbox is the phone's mailbox key, and Holder is this consumer's boot
	// id: together they are the node the lease lives in and the identity it
	// names.
	Mailbox string
	Holder  string
	// At is ONE authoritative clock's reading, in milliseconds since the epoch —
	// the server's (D117), never this process's own.
	At int64
	// TTL is the state's TTL. Zero means ClaimTTL, the module's default.
	TTL int64
	// Attempts bounds the retries of one take. Zero means LeaseAttempts.
	Attempts int
	// Sign signs the heartbeat. It is required: no signer, no write, no lease.
	Sign LeaseSigner
	// NoHeartbeat is `--no-heartbeat`: take no lease, write nothing, act on
	// nothing. It exists for diagnosis, and it is what keeps a consumer with no
	// writable heartbeat from acting at all.
	NoHeartbeat bool
}

// ttl is the TTL this run protects its claim with.
func (o LeaseOptions) ttl() int64 {
	if o.TTL <= 0 {
		return ClaimTTL
	}
	return o.TTL
}

// attempts is the retry bound this run uses.
func (o LeaseOptions) attempts() int {
	if o.Attempts <= 0 {
		return LeaseAttempts
	}
	return o.Attempts
}

// check refuses an option set this package will not write with: a holder that
// is not a boot id, an instant outside the module's bounds, or a take with no
// signer. It is called before any request is made, so a refusal costs nothing
// and writes nothing.
func (o LeaseOptions) check() error {
	if code := validateLeaseHolder(o.Holder); code != "" {
		return fmt.Errorf("mailbox: a lease holder is a boot id this consumer can write (%s)", code)
	}
	if o.TTL != 0 && (o.TTL < 1 || o.TTL > MaxTTL) {
		return fmt.Errorf("mailbox: a lease TTL is a whole number of milliseconds from 1 to %d (%s)", MaxTTL, LeaseBadTTL)
	}
	if _, code := leaseInstant(o.At); code != "" {
		return fmt.Errorf("mailbox: the instant a lease is taken at is a whole number of milliseconds from 1 to %d (%s)", MaxTimestamp, code)
	}
	if o.Sign == nil {
		return ErrLeaseNoSigner
	}
	return nil
}

// ErrLeaseNoSigner: the lease has no signer, so the heartbeat cannot be signed
// and therefore cannot be written — and since the heartbeat write IS the lease,
// there is no lease and nothing may be acted on (M4b).
var ErrLeaseNoSigner = errors.New("mailbox: the heartbeat cannot be signed, so no lease is taken")

// ErrLeaseContention: the heartbeat kept changing under the write, so the take
// stopped rather than forcing it. Nothing was written by this consumer.
var ErrLeaseContention = errors.New("mailbox: the heartbeat kept changing under the write")

// Take takes the lease on the heartbeat, or reports who holds it.
//
// It is the read and the write M1 names: the node is read with its ETag, the
// module decides whether the caller may take the claim, and the heartbeat is
// written back **conditional on the ETag read**. A lost race — the store's 412
// — is re-read and re-decided, at most Attempts times, and is never forced; a
// take that loses every attempt ends as ErrLeaseContention with nothing written
// by this consumer.
//
// A heartbeat that is present but is not a heartbeat the schema accepts is
// refused as an error: an unreadable claim is never taken over.
func Take(ctx context.Context, store HeartbeatStore, opts LeaseOptions) (LeaseRun, error) {
	if opts.NoHeartbeat {
		return LeaseRun{Verdict: LeaseNone}, nil
	}
	path, err := HeartbeatPath(opts.Mailbox)
	if err != nil {
		return LeaseRun{}, err
	}
	if err := opts.check(); err != nil {
		return LeaseRun{}, err
	}
	ttl := opts.ttl()

	for attempt := 1; attempt <= opts.attempts(); attempt++ {
		state, etag, claim, err := readHeartbeat(ctx, store, path, ttl)
		if err != nil {
			return LeaseRun{}, err
		}
		taken := TakeLease(state, Record{"holder": opts.Holder, "at": opts.At})
		if !taken.OK {
			if taken.Code != LeaseAlreadyClaimed {
				// A state this consumer cannot read is not a state it may write
				// from: fail closed rather than guess at the claim.
				return LeaseRun{}, fmt.Errorf("mailbox: the heartbeat at %s cannot be read as a lease (%s)", path, taken.Code)
			}
			// Someone's fresh claim: write nothing, act on nothing.
			return lostRun(*taken.Existing, ttl, attempt), nil
		}

		value, err := signedHeartbeat(opts)
		if err != nil {
			return LeaseRun{}, err
		}
		err = store.PutIfMatch(ctx, path, etag, value)
		switch {
		case err == nil:
			verdict := LeaseHeld
			if claim != nil {
				// A claim was held and was stale: this consumer took it over.
				verdict = LeaseTakenOver
			}
			return LeaseRun{
				Verdict:   verdict,
				Lease:     taken.Lease,
				Holder:    opts.Holder,
				ExpiresAt: opts.At + ttl,
				Attempts:  attempt,
			}, nil
		case errors.Is(err, rtdb.ErrPrecondition):
			// The fence, and the whole point of it: this write is not forced.
			// The heartbeat moved under us, so re-read it and decide again.
			continue
		default:
			return LeaseRun{}, err
		}
	}
	return LeaseRun{}, ErrLeaseContention
}

// Confirm re-reads the lease before this consumer acts on it.
//
// The module's caller obligation is the reason it exists: **a holder stops
// acting by `claim.at + ttl − MaxClockSkew`** — ActionBound — or re-reads the
// lease first, because past that instant another claimant may, by the module's
// own rule, already hold it. This is that re-read: it writes nothing, and it
// answers lost unless the heartbeat still names this consumer's own, still
// fresh, claim.
func Confirm(ctx context.Context, store HeartbeatStore, opts LeaseOptions) (LeaseRun, error) {
	if opts.NoHeartbeat {
		return LeaseRun{Verdict: LeaseNone}, nil
	}
	path, err := HeartbeatPath(opts.Mailbox)
	if err != nil {
		return LeaseRun{}, err
	}
	if err := opts.check(); err != nil {
		return LeaseRun{}, err
	}
	ttl := opts.ttl()

	state, _, claim, err := readHeartbeat(ctx, store, path, ttl)
	if err != nil {
		return LeaseRun{}, err
	}
	if claim == nil || claim.Holder != opts.Holder {
		if claim == nil {
			return LeaseRun{Verdict: LeaseLost, Attempts: 1}, nil
		}
		return lostRun(*claim, ttl, 1), nil
	}
	// The claim is this consumer's. It must also still be fresh by the module's
	// rule: a stale claim is one another consumer may already have taken over,
	// so this holder stops acting and re-takes it on its next pass.
	decided := TakeLease(state, Record{"holder": opts.Holder, "at": opts.At})
	if decided.OK {
		return lostRun(*claim, ttl, 1), nil
	}
	return LeaseRun{
		Verdict:   LeaseHeld,
		Lease:     claim,
		Holder:    claim.Holder,
		ExpiresAt: claim.At + ttl,
		Attempts:  1,
	}, nil
}

// ActionBound is the instant past which the holder must re-read the lease
// before it acts: `claim.at + ttl − MaxClockSkew`. Before it, the claim cannot
// have been taken over by the module's own arithmetic; at or after it, another
// consumer's take could already have succeeded, so a holder that does not
// re-read is acting on a lease it may not hold.
func ActionBound(lease Lease, ttl int64) int64 {
	return lease.At + ttl - MaxClockSkew
}

// lostRun is the outcome of a mailbox someone else holds: nothing is written
// and nothing is acted on.
func lostRun(holder Lease, ttl int64, attempt int) LeaseRun {
	held := holder
	return LeaseRun{
		Verdict:   LeaseLost,
		Lease:     &held,
		Holder:    holder.Holder,
		ExpiresAt: holder.At + ttl,
		Attempts:  attempt,
	}
}

// readHeartbeat reads the heartbeat under the caller's credential and answers
// the lease state it holds, the ETag that state was read at, and the claim
// itself (nil when nothing is held).
//
// An absent node is the empty state — nobody holds the mailbox. A node that is
// present but does not validate as a heartbeat is an error, never a claim: the
// shape is the only thing this consumer can check without the key (the tag is
// mac.go's, T2), and a claim it cannot read is a claim it must not take over.
func readHeartbeat(ctx context.Context, store HeartbeatStore, path string, ttl int64) (Record, string, *Lease, error) {
	var node Record
	etag, found, err := store.GetETag(ctx, path, &node)
	if err != nil {
		return nil, "", nil, err
	}
	if !found || node == nil {
		return stateRecord(nil, ttl), etag, nil, nil
	}
	hb, refusal := ValidateHeartbeat(node)
	if refusal != nil {
		return nil, "", nil, fmt.Errorf("mailbox: the heartbeat at %s is not a heartbeat this schema accepts (%s)", path, refusal.Code)
	}
	claim := Lease{Holder: hb.Boot, At: hb.At}
	return stateRecord(&claim, ttl), etag, &claim, nil
}

// signedHeartbeat is the value a take writes: `{at, boot, mac}`, the three
// fields the merged rules allow on the heartbeat and no fourth. It is signed
// **before** it is written (M4b) and validated against the schema after signing
// (M10: every value this consumer writes is validated first), so a value that
// cannot be signed, or that the schema would refuse, is never written — and
// therefore never becomes a lease.
func signedHeartbeat(opts LeaseOptions) (Record, error) {
	if opts.Sign == nil {
		return nil, ErrLeaseNoSigner
	}
	mac, err := opts.Sign(Heartbeat{At: opts.At, Boot: opts.Holder})
	if err != nil {
		return nil, fmt.Errorf("mailbox: the heartbeat could not be signed, so nothing is written and no lease is taken: %w", err)
	}
	value := Record{"at": opts.At, "boot": opts.Holder, "mac": mac}
	if _, refusal := ValidateHeartbeat(value); refusal != nil {
		return nil, fmt.Errorf("mailbox: the signed heartbeat is not a heartbeat this schema accepts (%s), so nothing is written", refusal.Code)
	}
	return value, nil
}
