// website/test/meta.mjs — a page says what it is for, never why its own text exists (website
// redesign, D186; reconciliation findings RF5–RF8).
//
// **The rule: a page must not explain why its own text exists.** A reader came for the
// commands, the answers or the costs; a sentence about where the page's words come from —
// that a block is "rendered from" a file, that "nothing here is typed", that a document "is
// generated rather than written" — is the site talking about its own build. It is the one
// kind of text the redesign removes (RF5–RF8), and it is text no byte budget, no link check
// and no a11y check can see: it is short, well-formed and honest, which is exactly why it
// needs a gate of its own.
//
// What it is NOT: a ban on naming a document. The docs hub names the document each guide
// lives in, a page may link to `SECURITY.md`, and the changelog's entries are the release
// files' own lines. Those are citations a reader uses; the phrases below are the build
// explaining itself. That is why D186 chose an explicit phrase list over a rule about
// "naming a repository file", which would fail on every legitimate citation.
//
// The phrases are D186's own list, verbatim, and they are refused in the text a reader
// reads: the built page's text, its `<title>` included, read through `test/lib/html.mjs`
// with whitespace flattened and case ignored — a phrase split across two lines of a source
// file, or capitalized at the start of a sentence, is the same phrase to a reader. A script
// or style body is not text (`textOf`), so the site's own script is never its subject.
//
// The fixture cases below keep the refusal running: one page per phrase, in the shape a
// real page would carry it, plus a control page that says what it is for and is not
// refused. They were mutation-proved with `FUGARO_GATES_DIST` over a copy of `dist/` and by
// planting each phrase in a page's source; a phrase dropped from `PHRASES` fails the case
// that walks the list.
//
// Standard library only; no network (Global Constraint 4).

import { test } from 'node:test'
import assert from 'node:assert/strict'
import { mkdirSync, mkdtempSync, rmSync, writeFileSync } from 'node:fs'
import { tmpdir } from 'node:os'
import path from 'node:path'
import { DIST, builtPages, parse, textOf } from './lib/html.mjs'

// D186's list, verbatim: the provenance phrases the redesign removes. Each one is a way of
// telling the reader where the page's words came from instead of giving them the words.
export const PHRASES = [
  'rendered from',
  'Nothing here is typed',
  'as it is generated',
  'generated rather than written',
  'rather than written here',
  'rather than described here',
  'points at those documents rather than repeating them',
  // Not on D186's list; added in review of P4 after the flow (#574) shipped it on / and
  // /how-it-works/: a caption about where the captions come from is the same defect.
  'Every caption below is a line of',
]

/**
 * The provenance phrases a single built page carries, as failure lines. `rel` names the
 * page in them, so a failure says which page and which phrase.
 */
export function pageMetaFailures(html, rel) {
  const text = textOf(parse(html)).replace(/\s+/g, ' ')
  const out = []
  for (const phrase of PHRASES) {
    const at = text.toLowerCase().indexOf(phrase.toLowerCase())
    if (at === -1) continue
    const around = text.slice(Math.max(0, at - 60), at + phrase.length + 60).trim()
    out.push(
      `${rel} explains why its own text exists: ${JSON.stringify(phrase)} in "…${around}…". ` +
        'A page says what it is for; where its words come from is the build\'s business, not the reader\'s (D186).',
    )
  }
  return out
}

/** Every provenance phrase in a built artifact. */
export function metaFailures(dist) {
  return builtPages(dist).flatMap((page) => pageMetaFailures(page.html, page.rel))
}

/**
 * The generated-file banner's opening, as a reader would read it if it reached a page: the
 * generated files under `website/content/` — `cli-reference.md`, `go run ./ee/clidoc`'s
 * output, and `security.md`, `go run ./internal/clidoc`'s — start with
 * `<!-- generated by …; do not edit -->`, which is the build's note to itself.
 * (`downloads.json` is hand-kept and has no banner; the rule below is about the banner, not
 * about which files live there.) W1.3's content pipeline reads it as the `generator` and
 * `source` facts and drops it from the `body` it renders, and the redesign's RF8 states the
 * consequence as a premise: the banner is never on a page.
 *
 * It was. The docs hub renders the CLI reference through Astro's markdown compiler, which
 * passes the comment through, and the page's own `escapeRawHtml` — the helper that shows a
 * reader any tag-shaped token the renderer did not emit as the text it was written as —
 * turned the banner into the line `<!-- generated by go run ./ee/clidoc; do not edit -->`
 * above the reference's title. A comment **node** is not text (`textOf`), so a page that
 * keeps the banner as a comment is fine and is what the fixture below shows; what this
 * refuses is the banner a reader can read.
 */
const BANNER = '<!-- generated by'

/**
 * The built pages that show a generated-file banner as text, as failure lines. It is the same
 * defect class as the phrases above — the page telling a reader about its own build — in the
 * one form a phrase list cannot hold, because the words belong to whichever generator wrote
 * the file.
 */
export function bannerFailures(dist) {
  const out = []
  for (const page of builtPages(dist)) {
    const text = textOf(parse(page.html)).replace(/\s+/g, ' ')
    const at = text.toLowerCase().indexOf(BANNER)
    if (at === -1) continue
    const around = text.slice(Math.max(0, at - 50), at + 80).trim()
    out.push(
      `${page.rel} shows a generated file's banner as text: "…${around}…". The banner is the build's note to itself — ` +
        "the content pipeline reads it as a fact and drops it from the body it renders — and a page that prints it is telling a reader about its own build (RF8, D186).",
    )
  }
  return out
}

// ---- the gate --------------------------------------------------------------------------

test('no built page explains why its own text exists', () => {
  const failures = metaFailures(DIST)
  assert.deepEqual(failures, [], `the built site carries provenance text:\n  ${failures.join('\n  ')}`)
})

test('no built page shows a generated file’s banner as text', () => {
  const failures = bannerFailures(DIST)
  assert.deepEqual(failures, [], `the built site prints a generated-file banner:\n  ${failures.join('\n  ')}`)
})

// ---- the refusals, kept ----------------------------------------------------------------

const shell = (body) => `<!DOCTYPE html><html lang="en"><head><title>t</title></head><body><main>${body}</main></body></html>`

function distOf(t, files) {
  const dist = mkdtempSync(path.join(tmpdir(), 'fugaro-meta-'))
  t.after(() => rmSync(dist, { recursive: true, force: true }))
  for (const [rel, body] of Object.entries(files)) {
    mkdirSync(path.dirname(path.join(dist, rel)), { recursive: true })
    writeFileSync(path.join(dist, rel), body)
  }
  return dist
}

test('every phrase in D186’s list is refused, wherever on a page it is', (t) => {
  // One page per phrase, and the whole list is walked: a phrase silently dropped from
  // `PHRASES` shows up here as a page that should have failed and did not.
  const files = {}
  for (const [i, phrase] of PHRASES.entries()) {
    files[`p${i}/index.html`] = shell(`<h1>Page ${i}</h1><p>This page's text is ${phrase} a file in this repository.</p>`)
  }
  const failures = metaFailures(distOf(t, files))
  assert.equal(failures.length, PHRASES.length, `the gate reported ${failures.length} failures for ${PHRASES.length} phrases:\n${failures.join('\n')}`)
  for (const [i, phrase] of PHRASES.entries()) {
    assert.ok(
      failures.some((line) => line.startsWith(`p${i}/index.html `) && line.includes(JSON.stringify(phrase))),
      `a page carrying ${JSON.stringify(phrase)} was not refused:\n${failures.join('\n')}`,
    )
  }
})

test('a phrase is refused through its capitalization and its line breaks', (t) => {
  // A reader does not see the source's line breaks or its sentence case: a phrase is
  // refused as the reader reads it, and the title is text a reader reads too.
  const files = {
    'case/index.html': shell('<h1>Rendered\n     From</h1><p>the file</p>'),
    'title/index.html': `<!DOCTYPE html><html lang="en"><head><title>nothing here is typed</title></head><body><main><h1>t</h1></main></body></html>`,
    'script/index.html': shell('<h1>t</h1><script>const s = "rendered from"</script><style>/* rendered from */</style><p>the commands</p>'),
  }
  const failures = metaFailures(distOf(t, files))
  assert.equal(failures.length, 2, failures.join('\n'))
  assert.ok(failures.some((line) => line.startsWith('case/index.html ')), failures.join('\n'))
  assert.ok(failures.some((line) => line.startsWith('title/index.html ')), failures.join('\n'))
  assert.ok(
    !failures.some((line) => line.startsWith('script/index.html ')),
    'a script or style body is not text a reader reads, and the gate read one anyway',
  )
})

test('an escaped banner is refused and a comment node is not', (t) => {
  // The two shapes are one character apart in the source and complete opposites to a reader:
  // `&lt;!-- … --&gt;` is a line of text on the page, and `<!-- … -->` is a note in the
  // document that no browser shows. The gate reads the first and ignores the second, which is
  // why the docs hub's reference may keep its banner in the markup and may not print it.
  const files = {
    'escaped/index.html': shell('<h1>Reference</h1><p>&lt;!-- generated by go run ./ee/clidoc; do not edit --&gt;</p>'),
    'comment/index.html': shell('<h1>Reference</h1><!-- generated by go run ./ee/clidoc; do not edit --><p>the commands</p>'),
  }
  const failures = bannerFailures(distOf(t, files))
  assert.equal(failures.length, 1, failures.join('\n'))
  assert.ok(failures[0].startsWith('escaped/index.html '), failures.join('\n'))
})

test('a page that says what it is for, and cites a document, is not refused', (t) => {
  // The control: naming a document is not provenance text. The docs hub names the file each
  // guide lives in, a page links to SECURITY.md, and the changelog renders the release
  // files' own lines — D186 chose the phrase list precisely so none of those misfires.
  const files = {
    'hub/index.html': shell(
      '<h1>Docs</h1><p>Every guide lives in a file in this repository: the CLI reference is <code>website/content/cli-reference.md</code>.</p>' +
        '<p>Report a vulnerability as <a href="/security/">SECURITY.md</a> describes.</p>',
    ),
    'release/index.html': shell('<h1>v1.2.3</h1><p>A line of the release notes, as the file writes it.</p>'),
  }
  assert.deepEqual(metaFailures(distOf(t, files)), [])
})
